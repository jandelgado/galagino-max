static uint32_t fnv1a(const char *s) {
  uint32_t h = 0x811C9DC5;
  for (; *s; s++) {
    h = (h ^ (uint8_t)*s) * 0x01000193;
  }
  return h;
}

static void put32(std::vector<uint8_t> &b, uint32_t at, uint32_t v) {
  for (uint32_t i = 0; i < 4; i++) {
    b[at + i] = (uint8_t)(v >> (8 * i));
  }
}

static const uint32_t ID_A = 0x1111;
static const uint32_t ID_B = 0x2222;

// header + 2 entries, data "_a" 3 bytes at 48, "_b" 8 bytes at 52
static std::vector<uint8_t> twoEntries() {
  std::vector<uint8_t> b(60, 0);
  put32(b, 0, 0x42474C47);
  b[4] = 1;  // version
  b[6] = 2;  // count
  const uint32_t e0[5] = {ID_A, 48, 3, 3, 0};
  const uint32_t e1[5] = {ID_B, 52, 8, 8, 0};
  for (uint32_t i = 0; i < 5; i++) {
    put32(b, 8 + 4 * i, e0[i]);
    put32(b, 28 + 4 * i, e1[i]);
  }
  b[48] = 1; b[49] = 2; b[50] = 3;
  memset(&b[52], 4, 8);
  return b;
}

static void test_find_entries(void) {
  std::vector<uint8_t> b = twoEntries();
  TEST_ASSERT_TRUE(Bundle::mount(b.data(), b.size()));
  TEST_ASSERT_EQUAL_PTR(b.data() + 48, Bundle::find(ID_A, 3));
  TEST_ASSERT_EQUAL_PTR(b.data() + 52, Bundle::find(ID_B, 8));
}

static void test_missing_and_length_mismatch(void) {
  std::vector<uint8_t> b = twoEntries();
  TEST_ASSERT_TRUE(Bundle::mount(b.data(), b.size()));
  TEST_ASSERT_NULL(Bundle::find(0x3333, 3));
  TEST_ASSERT_NULL(Bundle::find(ID_A, 4));
}

static void expectRejected(std::vector<uint8_t> b, uint32_t length) {
  TEST_ASSERT_FALSE(Bundle::mount(b.data(), length));
  TEST_ASSERT_NULL(Bundle::find(ID_A, 3));
}

static void test_reject_invalid(void) {
  std::vector<uint8_t> b = twoEntries();
  TEST_ASSERT_TRUE(Bundle::mount(b.data(), b.size()));  // stays mounted only if valid

  std::vector<uint8_t> bad = twoEntries();
  bad[0] ^= 1;
  expectRejected(bad, bad.size());                       // magic

  bad = twoEntries();
  bad[4] = 2;
  expectRejected(bad, bad.size());                       // version

  expectRejected(twoEntries(), 40);                      // entry table past length

  expectRejected(twoEntries(), 59);                      // entry data past length

  bad = twoEntries();
  put32(bad, 8 + 4, 49);
  expectRejected(bad, bad.size());                       // unaligned offset

  bad = twoEntries();
  put32(bad, 28 + 16, 1);
  expectRejected(bad, bad.size());                       // flags

  bad = twoEntries();
  put32(bad, 28 + 8, 7);
  expectRejected(bad, bad.size());                       // stored != raw (raw only)
}

static void test_unmount(void) {
  std::vector<uint8_t> b = twoEntries();
  TEST_ASSERT_TRUE(Bundle::mount(b.data(), b.size()));
  Bundle::unmount();
  TEST_ASSERT_NULL(Bundle::find(ID_A, 3));
}

