static std::vector<uint8_t> readBundleFile() {
  std::string path = __FILE__;
  path = path.substr(0, path.rfind('/')) + "/../../../galagino-server/data/g/";
  char hex[17];
  for (uint32_t i = 0; i < 8; i++) {
    snprintf(hex + 2 * i, 3, "%02x", _1943_bundle.hash[i]);
  }
  path += hex;

  std::vector<uint8_t> b;
  FILE *f = fopen(path.c_str(), "rb");
  TEST_ASSERT_NOT_NULL_MESSAGE(f, path.c_str());
  uint8_t chunk[4096];
  size_t n;
  while ((n = fread(chunk, 1, sizeof(chunk), f)) > 0) {
    b.insert(b.end(), chunk, chunk + n);
  }
  fclose(f);
  return b;
}

static void expectAsset(const char *name, const void *builtIn, uint32_t bytes) {
  const void *p = Bundle::find(fnv1a(name), bytes);
  TEST_ASSERT_NOT_NULL_MESSAGE(p, name);
  TEST_ASSERT_EQUAL_MEMORY_MESSAGE(builtIn, p, bytes, name);
}

static void test_real_1943_bundle(void) {
  std::vector<uint8_t> b = readBundleFile();
  TEST_ASSERT_EQUAL_UINT32(_1943_bundle.length, b.size());
  TEST_ASSERT_TRUE(Bundle::mount(b.data(), b.size()));
  expectAsset("_1943_rom", _1943_rom_data, sizeof(_1943_rom_data));
  expectAsset("_1943_sound", _1943_sound_data, sizeof(_1943_sound_data));
  expectAsset("_1943_bg1", _1943_bg1_data, sizeof(_1943_bg1_data));
  expectAsset("_1943_sprites", _1943_sprites_data, sizeof(_1943_sprites_data));
}
