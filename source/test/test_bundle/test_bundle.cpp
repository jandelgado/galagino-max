static std::vector<uint8_t> readBundleFile() {
  std::string path = __FILE__;
  path = path.substr(0, path.rfind('/')) + "/../../../galagino-server/data/g/";
  char hex[17];
  for (uint32_t i = 0; i < 8; i++) {
    snprintf(hex + 2 * i, 3, "%02x", _1943_bundle.hash[i]);
  }
  path += hex;

  std::vector<uint8_t> b;
  FILE *f = fopen(path.c_str(), "rb");
  TEST_ASSERT_NOT_NULL_MESSAGE(f, path.c_str());
  uint8_t chunk[4096];
  size_t n;
  while ((n = fread(chunk, 1, sizeof(chunk), f)) > 0) {
    b.insert(b.end(), chunk, chunk + n);
  }
  fclose(f);
  return b;
}

static bool toVector(void *ctx, const uint8_t *data, uint32_t length) {
  std::vector<uint8_t> *v = (std::vector<uint8_t> *)ctx;
  v->insert(v->end(), data, data + length);
  return true;
}

static void *heapAlloc(ISzAllocPtr, size_t size) { return malloc(size); }
static void heapFree(ISzAllocPtr, void *p) { free(p); }
static const ISzAlloc heap = {heapAlloc, heapFree};
static uint8_t dict[BundleUnpacker::PLAIN_DICT_BYTES];

static void expectAsset(const char *name, uint32_t flags, const void *builtIn, uint32_t bytes) {
  const void *p = Bundle::find(fnv1a(name), flags);
  TEST_ASSERT_NOT_NULL_MESSAGE(p, name);
  TEST_ASSERT_EQUAL_MEMORY_MESSAGE(builtIn, p, bytes, name);
}

static void test_real_1943_bundle(void) {
  std::vector<uint8_t> wire = readBundleFile();
  TEST_ASSERT_EQUAL_UINT32(_1943_bundle.wireLength, wire.size());

  std::vector<uint8_t> entry;
  BundleUnpacker u(toVector, &entry, dict, &heap);
  TEST_ASSERT_TRUE(u.feed(wire.data(), wire.size()));
  TEST_ASSERT_TRUE(u.finished());
  TEST_ASSERT_EQUAL_UINT32(_1943_bundle.entryLength, entry.size());

  TEST_ASSERT_TRUE(Bundle::mount(entry.data(), entry.size()));
  expectAsset("_1943_rom", Bundle::FLAG_RAW, _1943_rom_data, sizeof(_1943_rom_data));
  expectAsset("_1943_sound", Bundle::FLAG_RAW, _1943_sound_data, sizeof(_1943_sound_data));
  expectAsset("_1943_bg1", Bundle::FLAG_RAW, _1943_bg1_data, sizeof(_1943_bg1_data));
  expectAsset("_1943_sprites", Bundle::FLAG_RAW, _1943_sprites_data, sizeof(_1943_sprites_data));
  expectAsset("_1943_chars", Bundle::FLAG_PACKED, _1943_chars_packed, sizeof(_1943_chars_packed));
}
