#!/usr/bin/env python3
# Writes mame_mhavoc_frames.h from MAME mhavoc captures: per frame the alpha
# VRAM (0x4000-0x4fff) + color RAM (0x1400-0x141f) dump (fix_NNNNN.bin, 4128
# bytes) and the snapshot PNG of the same frame_done, reduced to a lit mask
# on the panel (bwidow_layout mapping of mhavoc_layout::SCREEN).
# Usage: make_fixture.py out.h frame:dump.bin:snap.png ...
import sys
from PIL import Image

SCALE, TOP, ROWS, COLS = 819, 40, 208, 240
VIS_W, VIS_H = 301, 261  # MAME visarea 0..300 x 0..260

out = open(sys.argv[1], "w", newline="\n")
out.write("// Generated by make_fixture.py from MAME mhavoc captures; reference data, keep tracked.\n")
out.write("#include <stdint.h>\n\n")
names = []
for arg in sys.argv[2:]:
    frame, dump, snap = arg.split(":")
    data = open(dump, "rb").read()
    assert len(data) == 0x1020
    im = Image.open(snap).convert("RGB")
    w, h = im.size
    px = im.load()
    lit = [[max(px[x, y]) > 40 for x in range(w)] for y in range(h)]
    mask = bytearray(ROWS * COLS // 8)
    for r in range(ROWS):
        y0, y1 = r * 1024 / SCALE, (r + 1) * 1024 / SCALE
        sy0, sy1 = int(y0 * h / VIS_H), max(int(y0 * h / VIS_H) + 1, int(y1 * h / VIS_H))
        for c in range(COLS):
            x0, x1 = c * 1024 / SCALE, (c + 1) * 1024 / SCALE
            sx0, sx1 = int(x0 * w / VIS_W), max(int(x0 * w / VIS_W) + 1, int(x1 * w / VIS_W))
            if any(lit[y][x] for y in range(sy0, min(sy1, h)) for x in range(sx0, min(sx1, w))):
                mask[(r * COLS + c) // 8] |= 1 << (c & 7)
    name = f"mame_frame_{int(frame)}"
    names.append(name)
    out.write(f"static const uint8_t {name}_ram[{len(data)}] = {{\n")
    for i in range(0, len(data), 24):
        out.write("  " + ", ".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",\n")
    out.write("};\n")
    out.write(f"static const uint8_t {name}_mask[{len(mask)}] = {{\n")
    for i in range(0, len(mask), 30):
        out.write("  " + ", ".join(f"0x{b:02x}" for b in mask[i:i + 30]) + ",\n")
    out.write("};\n\n")
out.write("struct MameFrame { uint32_t frame; const uint8_t *ram, *mask; };\n")
out.write("static const MameFrame mame_frames[] = {\n")
for n in names:
    out.write(f"  {{{n.split('_')[-1]}, {n}_ram, {n}_mask}},\n")
out.write("};\n")
