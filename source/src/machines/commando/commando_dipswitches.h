#ifndef COMMANDO_DIPSWITCHES_H
#define COMMANDO_DIPSWITCHES_H

// Raw port values as read by the CPU (MAME commando.cpp INPUT_PORTS)

// DSW1
#define COMMANDO_DIP_AREA_0       0b00000011 // starting area: forest 1
#define COMMANDO_DIP_LIVES_3      0b00001100
#define COMMANDO_DIP_COIN_B_1C1C  0b00110000
#define COMMANDO_DIP_COIN_A_1C1C  0b11000000

#define COMMANDO_DIP_A (COMMANDO_DIP_AREA_0 | COMMANDO_DIP_LIVES_3 | \
                        COMMANDO_DIP_COIN_B_1C1C | COMMANDO_DIP_COIN_A_1C1C)

// DSW2
#define COMMANDO_DIP_BONUS_10K_50K 0b00000111
#define COMMANDO_DIP_DEMO_SOUNDS   0b00001000
#define COMMANDO_DIP_NORMAL        0b00010000 // difficulty
#define COMMANDO_DIP_NO_FLIP       0b00000000
#define COMMANDO_DIP_UPRIGHT       0b00000000

#define COMMANDO_DIP_B (COMMANDO_DIP_BONUS_10K_50K | COMMANDO_DIP_DEMO_SOUNDS | \
                        COMMANDO_DIP_NORMAL | COMMANDO_DIP_NO_FLIP | COMMANDO_DIP_UPRIGHT)

#endif
