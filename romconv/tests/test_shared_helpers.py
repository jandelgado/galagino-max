import hashlib

import pytest

from romconv.core.context import Context
from romconv.core.errors import ConversionError
from romconv.core.job import Job
from romconv.emit.write import banner, write_array, write_asset, write_bytes, write_color_tables
from romconv.gfx import gfxutil
from romconv.gfx.rom import rom_bytes, rom_bytes_all
from romconv.hw import snk6502
from romconv.plan.budget import check_budget, log_sizes

JOB = Job(name="g", convert=lambda c: None, machine="g", zips=("g.zip",))


@pytest.fixture
def ctx(paths, log):
    return Context(JOB, paths, (), log)


def _text(paths, name):
    return (paths.machines / "g" / name).read_text()


def test_write_bytes_header_and_size(ctx, paths):
    assert write_bytes(ctx, "a.h", "sym", b"\x01\x02\x03", "comment", "g") == 3
    text = _text(paths, "a.h")
    assert text.startswith(banner("g") + "// comment\n")
    assert "sym" in text
    assert write_bytes(ctx, "b.h", "sym", [1, 2], None, ctype="unsigned short") == 4
    assert not _text(paths, "b.h").startswith("//")  # neither banner nor comment


def test_write_array_and_asset(ctx, paths):
    assert write_array(ctx, "c.h", "w", "uint32_t", "[2]", 2, [1, 2, 3, 4], "words") == 16
    assert write_asset(ctx, "d.h", "c", lambda f: f.write("x\n") and 7, "g") == 7
    assert _text(paths, "d.h") == banner("g") + "// c\nx\n"


def test_banner_names_the_old_script():
    assert banner("zaxxon") == "// Generated by romconv/internal/zaxxon/zaxxon_rom_convert.py; do not edit.\n"


def test_write_color_tables(ctx, paths):
    pal = list(range(32))
    clut = [0] * 256
    clut[1] = 5

    def emit(f):
        write_color_tables(f, "t", pal, clut, 0x10, " PROGMEM")

    write_asset(ctx, "e.h", None, emit)
    text = _text(paths, "e.h")
    assert text.startswith("const unsigned short t_cmap[16][16] PROGMEM = {\n  { 0x0010, 0x0015,")
    assert "const unsigned short t_transp[16] PROGMEM = { 0xfffd," in text


def test_rom_bytes(paths, make_zip, ctx):
    data = b"abc"
    make_zip("g.zip", {"x": data, "y": b"de"})
    sha = hashlib.sha1(data).hexdigest()
    assert rom_bytes(ctx, ("x", sha)) == data
    assert rom_bytes(ctx, (("nope", "x"), sha)) == data
    assert rom_bytes_all(ctx, [("x", None), ("y", None)]) == b"abcde"
    with pytest.raises(ConversionError, match="SHA-1 mismatch"):
        rom_bytes(ctx, ("y", sha))


def test_budget_helpers(ctx):
    check_budget(ctx, 181999)
    with pytest.raises(ConversionError, match="Arena budget"):
        check_budget(ctx, 182000)
    log_sizes(ctx, {"a": 1, "b": 2}, 4)
    with pytest.raises(ConversionError, match="3 >= 3"):
        log_sizes(ctx, {"a": 1, "b": 2}, 3)


def test_gfxutil_packing():
    assert gfxutil.step(1, 3, 3) == [1, 4, 7]
    assert gfxutil.pack_pens([1, 2, 3], 4) == 0x321
    assert gfxutil.pack_nibbles([1, 2, 3]) == 0x123
    tile = [[(x == 2) * (y + 1) for x in range(8)] for y in range(8)]
    assert gfxutil.column_words([tile], 4)[2] == gfxutil.pack_pens(range(1, 9), 4)
    assert gfxutil.column_words([tile], 4)[0] == 0
    sprite = [[x for x in range(16)] for _ in range(16)]
    rows = gfxutil.pack_sprite_rows([sprite])
    assert len(rows) == 32 and rows[0] == 0x01234567 and rows[1] == 0x89ABCDEF
    assert gfxutil.pack_pairs([sprite])[:2] == [0x10, 0x32] and len(gfxutil.pack_pairs([sprite])) == 128


def test_encode_samples_needs_the_pack(ctx):
    with pytest.raises(ConversionError, match="missing Test sample pack"):
        snk6502.encode_samples(ctx, "t.zip", "Test", ["a.wav"], [6000])
