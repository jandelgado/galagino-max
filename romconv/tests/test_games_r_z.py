def test_btime_family_decoding():
    region = bytes(0x6000)
    chars, char_count = btime.decode_chars(region)
    tiles, tile_count = btime.decode_tiles16(region)
    assert (char_count, len(chars[0]), len(chars[0][0])) == (1024, 8, 8)
    assert (tile_count, len(tiles[0])) == (256, 16)
    assert btime._planes3(24) == [16, 8, 0]
    bits = bytearray(0x6000)
    bits[0] = 0x80   # last plane (LSB), pixel (0, 0): rotated to chars[0][0][7]
    rotated, _ = btime.decode_chars(bits)
    assert rotated[0][0][7] == 1


