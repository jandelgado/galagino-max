def test_roadfighter_decoding_and_palette():
    rom = bytearray(0xC000)
    rom[0] = 0x80          # pixel (0,0): bit 7 of the low half = plane 0
    assert roadfighter._decode_konami_tile(rom, 0)[0][0] == 1
    rom[0x6000] = 0x80     # high half plane -> bit 2
    assert roadfighter._decode_konami_tile(rom, 0)[0][0] == 5
    assert roadfighter._pack8([1, 2, 3, 4, 5, 6, 7, 8]) == 0x87654321
    pal = roadfighter._build_palette(bytes(32))
    assert len(pal) == 32 and pal[0] == 0
    assert roadfighter._boost_rgb(0, 0, 0) == (0, 0, 0)
    assert roadfighter._boost_rgb(255, 255, 255) == (255, 255, 255)
    spr = roadfighter._decode_konami_sprite(bytearray(0x8000), 0)
    assert len(spr) == 16 and len(spr[0]) == 16


