def test_vulgus_line_packing():
    tile = [[(x + y) & 15 for x in range(16)] for y in range(16)]
    words = vulgus._lines16([tile])
    assert len(words) == 32
    assert words[0] == sum(tile[k][0] << (4 * k) for k in range(8))


