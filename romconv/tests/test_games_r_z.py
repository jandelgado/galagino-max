def test_snk6502_read_sample_resamples_and_rejects_8bit_garbage(tmp_path):
    import zipfile
    path = tmp_path / "s.zip"
    with zipfile.ZipFile(path, "w") as z:
        z.writestr("a.wav", _wav(12000, np.arange(1200) % 100))
    with zipfile.ZipFile(path) as z:
        out = snk6502.read_sample(z, "a.wav", 6000, "s.zip")
    assert len(out) == 600 and out.dtype == np.int8
