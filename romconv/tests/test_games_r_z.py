def test_rocnrope_helpers():
    pal = rocnrope._build_base_palette(bytes([0xff] + [0] * 31))
    assert pal[0] == rgb565_swapped(0x1D + 0x3E + 0x85, 0x1D + 0x3E + 0x85, 0x48 + 0x99)
    sprite_cmap, tile_cmap = rocnrope._build_colormaps(list(range(32)), bytes(range(256)), bytes(256))
    assert sprite_cmap[1][2] == 18 % 16 and tile_cmap[3][4] == 0
    half0, half1 = bytearray(8192), bytearray(8192)
    half0[0] = 0x80
    assert rocnrope._decode_tile(half0, half1, 0)[0][0] == 1
    half1[0] = 0x80
    assert rocnrope._decode_tile(half0, half1, 0)[0][0] == 5
    assert len(rocnrope._Y_BITS) == 16 and len(rocnrope._X_BITS) == 16


