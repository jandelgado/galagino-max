"""Lockstep reference for test_qbert_boot: SP and CRC32 of the 8088 RAM at every NMI.

ram_fixture.lua dumps SP + 0000-2fff + 3800-3bff (2 + 13312 bytes) per NMI entry. The CRC skips
the dead stack [SP - STALE, SP + 6): the NMI frame (FLAGS, CS, IP) holds where in the 3
instruction wait loop the NMI landed, which depends on cycle timing the interpreter does not
model, and stale copies of it stay below SP. Keep the dumps: on a mismatch, `diff` prints the
differing addresses of one NMI against the host dump.

usage: uv run python -m dev.qbert.ram_fixture <dir with attract/ game1/ game2/ ram.bin> <out.h>
       uv run python -m dev.qbert.ram_fixture diff <mame ram.bin> <host frame.bin> <nmi>
"""
import sys
import zlib

RAM = 0x3000
FRAME = 2 + RAM + 0x400
STALE = 0x40    # bytes below SP left out (masked), C++ test mirrors it
NMI_FRAME = 6   # FLAGS, CS, IP
SCENARIOS = ("attract", "game1", "game2")


def masked(frame: bytes) -> tuple[int, bytes]:
    sp = frame[0] | frame[1] << 8
    ram = bytearray(frame[2:])
    lo, hi = max(sp - STALE, 0), min(sp + NMI_FRAME, RAM)
    ram[lo:hi] = bytes(hi - lo)
    return sp, bytes(ram)


def frames(path: str):
    d = open(path, "rb").read()
    return [d[i:i + FRAME] for i in range(0, len(d) - FRAME + 1, FRAME)]


def array(ctype: str, name: str, values: list[int], digits: int) -> list[str]:
    out = [f"static const {ctype} {name}[{len(values)}] = {{"]
    out += ["  " + ", ".join(f"0x{v:0{digits}x}" for v in values[i:i + 8]) + "," for i in range(0, len(values), 8)]
    return out + ["};"]


def header(root: str, out: str) -> None:
    lines = ["// Generated by romconv/dev/qbert/ram_fixture.py from MAME 0.289 qbert: SP and",
             f"// CRC32 of 8088 RAM 0000-2fff + 3800-3bff at each NMI entry, [SP - 0x{STALE:x},",
             f"// SP + {NMI_FRAME}) zeroed (dead stack, see ram_fixture.py).",
             "#include <stdint.h>", ""]
    for sc in SCENARIOS:
        rows = [masked(f) for f in frames(f"{root}/{sc}/ram.bin")]
        lines += array("uint16_t", f"MAME_SP_{sc.upper()}", [sp for sp, _ in rows], 4)
        lines += array("uint32_t", f"MAME_RAM_{sc.upper()}", [zlib.crc32(r) for _, r in rows], 8)
    open(out, "w").write("\n".join(lines) + "\n")


def diff(mame: str, host: str, nmi: int) -> None:
    sp_a, a = masked(frames(mame)[nmi])
    sp_b, b = masked(open(host, "rb").read())   # one frame, written by test_qbert_boot
    print(f"SP mame {sp_a:04x} host {sp_b:04x}")
    for i, (x, y) in enumerate(zip(a, b)):
        if x != y:
            addr = i if i < RAM else 0x3800 + i - RAM
            print(f"{addr:04x}: mame {x:02x} host {y:02x}")


if __name__ == "__main__":
    if sys.argv[1] == "diff":
        diff(sys.argv[2], sys.argv[3], int(sys.argv[4]))
    else:
        header(sys.argv[1], sys.argv[2])
