"""Turn a sound_fixture.lua capture into source/test/test_qbert_sound/mame_sound.h.

Keeps everything before END cycles (22 s of attract: boot speech, the first sound commands, the
second phrase): commands with their sound CPU cycle, and every DAC / Votrax / speech clock write.

usage: uv run python -m dev.qbert.sound_fixture <snd.txt> <out.h>
"""
import sys

END = 20_000_000
KINDS = {"D": 1, "V": 2, "K": 3}


def main(src: str, out: str) -> None:
    cmds, writes, start = [], [], 0
    for line in open(src):
        kind, cycle, val = line.split()
        cycle = int(cycle)
        if cycle >= END:
            continue
        if kind == "S":
            start = cycle
        elif kind == "C":
            cmds.append((cycle, int(val, 16)))
        else:
            writes.append((cycle, KINDS[kind] << 8 | int(val, 16)))

    def table(name, rows):
        body = ",\n".join("  {%d, 0x%x}" % r for r in rows)
        return [f"static const SoundEvent {name}[{len(rows)}] = {{", body, "};"]

    lines = ["// Generated by romconv/dev/qbert/sound_fixture.py from MAME 0.289 qbert",
             "// (sound_fixture.lua): sound commands and sound board writes, in 6502 cycles.",
             "#include <stdint.h>", "",
             "struct SoundEvent {", "  uint32_t cycle;", "  uint16_t value;   // writes: kind << 8 | byte, kind 1 DAC, 2 Votrax, 3 clock",
             "};", "", f"static const uint32_t MAME_SOUND_START = {start};   // capture begins (frame 1)",
             f"static const uint32_t MAME_SOUND_END = {END};"]
    lines += table("MAME_COMMANDS", cmds) + table("MAME_WRITES", writes)
    open(out, "w").write("\n".join(lines) + "\n")
    print(f"{out}: {len(cmds)} commands, {len(writes)} writes")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
