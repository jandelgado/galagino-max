"""Turn a video_fixture.lua capture into source/test/test_qbert_video/mame_frames.h.

Each frame: MAME's render input (video RAM, sprite RAM, palette, 0x5803 latch) and the CRC32 of
every snapshot line as RGB565 (byte swapped, as the panel takes it). Snapshots are already turned
to the player view, 240 x 256: snapshot line y is panel line y + 16.

usage: uv run python -m dev.qbert.video_fixture <capture dir> <out.h>
"""
import sys
import zlib
from pathlib import Path

from PIL import Image

from romconv.gfx.color import rgb565_swapped

WIDTH, HEIGHT = 240, 256
PLAY_EVERY = 6   # of the play frames (every 20th frame), keep every 6th; all priority frames


def line_crcs(png: Path) -> list[int]:
    im = Image.open(png).convert("RGB")
    assert im.size == (WIDTH, HEIGHT), im.size
    px = im.load()
    return [zlib.crc32(b"".join(rgb565_swapped(*px[x, y]).to_bytes(2, "little") for x in range(WIDTH)))
            for y in range(HEIGHT)]


def hexbytes(s: str) -> str:
    return ",".join(f"0x{s[i:i + 2]}" for i in range(0, len(s), 2))


def main(cap: Path, out: Path) -> None:
    rows = [line.split() for line in open(cap / "state.txt")]
    snaps = sorted((cap / "snap" / "qbert").glob("*.png"))
    assert len(snaps) == len(rows), (len(snaps), len(rows))
    play = [k for k, r in enumerate(rows) if r[1] == "00"]
    keep = play[::PLAY_EVERY] + [k for k, r in enumerate(rows) if r[1] != "00"]

    lines = ["// Generated by romconv/dev/qbert/video_fixture.py from MAME 0.289 qbert",
             "// (video_fixture.lua): render input and snapshot line CRCs per frame.",
             "#include <stdint.h>", "",
             "struct MameFrame {", "  int frame;", "  uint8_t ctrl;", "  uint8_t vram[0x400];",
             "  uint8_t spr[0x100];", "  uint8_t pal[0x20];", f"  uint32_t line_crc[{HEIGHT}];", "};", "",
             "static const MameFrame MAME_FRAMES[] = {"]
    for k in keep:
        f, ctrl, vram, spr, pal = rows[k]
        crcs = ",".join(f"0x{c:08x}" for c in line_crcs(snaps[k]))
        lines.append(f"  {{{f}, 0x{ctrl}, {{{hexbytes(vram)}}},\n   {{{hexbytes(spr)}}},\n"
                     f"   {{{hexbytes(pal)}}},\n   {{{crcs}}}}},")
    lines.append("};")
    out.write_text("\n".join(lines) + "\n")
    print(f"{out}: {len(keep)} frames")


if __name__ == "__main__":
    main(Path(sys.argv[1]), Path(sys.argv[2]))
