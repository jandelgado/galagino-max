#!/usr/bin/env python3
"""Turn a mame_ref.lua capture (ram_trace.txt + snapshots) into the host
test fixture source/test/test_docastle_video/mame_frames.h.

usage: uv run python -m dev.docastle.mame_fixture <capture dir> <out.h> <frame> ...
       uv run python -m dev.docastle.mame_fixture <capture dir> --overlaps
Snapshot N in <capture dir>/snap/docastle is frame FIRST + STEP * N (300, 10).
Tiles and sprites from <frame>. --overlaps lists snapshot frames with
overlapping sprites."""
import sys
import zlib
from pathlib import Path

from PIL import Image

FIRST, STEP = 300, 10
SPRITE_BYTES = 0x200


def rgb565_swapped(r, g, b):
    v = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
    return ((v & 0xff) << 8) | (v >> 8)


def load(capture):
    rows = {}
    for line in open(capture / "ram_trace.txt"):
        f, spr, vid = line.split()
        rows[int(f)] = (bytes.fromhex(spr), bytes.fromhex(vid))
    return rows


def boxes(spr):
    out = []
    for offs in range(0, SPRITE_BYTES, 4):
        sy = spr[offs] - 32
        sx = ((spr[offs + 1] + 8) & 0xff) - 8
        if -16 < sy < 192:
            out.append((sx, sy))
    return out


def overlaps(rows):
    for f in range(FIRST + STEP, max(rows) + 1, STEP):
        b = boxes(rows[f][0])
        n = sum(1 for i in range(len(b)) for j in range(i + 1, len(b))
                if abs(b[i][0] - b[j][0]) < 16 and abs(b[i][1] - b[j][1]) < 16)
        if n:
            print(f, n)


def line_crcs(png):
    im = Image.open(png).convert("RGB")
    assert im.size == (192, 240), im.size
    crcs = []
    for y in range(240):
        line = b"".join(rgb565_swapped(*im.getpixel((x, y))).to_bytes(2, "little") for x in range(192))
        crcs.append(zlib.crc32(line))
    return crcs


def main(capture, out, frames):
    rows = load(capture)
    with open(out, "w", newline="\n") as f:
        f.write("// Generated by romconv/dev/docastle/mame_fixture.py from MAME 0.289 docastle\n")
        f.write("// (dev/docastle/mame_ref.lua): video + color RAM b000-b7ff and sprite RAM\n")
        f.write("// of frame F, CRC32 of the 240 snapshot lines (192 RGB565\n")
        f.write("// byte-swapped pixels each).\n#include <stdint.h>\n\n")
        f.write("struct MameFrame {\n  uint32_t frame;\n  uint8_t video[0x800];\n  uint8_t sprites[0x200];\n")
        f.write("  uint32_t line_crc[240];\n};\n\n")
        f.write(f"static const MameFrame mame_frames[{len(frames)}] = {{\n")
        for fr in frames:
            png = capture / "snap" / "docastle" / f"{(fr - FIRST) // STEP:04d}.png"
            f.write(f"  {{{fr},\n   {{" + ",".join(str(b) for b in rows[fr][1]) + "},\n")
            f.write("   {" + ",".join(str(b) for b in rows[fr][0]) + "},\n")
            f.write("   {" + ",".join(f"0x{c:08x}" for c in line_crcs(png)) + "}},\n")
        f.write("};\n")


if __name__ == "__main__":
    cap = Path(sys.argv[1])
    if sys.argv[2] == "--overlaps":
        overlaps(load(cap))
    else:
        main(cap, sys.argv[2], [int(a) for a in sys.argv[3:]])
