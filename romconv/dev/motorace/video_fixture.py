"""Turn a video_fixture.lua capture into source/test/test_motorace_video/mame_frames.h.

Each frame: MAME's render input (video RAM, sprite RAM, scroll) and the CRC32 of every snapshot
line as RGB565 (byte swapped, as the panel takes it). Snapshots are 256 x 240 (after ROT270); the
panel shows x 16-255 (the left road shoulder is cropped, the HUD stays): snapshot line y is
panel line y + 24.

usage: uv run python -m dev.motorace.video_fixture <capture dir> <out.h>
"""
import sys
import zlib
from pathlib import Path

from PIL import Image

from romconv.gfx.color import rgb565_swapped

_SNAP_W, _CROP_X, _HEIGHT = 256, 16, 240
# title, attract, play, tunnel tiles (colour 15) in front of sprites
_FRAMES = (100, 500, 1100, 1300, 1500, 1900, 2100, 2500, 2600, 3000, 3100, 3220, 3500, 4100,
           5000, 5900)


def _line_crcs(png: Path) -> list[int]:
    im = Image.open(png).convert("RGB")
    assert im.size == (_SNAP_W, _HEIGHT), im.size
    px = im.load()
    return [zlib.crc32(b"".join(rgb565_swapped(*px[x, y]).to_bytes(2, "little")
                                for x in range(_CROP_X, _SNAP_W)))
            for y in range(_HEIGHT)]


def _hexbytes(s: str) -> str:
    return ",".join(f"0x{s[i:i + 2]}" for i in range(0, len(s), 2))


def _main(cap: Path, out: Path) -> None:
    rows = [line.split() for line in open(cap / "state.txt")]
    snaps = sorted((cap / "snap" / "motorace").glob("*.png"))
    assert len(snaps) == len(rows), (len(snaps), len(rows))

    lines = ["// Generated by romconv/dev/motorace/video_fixture.py from MAME 0.289 motorace",
             "// (video_fixture.lua): render input and snapshot line CRCs per frame.",
             "#include <stdint.h>", "",
             "struct MameFrame {", "  int frame;", "  uint16_t scroll;", "  uint8_t vram[0x1000];",
             "  uint8_t spr[0x200];", f"  uint32_t line_crc[{_HEIGHT}];", "};", "",
             "static const MameFrame MAME_FRAMES[] = {"]
    kept = [k for k, row in enumerate(rows) if int(row[0]) in _FRAMES]
    for k in kept:
        f, scroll, vram, spr = rows[k]
        crcs = ",".join(f"0x{c:08x}" for c in _line_crcs(snaps[k]))
        lo, hi = scroll[:2], scroll[2:]
        lines.append(f"  {{{f}, 0x{hi}{lo}, {{{_hexbytes(vram)}}},\n   {{{_hexbytes(spr)}}},\n"
                     f"   {{{crcs}}}}},")
    lines.append("};")
    out.write_text("\n".join(lines) + "\n")
    print(f"{out}: {len(kept)} frames")


if __name__ == "__main__":
    _main(Path(sys.argv[1]), Path(sys.argv[2]))
