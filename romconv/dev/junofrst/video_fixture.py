"""Turn a video_fixture.lua capture into source/test/test_junofrst_video/mame_frames.h.

Each frame: the bitmap (run-length coded, (count, byte) pairs, count <= 255), the palette and the
CRC32 of every snapshot line as RGB565 (byte swapped, as the panel takes it). Snapshots are the
player view 224 x 768: each native pixel is 3 lines tall (GALAXIAN_XSCALE), so line 3 * k is panel
line k + 16.

usage: uv run python -m dev.junofrst.video_fixture <capture dir> <out.h>
"""
import sys
import zlib
from pathlib import Path

from PIL import Image

from romconv.gfx.color import rgb565_swapped

WIDTH, HEIGHT, XSCALE = 224, 256, 3


def line_crcs(png: Path) -> list[int]:
    im = Image.open(png).convert("RGB")
    assert im.size == (WIDTH, HEIGHT * XSCALE), im.size
    px = im.load()
    return [zlib.crc32(b"".join(rgb565_swapped(*px[x, y * XSCALE]).to_bytes(2, "little")
                                for x in range(WIDTH)))
            for y in range(HEIGHT)]


def rle(data: bytes) -> list[int]:
    out, i = [], 0
    while i < len(data):
        n = 1
        while i + n < len(data) and n < 255 and data[i + n] == data[i]:
            n += 1
        out += [n, data[i]]
        i += n
    return out


def main(cap: Path, out: Path) -> None:
    rows = [line.split() for line in open(cap / "state.txt")]
    snaps = sorted((cap / "snap" / "junofrst").glob("*.png"))
    assert len(snaps) == len(rows), (len(snaps), len(rows))

    lines = ["// Generated by romconv/dev/junofrst/video_fixture.py from MAME 0.289 junofrst",
             "// (video_fixture.lua): bitmap (RLE), palette and snapshot line CRCs per frame.",
             "#include <stdint.h>", ""]
    for k, (f, vram, pal) in enumerate(rows):
        codes = rle(bytes.fromhex(vram))
        lines.append(f"static const uint8_t VRAM_{k}[] = {{")
        lines += ["  " + ",".join(f"{b}" for b in codes[i:i + 32]) + "," for i in range(0, len(codes), 32)]
        lines.append("};")
    lines += ["", "struct MameFrame {", "  int frame;", "  const uint8_t *vram_rle;", "  uint32_t vram_rle_size;",
              "  uint8_t pal[16];", f"  uint32_t line_crc[{HEIGHT}];", "};", "",
              "static const MameFrame MAME_FRAMES[] = {"]
    for k, (f, vram, pal) in enumerate(rows):
        crcs = ",".join(f"0x{c:08x}" for c in line_crcs(snaps[k]))
        pal_bytes = ",".join(f"0x{b:02x}" for b in bytes.fromhex(pal))
        lines.append(f"  {{{f}, VRAM_{k}, sizeof(VRAM_{k}), {{{pal_bytes}}},\n   {{{crcs}}}}},")
    lines.append("};")
    out.write_text("\n".join(lines) + "\n")
    print(f"{out}: {len(rows)} frames")


if __name__ == "__main__":
    main(Path(sys.argv[1]), Path(sys.argv[2]))
