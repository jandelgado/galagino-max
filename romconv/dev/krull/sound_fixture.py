"""Turn a sound_fixture.lua capture into source/test/test_krull_sound/mame_sound.h.

Keeps everything before END cycles (22 s of attract: boot sound, the first sound commands):
commands with their sound CPU cycle, and the DAC writes compacted to blocks of BLOCK writes
(cycle of the first and last write, CRC32 of the values), ~19000 writes in ~300 blocks.

usage: uv run python -m dev.krull.sound_fixture <snd.txt> <out.h>
"""
import sys
import zlib

END = 20_000_000
BLOCK = 64


def main(src: str, out: str) -> None:
    cmds, writes, start = [], [], 0
    for line in open(src):
        kind, cycle, val = line.split()
        cycle = int(cycle)
        if cycle >= END:
            continue
        if kind == "S":
            start = cycle
        elif kind == "C":
            cmds.append((cycle, int(val, 16)))
        else:
            writes.append((cycle, int(val, 16)))

    blocks = []
    for i in range(0, len(writes), BLOCK):
        part = writes[i:i + BLOCK]
        crc = zlib.crc32(bytes(v for _, v in part))
        blocks.append("  {%d, %d, 0x%08x}" % (part[0][0], part[-1][0], crc))

    lines = ["// Generated by romconv/dev/krull/sound_fixture.py from MAME 0.289 krull",
             "// (sound_fixture.lua): sound commands and DAC writes, in 6502 cycles.",
             "#include <stdint.h>", "",
             "struct SoundCommand {", "  uint32_t cycle;", "  uint8_t value;", "};", "",
             f"// {BLOCK} DAC writes: cycles of the first and last, CRC32 of the values",
             "struct DacBlock {", "  uint32_t first, last, crc;", "};", "",
             f"static const uint32_t MAME_SOUND_START = {start};   // capture begins (frame 1)",
             f"static const uint32_t MAME_SOUND_END = {END};",
             f"static const int MAME_DAC_BLOCK = {BLOCK};",
             f"static const int MAME_DAC_WRITES = {len(writes)};",
             f"static const SoundCommand MAME_COMMANDS[{len(cmds)}] = {{",
             ",\n".join("  {%d, 0x%02x}" % c for c in cmds), "};",
             f"static const DacBlock MAME_DAC[{len(blocks)}] = {{", ",\n".join(blocks), "};"]
    open(out, "w").write("\n".join(lines) + "\n")
    print(f"{out}: {len(cmds)} commands, {len(writes)} writes, {len(blocks)} blocks")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
