"""Lockstep reference for test_krull_boot: SP and CRC32 of the RAM at every NMI.

ram_fixture.lua dumps SP + 0000-0fff + 3800-3bff + 4000-4fff (2 + 9216 bytes) per NMI entry. The
CRC skips the dead stack [SP - STALE, SP + 6): the NMI frame (IP, CS, FLAGS) holds where in the 3
instruction idle loop the NMI landed, which depends on cycle timing the interpreter does not
model, and stale copies of it stay below SP. 0x9e9-0x9ea (idle pass count, written after the
loop) differs by design and is zeroed too. NMIs MAME lands outside the idle loop (1581-1587) are
listed by index: the host test only counts those. On a mismatch, `diff` prints the differing
addresses of one NMI against the host dump.

usage: uv run python -m dev.krull.ram_fixture <dir with attract/ game1/ ram.bin> <out.h>
       uv run python -m dev.krull.ram_fixture diff <mame ram.bin> <host frame.bin> <nmi>
"""
import sys
import zlib

RAM = 0x1000
VRAM = 0x400
FRAME = 2 + RAM + VRAM + 0x1000
STALE = 0x40           # bytes below SP left out (masked), C++ test mirrors it
NMI_FRAME = 6          # IP, CS, FLAGS
IDLE_COUNT = 0x9e9     # 2 bytes, masked
IDLE_LOOP = (0x1581, 0x1587)
SCENARIOS = ("attract", "game1")


def masked(frame: bytes) -> tuple[int, int, bytes]:
    sp = frame[0] | frame[1] << 8
    ram = bytearray(frame[2:])
    ip = ram[sp] | ram[sp + 1] << 8
    lo, hi = max(sp - STALE, 0), min(sp + NMI_FRAME, RAM)
    ram[lo:hi] = bytes(hi - lo)
    ram[IDLE_COUNT:IDLE_COUNT + 2] = bytes(2)
    return sp, ip, bytes(ram)


def frames(path: str):
    d = open(path, "rb").read()
    return [d[i:i + FRAME] for i in range(0, len(d) - FRAME + 1, FRAME)]


def array(ctype: str, name: str, values: list[int], digits: int) -> list[str]:
    out = [f"static const {ctype} {name}[{len(values)}] = {{"]
    out += ["  " + ", ".join(f"0x{v:0{digits}x}" for v in values[i:i + 8]) + "," for i in range(0, len(values), 8)]
    return out + ["};"]


def header(root: str, out: str) -> None:
    lines = ["// Generated by romconv/dev/krull/ram_fixture.py from MAME 0.289 krull: SP and CRC32 of",
             "// 8088 RAM 0000-0fff + 3800-3bff + 4000-4fff at each NMI entry; NMI indices outside the idle loop;",
             f"// [SP - 0x{STALE:x}, SP + {NMI_FRAME}) and 0x{IDLE_COUNT:x}-0x{IDLE_COUNT + 1:x} zeroed"
             " (see ram_fixture.py).",
             "#include <stdint.h>", ""]
    for sc in SCENARIOS:
        rows = [masked(f) for f in frames(f"{root}/{sc}/ram.bin")]
        lines += array("uint16_t", f"MAME_SP_{sc.upper()}", [sp for sp, _, _ in rows], 4)
        lines += array("uint16_t", f"MAME_OUTSIDE_{sc.upper()}",
                       [n for n, (_, ip, _) in enumerate(rows) if not IDLE_LOOP[0] <= ip <= IDLE_LOOP[1]], 4)
        lines += array("uint32_t", f"MAME_RAM_{sc.upper()}", [zlib.crc32(r) for _, _, r in rows], 8)
    open(out, "w").write("\n".join(lines) + "\n")


def diff(mame: str, host: str, nmi: int) -> None:
    sp_a, _, a = masked(frames(mame)[nmi])
    sp_b, _, b = masked(open(host, "rb").read())   # one frame, written by test_krull_boot
    print(f"SP mame {sp_a:04x} host {sp_b:04x}")
    for i, (x, y) in enumerate(zip(a, b)):
        if x != y:
            if i < RAM:
                addr = i
            elif i < RAM + VRAM:
                addr = 0x3800 + i - RAM
            else:
                addr = 0x4000 + i - RAM - VRAM
            print(f"{addr:04x}: mame {x:02x} host {y:02x}")


if __name__ == "__main__":
    if sys.argv[1] == "diff":
        diff(sys.argv[2], sys.argv[3], int(sys.argv[4]))
    else:
        header(sys.argv[1], sys.argv[2])
