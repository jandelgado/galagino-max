#!/usr/bin/env python3
"""MAME tokisens frames -> host test fixture: RAM + CRC32 per panel row.

ROT90 snapshot (224 x 512): row 2x is native half-res x, column 223 - y is
native line y, so snapshot row 2x is galagino panel row x + 16 as is.

Usage: uv run python -m dev.system1.mame_fixture_tokisens <dump dir> <frame>:<snapshot png> ...
The dump dir holds <frame>.txt from mame_fixture_tokisens.lua.
"""
import binascii
import os
import sys

from PIL import Image

from dev.system1.mame_fixture import arr, rgb565_swapped

LINES, NATIVE_WIDTH = 224, 256
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "source",
                   "test", "test_tokisens_video", "mame_tokisens_frames.h")


def row_crcs(png):
    im = Image.open(png).convert("RGB")
    assert im.size == (LINES, 2 * NATIVE_WIDTH), im.size
    return [binascii.crc32(b"".join(rgb565_swapped(*im.getpixel((c, 2 * x)))
                                    for c in range(LINES))) & 0xffffffff
            for x in range(NATIVE_WIDTH)]


def main():
    d, picks = sys.argv[1], sys.argv[2:]
    with open(OUT, "w", newline="\n") as f:
        f.write("// MAME tokisens attract frames: 8 VRAM pages, palette RAM d800-ddff,\n"
                "// sprite RAM d000-d7ff, video mode (PPI port B) of the same frame, CRC32\n"
                "// per panel row (native half-res x) of the ROT90 snapshot (RGB565 swapped).\n"
                "// Generated by romconv/dev/system1/mame_fixture_tokisens.py.\n\n")
        f.write("static const MameFrame MAME_TOKISENS[] = {\n")
        for p in picks:
            frame, png = p.split(":")
            vram, pal, spr, mode = open(os.path.join(d, f"{frame}.txt")).read().split()
            crcs = ",".join(f"0x{c:08x}u" for c in row_crcs(png))
            f.write(f"  {{{frame}, 0x{mode},\n   {arr(vram)},\n   {arr(pal)},\n   {arr(spr)},\n"
                    f"   {{{crcs}}}}},\n")
        f.write("};\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
