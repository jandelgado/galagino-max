#!/usr/bin/env python3
"""MAME System 1 ROT0 frames -> host test fixture: RAM + per-line CRC32 of each
240 px window (x w .. w + 239, w = 0..16) of the snapshot.

Usage: uv run python -m dev.system1.mame_fixture <game> <dump dir> <frame>:<snapshot png> ...
The dump dir holds <frame>.txt from mame_fixture.lua.
"""
import binascii
import os
import struct
import sys

from PIL import Image

OUT_WIDTH, NATIVE_WIDTH, LINES, WINDOWS = 240, 256, 224, 17
TEST_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "source",
                        "test", "test_system1_rot0")


def rgb565_swapped(r, g, b):
    c = ((r & 0xf8) << 8) | ((g & 0xfc) << 3) | (b >> 3)
    return struct.pack("<H", ((c >> 8) | (c << 8)) & 0xffff)


# snapshot is 512 wide: half-res x samples the even 512 position
def window_crcs(png):
    im = Image.open(png).convert("RGB")
    assert im.size == (2 * NATIVE_WIDTH, LINES), im.size
    crcs = []
    for y in range(LINES):
        row = [rgb565_swapped(*im.getpixel((2 * x, y))) for x in range(NATIVE_WIDTH)]
        crcs.append([binascii.crc32(b"".join(row[w:w + OUT_WIDTH])) & 0xffffffff
                     for w in range(WINDOWS)])
    return crcs


def arr(hexstr):
    return "{" + ",".join(f"0x{hexstr[i:i + 2]}" for i in range(0, len(hexstr), 2)) + "}"


def main():
    game, d, picks = sys.argv[1], sys.argv[2], sys.argv[3:]
    out = os.path.join(TEST_DIR, f"mame_{game}.h")
    with open(out, "w", newline="\n") as f:
        f.write(f"// MAME {game} frames: video RAM e000-efff, palette RAM d800-ddff, sprite\n"
                "// RAM d000-d7ff of the same frame, CRC32 per 240 px line of\n"
                "// the snapshot window x w .. w + 239 for w = 0..16 (RGB565 swapped).\n"
                "// Generated by romconv/dev/system1/mame_fixture.py.\n\n")
        f.write(f"static const MameFrame MAME_{game.upper()}[] = {{\n")
        for p in picks:
            frame, png = p.split(":")
            vram, pal, spr = open(os.path.join(d, f"{frame}.txt")).read().split()
            crcs = ",\n    ".join("{" + ",".join(f"0x{c:08x}u" for c in line) + "}"
                                  for line in window_crcs(png))
            f.write(f"  {{{frame},\n   {arr(vram)},\n   {arr(pal)},\n   {arr(spr)},\n"
                    f"   {{{crcs}}}}},\n")
        f.write("};\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
