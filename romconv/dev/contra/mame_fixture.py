#!/usr/bin/env python3
"""Turn a mame_ref.lua capture (ram_trace.txt + snapshots) into the host test
fixture source/test/test_contra_video/mame_frames.h.

usage: uv run python -m dev.contra.mame_fixture <capture dir> <out.h> <frame> ...
Frames are multiples of STEP (snapshot N = frame FIRST + STEP * N, 500, 10);
the trace holds frame F and F - 1 (sprite lists of the frame before)."""
import sys
import zlib
from pathlib import Path

from PIL import Image

FIRST, STEP = 500, 10
WIDTH, HEIGHT = 224, 280
REGIONS = (("palette", 0x0c00, 0x100), ("layer0_2", 0x2000, 0x1000), ("sprites0", 0x3000, 0x1000),
           ("layer1", 0x4000, 0x800), ("sprites1", 0x5000, 0x1000))


def rgb565_swapped(r, g, b):
    v = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
    return ((v & 0xff) << 8) | (v >> 8)


def load(capture):
    rows = {}
    for line in open(capture / "ram_trace.txt"):
        f, ctrl, _written, ram = line.split()
        rows[int(f)] = (bytes.fromhex(ctrl), bytes.fromhex(ram))
    return rows


def line_crcs(png):
    im = Image.open(png).convert("RGB")
    assert im.size == (WIDTH, HEIGHT), im.size
    px = im.load()
    crcs = []
    for y in range(HEIGHT):
        line = b"".join(rgb565_swapped(*px[x, y]).to_bytes(2, "little") for x in range(WIDTH))
        crcs.append(zlib.crc32(line))
    return crcs


def _bytes(data):
    return "{" + ",".join(str(b) for b in data) + "}"


def main(capture, out, frames):
    rows = load(capture)
    with open(out, "w", newline="\n") as f:
        f.write("// Generated by romconv/dev/contra/mame_fixture.py from MAME 0.289 contra\n")
        f.write("// (dev/contra/mame_ref.lua): K007121 control registers and RAM of frame F,\n")
        f.write("// sprite RAM of F - 1, CRC32 of the 280 snapshot lines (224 RGB565\n")
        f.write("// byte-swapped pixels each, ROT90 as on the panel).\n#include <stdint.h>\n\n")
        f.write("struct MameFrame {\n  uint32_t frame;\n  uint8_t ctrl[16];\n")
        for name, _, size in REGIONS:
            f.write(f"  uint8_t {name}[0x{size:x}];\n")
        f.write("  uint8_t prev_sprites0[0x1000];\n  uint8_t prev_sprites1[0x1000];\n")
        f.write(f"  uint32_t line_crc[{HEIGHT}];\n}};\n\n")
        f.write(f"static const MameFrame mame_frames[{len(frames)}] = {{\n")
        for fr in frames:
            ctrl, ram = rows[fr]
            prev = rows[fr - 1][1]
            png = capture / "snap" / "contra" / f"{(fr - FIRST) // STEP:04d}.png"
            f.write(f"  {{{fr}, {_bytes(ctrl)},\n")
            for _, base, size in REGIONS:
                f.write(f"   {_bytes(ram[base:base + size])},\n")
            f.write(f"   {_bytes(prev[0x3000:0x4000])},\n   {_bytes(prev[0x5000:0x6000])},\n")
            f.write("   {" + ",".join(f"0x{c:08x}" for c in line_crcs(png)) + "}},\n")
        f.write("};\n")


if __name__ == "__main__":
    if len(sys.argv) < 4:
        sys.exit(__doc__)
    main(Path(sys.argv[1]), Path(sys.argv[2]), [int(a) for a in sys.argv[3:]])
