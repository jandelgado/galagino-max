"""Lockstep reference for test_tylz_boot: SP, interrupted IP and CRC32 of the RAM at every NMI.

ram_fixture.lua dumps SP + 0000-2fff + 3800-3bff (2 + 13312 bytes) per NMI, taken in the handler
after its 7 pushes. The CRC skips the dead stack [SP - STALE, SP + PUSHED + 6): the pushed
registers and the NMI frame (IP, CS, FLAGS) hold where in the 2 instruction frame wait the NMI
landed, which depends on cycle timing the interpreter does not model, and stale copies stay
below SP. The interrupted IP is kept separately: the host test checks every NMI MAME lands in the
frame wait (8aae-8ab3) and only counts the others. On a mismatch, `diff` prints the differing
addresses of one NMI against the host dump.

usage: uv run python -m dev.tylz.ram_fixture <dir with attract/ game1/ ram.bin> <out.h>
       uv run python -m dev.tylz.ram_fixture diff <mame ram.bin> <host frame.bin> <nmi>
"""
import sys
import zlib

_RAM = 0x3000
_VRAM = 0x400
_FRAME = 2 + _RAM + _VRAM
_STALE = 0x40       # bytes below SP left out (masked), C++ test mirrors it
_PUSHED = 14        # AX, BX, CX, DI, DS, ES, SI
_NMI_FRAME = 6      # IP, CS, FLAGS
_SCENARIOS = ("attract", "game1")


def _masked(frame: bytes) -> tuple[int, int, bytes]:
    sp = frame[0] | frame[1] << 8
    ram = bytearray(frame[2:])
    ip = ram[sp + _PUSHED] | ram[sp + _PUSHED + 1] << 8
    lo, hi = max(sp - _STALE, 0), min(sp + _PUSHED + _NMI_FRAME, _RAM)
    ram[lo:hi] = bytes(hi - lo)
    return sp, ip, bytes(ram)


def _frames(path: str):
    d = open(path, "rb").read()
    return [d[i:i + _FRAME] for i in range(0, len(d) - _FRAME + 1, _FRAME)]


def _array(ctype: str, name: str, values: list[int], digits: int) -> list[str]:
    out = [f"static const {ctype} {name}[{len(values)}] = {{"]
    out += ["  " + ", ".join(f"0x{v:0{digits}x}" for v in values[i:i + 8]) + "," for i in range(0, len(values), 8)]
    return out + ["};"]


def _header(root: str, out: str) -> None:
    lines = ["// Generated by romconv/dev/tylz/ram_fixture.py from MAME 0.289 tylz: SP, interrupted IP",
             "// and CRC32 of 8088 RAM 0000-2fff + 3800-3bff at each NMI (after the handler's pushes),",
             f"// [SP - 0x{_STALE:x}, SP + {_PUSHED + _NMI_FRAME}) zeroed (see ram_fixture.py).",
             "#include <stdint.h>", ""]
    for sc in _SCENARIOS:
        rows = [_masked(f) for f in _frames(f"{root}/{sc}/ram.bin")]
        lines += _array("uint16_t", f"MAME_SP_{sc.upper()}", [sp for sp, _, _ in rows], 4)
        lines += _array("uint16_t", f"MAME_IP_{sc.upper()}", [ip for _, ip, _ in rows], 4)
        lines += _array("uint32_t", f"MAME_RAM_{sc.upper()}", [zlib.crc32(r) for _, _, r in rows], 8)
    open(out, "w").write("\n".join(lines) + "\n")


def _diff(mame: str, host: str, nmi: int) -> None:
    sp_a, _, a = _masked(_frames(mame)[nmi])
    sp_b, _, b = _masked(open(host, "rb").read())   # one frame, written by test_tylz_boot
    print(f"SP mame {sp_a:04x} host {sp_b:04x}")
    for i, (x, y) in enumerate(zip(a, b)):
        if x != y:
            addr = i if i < _RAM else 0x3800 + i - _RAM
            print(f"{addr:04x}: mame {x:02x} host {y:02x}")


if __name__ == "__main__":
    if sys.argv[1] == "diff":
        _diff(sys.argv[2], sys.argv[3], int(sys.argv[4]))
    else:
        _header(sys.argv[1], sys.argv[2])
