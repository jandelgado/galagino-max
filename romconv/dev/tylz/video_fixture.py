"""Turn a video_fixture.lua capture into source/test/test_tylz_video/mame_frames.h.

Each frame: MAME's render input (video RAM, sprite RAM, palette, 0x5803 latch) and the CRC32 of
every snapshot line as RGB565 (byte swapped, as the panel takes it). Snapshots are 256 x 240
(ROT0); the panel shows x 4-243: snapshot line y is panel line y + 20.

usage: uv run python -m dev.tylz.video_fixture <capture dir> <out.h>
"""
import sys
import zlib
from pathlib import Path

from PIL import Image

from romconv.gfx.color import rgb565_swapped

_NATIVE_W, _WIDTH, _HEIGHT = 256, 240, 240
_LEFT = 4   # native x of panel column 0
_KEEP_EVERY = 6   # of the captured frames (every 20th frame)


def _line_crcs(png: Path) -> list[int]:
    im = Image.open(png).convert("RGB")
    assert im.size == (_NATIVE_W, _HEIGHT), im.size
    px = im.load()
    return [zlib.crc32(b"".join(rgb565_swapped(*px[x, y]).to_bytes(2, "little") for x in range(_LEFT, _LEFT + _WIDTH)))
            for y in range(_HEIGHT)]


def _hexbytes(s: str) -> str:
    return ",".join(f"0x{s[i:i + 2]}" for i in range(0, len(s), 2))


def _main(cap: Path, out: Path) -> None:
    rows = [line.split() for line in open(cap / "state.txt")]
    snaps = sorted((cap / "snap" / "tylz").glob("*.png"))
    assert len(snaps) == len(rows), (len(snaps), len(rows))

    lines = ["// Generated by romconv/dev/tylz/video_fixture.py from MAME 0.289 tylz",
             "// (video_fixture.lua): render input and snapshot line CRCs per frame.",
             "#include <stdint.h>", "",
             "struct MameFrame {", "  int frame;", "  uint8_t ctrl;", "  uint8_t vram[0x400];",
             "  uint8_t spr[0x100];", "  uint8_t pal[0x20];", f"  uint32_t line_crc[{_HEIGHT}];", "};", "",
             "static const MameFrame MAME_FRAMES[] = {"]
    for k in range(0, len(rows), _KEEP_EVERY):
        f, ctrl, vram, spr, pal = rows[k]
        crcs = ",".join(f"0x{c:08x}" for c in _line_crcs(snaps[k]))
        lines.append(f"  {{{f}, 0x{ctrl}, {{{_hexbytes(vram)}}},\n   {{{_hexbytes(spr)}}},\n"
                     f"   {{{_hexbytes(pal)}}},\n   {{{crcs}}}}},")
    lines.append("};")
    out.write_text("\n".join(lines) + "\n")
    print(f"{out}: {(len(rows) + _KEEP_EVERY - 1) // _KEEP_EVERY} frames")


if __name__ == "__main__":
    _main(Path(sys.argv[1]), Path(sys.argv[2]))
