"""Helpers of the Atari ROM-only converters (vector games, Centipede and Millipede)."""
from collections.abc import Sequence

from romconv.core.context import Context
from romconv.core.errors import ConversionError
from romconv.emit.asset import emit_compressed

ARENA_BUDGET = 182000

# dvgMachine::_MAX_LINES vec2d::Line (16 B) + StripRasterizer next/active
# (2 x uint16_t per line) + 36 strip heads, allocated in start()
_MAX_LINES = 1024
_LINE_BUFFER_BYTES = _MAX_LINES * 16 + _MAX_LINES * 2 * 2 + 36 * 2
# GO list: decode buffer (vec2d::Line per line) and published PackedLine
# (8 B) list (+ 2 B count + 4 B sequence)
_GO_LIST_BYTES = _MAX_LINES * 16 + _MAX_LINES * 8 + 8


def load_all(ctx: Context, files: Sequence[tuple[str, str]]) -> bytes:
    """The (name, sha1) ROM files of the job's zip, concatenated."""
    return b"".join(bytes(ctx.rom(name, sha1)) for name, sha1 in files)


def write(ctx: Context, game: str, filename: str, symbol: str, data: Sequence[int], description: str,
          ctype: str = "unsigned char") -> int:
    """One LZMA array header; returns its size in bytes."""
    with ctx.header(filename) as out:
        out.write(f"// Generated by romconv/internal/{game}/{game}_rom_convert.py; do not edit.\n")
        out.write(f"// {description}\n")
        emit_compressed(out, symbol, ctype, "", len(data), list(data))
    size = len(data) * (2 if ctype == "unsigned short" else 1)
    ctx.log.info(f"  wrote {filename}: {size} bytes")
    return size


def check_budget(ctx: Context, total: int) -> None:
    ctx.log.info(f"  Arena budget: {total} / {ARENA_BUDGET} bytes")
    if total >= ARENA_BUDGET:
        raise ConversionError("Arena budget exceeded")


def convert_vector(ctx: Context, game: str, program: Sequence[tuple[str, str]], vector: Sequence[tuple[str, str]],
                   program_description: str, vector_description: str, *, program_bytes: int | None = None,
                   vector_bytes: int | None = None) -> None:
    """Program ROM and DVG/AVG vector ROM headers of a vector game; the budget adds the
    machine's line buffers."""
    prog, vec = load_all(ctx, program), load_all(ctx, vector)
    if program_bytes is not None:
        assert len(prog) == program_bytes and len(vec) == vector_bytes
    total = write(ctx, game, f"{game}_rom.h", f"{game}_rom", prog, program_description)
    total += write(ctx, game, f"{game}_vrom.h", f"{game}_vrom", vec, vector_description)
    total += _LINE_BUFFER_BYTES + _GO_LIST_BYTES
    check_budget(ctx, total)
