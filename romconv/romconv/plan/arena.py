# Arena split of one game per layout: which assets stay PLAIN (flash) and
# which block each COMPRESSED asset unpacks into. Writes <game>_arena_plan.h,
# read by the planned asset headers (emit.asset) and machines.h.
#
# Inputs: the planned assets in the job's manifest (raw and LZMA sizes),
# ARENA_EXTRA / ARENA_RAM / ARENA_FLASH in its machine header (plain
# literals), block sizes of every layout in [arena] of source/platformio.ini
# (plan/layout.py); the build selects its block with ARENA_LAYOUT_<NAME>,
# any other layout is an #error.
#
# plan/solver.py picks the split with the fewest flash bytes under the block
# sizes, the extras (non-asset Arena::alloc, first-fit in declared order, or
# in every order with ARENA_EXTRA_ANY_ORDER: allocations as function
# arguments) and the SCRATCH_BYTES one block keeps for the LZMA probability
# table.
import re
from collections.abc import Sequence
from pathlib import Path

from romconv.core.context import Context
from romconv.core.errors import ConversionError
from romconv.core.manifest import Asset
from romconv.emit.text import WIDTH, c_symbol
from romconv.emit.write import module_path
from romconv.plan.layout import define_name, ini_path, read_layouts
from romconv.plan.solver import HighsSolver, Infeasible, Item, Problem, Solver, r4

# LZMA probability table of one unpack (LzmaProps_GetNumProbs 2614 x 2 at
# lc = lp = 0, 5228 B) plus Arena::scratch alignment, taken from the top of
# a block's free gap; without the gap the device falls back to malloc from a
# heap that WiFi leaves small
SCRATCH_BYTES = 5232

# any_order: extras checked in every order up to this count
_ANY_ORDER_MAX = 8

_DEFAULT_SOLVER = HighsSolver()


def solve(assets, extras, layout, ram=(), flash=(), any_order=False, solver: Solver | None = None):
    """Mode per asset ("PLAIN", "A", "B") and reserved bytes per block.

    assets: (name, raw bytes, packed bytes, align). Fewest flash bytes (see
    plan/solver.py) with the extras first-fit below the reservations and the
    scratch gap kept. any_order: extras must fit in every run-time order.
    ValueError if no split fits.
    """
    names = {a[0] for a in assets}
    for pin in list(ram) + list(flash):
        if pin not in names:
            raise ValueError(f"pinned asset {pin} not in the game's assets")
    if any_order and len(extras) > _ANY_ORDER_MAX:
        raise ValueError(f"ARENA_EXTRA_ANY_ORDER with more than {_ANY_ORDER_MAX} extras")

    problem = Problem(tuple(Item(name, raw, packed, align) for name, raw, packed, align in assets), tuple(layout),
                      frozenset(flash), frozenset(ram), tuple(r4(e) for e in extras), any_order, SCRATCH_BYTES)
    try:
        solution = (solver or _DEFAULT_SOLVER).solve(problem)
    except Infeasible as e:
        raise ValueError(str(e)) from e
    return solution.modes, solution.reserve


def _array(text, name):
    m = re.search(r"\b" + name + r"\[\]\s*=\s*\{(.*?)\};", text, re.S)
    if not m:
        return []
    return [v.strip() for v in re.sub(r"//[^\n]*", "", m.group(1)).split(",") if v.strip()]


def parse_machine_header(path: Path):
    """(extras, ram, flash, any_order) from the ARENA_* constants; literals only."""
    text = Path(path).read_text(encoding="utf-8")
    extras = []
    for v in _array(text, "ARENA_EXTRA"):
        if not re.fullmatch(r"\d+", v):
            raise ValueError(f"{path}: ARENA_EXTRA entry '{v}' is not an integer literal")
        extras.append(int(v))
    pins = []
    for name in ("ARENA_RAM", "ARENA_FLASH"):
        vals = []
        for v in _array(text, name):
            if not re.fullmatch(r'"\w+"', v):
                raise ValueError(f"{path}: {name} entry {v} is not a string literal")
            vals.append(v.strip('"'))
        pins.append(vals)
    any_order = bool(re.search(r"\bARENA_EXTRA_ANY_ORDER\s*=\s*true\b", text))
    return extras, pins[0], pins[1], any_order


def extras_key(extras, any_order):
    """Same as arena.h arenaExtrasKey(): the plan records what it was solved for."""
    key = 0
    for e in extras:
        key = (key * 31 + e) & 0xFFFFFFFF
    return key ^ 0x80000000 if any_order else key


def plan_header(game: str, plans: dict, types: dict[str, str], key: int,
                layouts: dict[str, tuple[int, int]]) -> str:
    """Header text; plans = {layout: (modes, reserve)} for every layout in
    layouts (read_layouts(), ini order), one #if block per layout selected
    by its build define, #error for any other. types = {name: element type}
    for the <name>_asset aliases, key = extras_key() of the machine's
    ARENA_EXTRA."""
    ident = c_symbol(game)
    guard = ident.upper() + "_ARENA_PLAN_H"
    out = [f"// Generated by {module_path(__file__)}: Arena split of {game} per layout. Do not edit.",
           f"#ifndef {guard}", f"#define {guard}", '#include "../../emulation/asset.h"',
           f"static constexpr uint32_t {ident}_arena_extras_key = {key}u;"]
    for i, (layout, (a, b)) in enumerate(layouts.items()):
        modes, reserve = plans[layout]
        out.append(f"#{'if' if i == 0 else 'elif'} defined({define_name(layout)})")
        out.append(f"static_assert(Arena::BLOCK_A_SIZE == {a} && Arena::BLOCK_B_SIZE == {b}, "
                   '"Arena layout changed: rerun romconv");')
        for name in sorted(modes):
            mode = modes[name]
            out.append(f"#define {name}_PLAIN {1 if mode == 'PLAIN' else 0}")
            out.append(f"#define {name}_BLOCK " + {"PLAIN": "ARENA_ANY", "A": "ARENA_A", "B": "ARENA_B"}[mode])
            out.append(f"using {name}_asset = Asset<{types[name]}, {'PLAIN' if mode == 'PLAIN' else 'COMPRESSED'}>;")
        out.append(f"static constexpr ArenaPlan {ident}_arena_plan = {{ {reserve[0]}, {reserve[1]} }};")
    out += ["#else", '#error "no Arena plan for this layout: add it to [arena] in platformio.ini and rerun romconv"',
            "#endif", "#endif", ""]
    return "\n".join(out)


def plan_assets(assets: Sequence[Asset]) -> list[tuple[str, int, int, int, str]]:
    """[(name, raw bytes, packed bytes, align, type)] of the planned assets."""
    return [(a.name, len(a.raw), len(a.packed), WIDTH[a.ctype], f"{a.ctype}{a.inner}")
            for a in assets if a.mode == "PLANNED"]


def write_arena_plan(ctx: Context) -> None:
    game = ctx.job.machine
    if game is None:
        raise ConversionError(f"job {ctx.job.name}: plan needs a machine dir")
    assets = plan_assets(ctx.manifest.assets())
    machine_dir = ctx.path(game + ".h").parent
    if not assets:
        raise ConversionError(f"{game}: no planned assets in {machine_dir}")
    try:
        layouts = read_layouts(ini_path(ctx.paths))
        extras, ram, flash, any_order = parse_machine_header(ctx.path(game + ".h"))
        plans = {}
        for layout, (a, b) in layouts.items():
            try:
                modes, reserve = solve([x[:4] for x in assets], extras, (a, b), ram, flash, any_order)
            except ValueError as e:
                raise ValueError(f"{game} {layout}: {e}") from e
            plans[layout] = (modes, reserve)
            plain = [n for n in sorted(modes) if modes[n] == "PLAIN"]
            plain_bytes = sum(x[1] for x in assets if modes[x[0]] == "PLAIN")
            flash_bytes = plain_bytes + sum(x[2] for x in assets if modes[x[0]] != "PLAIN")
            ctx.log.info(f"  {game} {layout:14s} A {reserve[0]:6d} B {reserve[1]:6d} reserved of {a}+{b},"
                         f" extras {sum(map(r4, extras))}, flash {flash_bytes} B, PLAIN {plain_bytes} B:"
                         f" {' '.join(plain) or '-'}")
        text = plan_header(game, plans, {x[0]: x[4] for x in assets}, extras_key(extras, any_order), layouts)
    except ValueError as e:
        raise ConversionError(str(e)) from e
    with ctx.header(game + "_arena_plan.h", plan=False, remote=False) as f:
        f.write(text)
