import numpy as np

from romconv.core.context import Context
from romconv.emit.write import module_path
from romconv.gfx.adpcm import emit_adpcm


def sample(ctx: Context, symbol: str, src_name: str, header: str, *, compress: bool = False) -> None:
    """Raw signed 8-bit sample (samples/<src_name>) -> IMA-ADPCM asset header,
    played by ima_adpcm::Voice. The sample rate is kept: the machine plays
    it as before. compress: COMPRESSED (unpacked to the Arena), else PLAIN."""
    pcm = np.frombuffer((ctx.paths.samples / src_name).read_bytes(), dtype=np.int8)

    with ctx.header(header) as f:
        print(f"// {symbol}: samples/{src_name}, signed 8-bit, as 4-bit IMA-ADPCM", file=f)
        print("// (2-byte predictor, then one nibble per sample). Generated by", file=f)
        print(f"// {module_path(__file__)}, do not edit.", file=f)
        size = emit_adpcm(f, symbol, pcm, compress)
    ctx.log.info(f"{symbol}: {len(pcm)} -> {size} bytes")
