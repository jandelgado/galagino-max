_CRYPT_SIZE = 0x8000
_CRYPT_BITS = 0xa8  # bits 3, 5, 7 are swapped/inverted, the rest pass through


# MAME segacrpt decode(): data image of the whole ROM, opcode image of 0000-7fff
def _sega_decrypt(rom, table):
    data = bytearray(rom)
    ops = bytearray(_CRYPT_SIZE)
    for a in range(_CRYPT_SIZE):
        src = rom[a]
        row = BIT(a, 0) | BIT(a, 4) << 1 | BIT(a, 8) << 2 | BIT(a, 12) << 3
        col = BIT(src, 3) | BIT(src, 5) << 1
        xor = 0
        if src & 0x80:
            col = 3 - col
            xor = _CRYPT_BITS
        keep = src & ~_CRYPT_BITS
        ops[a] = keep | (table[2 * row][col] ^ xor)
        data[a] = keep | (table[2 * row + 1][col] ^ xor)
    return bytes(data), bytes(ops)


def _swap2(src, t):
    out = src & 0xaa
    for dst, s in zip((6, 4, 2, 0), t):
        out |= BIT(src, s) << dst
    return out


# MAME segacrp2 decode(): data image of the whole ROM, opcode image of 0000-7fff
def _sega_decrypt2(rom, tables):
    xor, swap = tables
    data = bytearray(rom)
    ops = bytearray(_CRYPT_SIZE)
    for a in range(_CRYPT_SIZE):
        src = rom[a]
        row = (BIT(a, 14) << 5 | BIT(a, 12) << 4 | BIT(a, 9) << 3 |
               BIT(a, 6) << 2 | BIT(a, 3) << 1 | BIT(a, 0))
        ops[a] = _swap2(src, _SWAPS2[swap[2 * row]]) ^ xor[2 * row]
        data[a] = _swap2(src, _SWAPS2[swap[2 * row + 1]]) ^ xor[2 * row + 1]
    return bytes(data), bytes(ops)


# (data image, opcode image or None) per the game's "crypt" key. MC-8123
# needs its key RAM image ("key" spec) from the game's zip.
def decrypt_main(ctx: Context, spec: SetSpec, rom: bytes, zip: str) -> tuple[bytes, bytes | None]:
    name = spec.crypt
    if name == "mc8123":
        return mc8123.decode(rom, load_roms(ctx, spec.key, zip))
    if name in _CRYPT:
        return _sega_decrypt(rom, _CRYPT[name])
    if name in _CRYPT2:
        return _sega_decrypt2(rom, _CRYPT2[name])
    assert name is None, f"unknown crypt {name}"
    return rom, None
