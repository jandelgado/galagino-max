"""Convert the MAME atetris (Tetris set 1) ROM set into galagino headers."""
from romconv.core.context import Context
from romconv.core.errors import ConversionError
from romconv.core.job import Job
from romconv.emit.asset import emit_compressed

_MAIN = ("136066-1100.45f", "5e1189227f26563fd3e5372121ea5c915620f892")
_TILES = ("136066-1101.35a", "d8577985fc8ed4e74f74c68b7c00c4855b7c3270")


def _tile_words(gfx):
    # MAME gfx_8x8x4_packed_msb: 32 bytes per tile, 4 per row, high nibble
    # = left pixel, pen = nibble. Word per row: pixel i in bits 4i..4i+3.
    words = []
    for row in range(len(gfx) // 4):
        w = 0
        for i in range(8):
            b = gfx[row * 4 + (i >> 1)]
            w |= ((b >> 4) if i % 2 == 0 else (b & 15)) << (4 * i)
        words.append(w)
    return words


def _write(ctx, filename, description, emit):
    with ctx.header(filename) as out:
        out.write("// Generated by romconv/internal/atetris/atetris_rom_convert.py; do not edit.\n")
        out.write(f"// {description}\n")
        emit(out)
    ctx.log.info(f"  wrote {filename}")


def _convert(ctx: Context) -> None:
    rom = bytes(ctx.rom(*_MAIN))
    gfx = bytes(ctx.rom(*_TILES))
    _write(ctx, "atetris_rom.h", "Main M6502 ROM, 64 KiB: 0x0000-0x7fff slapstic banks, 0x8000-0xffff fixed.",
           lambda f: emit_compressed(f, "atetris_rom", "unsigned char", "", len(rom), list(rom)))
    words = _tile_words(gfx)
    _write(ctx, "atetris_tiles.h", "2048 8x8 tiles, uint32_t per row, pixel i in bits 4i..4i+3.",
           lambda f: emit_compressed(f, "atetris_tiles", "uint32_t", "[8]", len(words) // 8, words))
    total = len(rom) + len(words) * 4
    ctx.log.info(f"  Arena budget: {total} / 182000 bytes")
    if total >= 182000:
        raise ConversionError("Arena budget exceeded")


JOB = Job(name="atetris", convert=_convert, machine="atetris", zips=("atetris.zip",))
