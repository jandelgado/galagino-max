"""Space Invaders (Midway, 1978; MAME mw8080bw). A bitmap framebuffer game: no tile or sprite ROMs."""
import numpy as np

from romconv.core.context import Context
from romconv.core.job import Job
from romconv.emit.asset import emit_compressed
from romconv.emit.write import module_path
from romconv.gfx.adpcm import emit_adpcm

# 2 KB each at 0x0000, 0x0800, 0x1000, 0x1800
_ROMS = ("invaders.h", "invaders.g", "invaders.f", "invaders.e")
_ROM_SIZE = 0x0800
_SAMPLES = ("shot", "invhit")


def _convert_rom(ctx: Context) -> None:
    rom_data = bytearray()
    for name in _ROMS:
        data = ctx.rom(name)
        if len(data) != _ROM_SIZE:
            ctx.log.warning(f"{name} is {len(data)} bytes, expected {_ROM_SIZE}")
        rom_data.extend(data[:_ROM_SIZE])

    with ctx.header("spaceinvaders_rom.h") as f:
        f.write("// Space Invaders CPU ROM (8KB: invaders.h + .g + .f + .e)\n")
        f.write(f"// Auto-generated by {module_path(__file__)} - DO NOT EDIT\n\n")
        f.write("#ifndef _spaceinvaders_rom_h_\n")
        f.write("#define _spaceinvaders_rom_h_\n\n")
        emit_compressed(f, "spaceinvaders_rom", "unsigned char", "", len(rom_data), list(rom_data))
        f.write("\n#endif\n")


def _convert_samples(ctx: Context) -> None:
    """Shot and invader hit samples (12 kHz signed 8-bit, each played twice at 24 kHz) to IMA-ADPCM."""
    with ctx.header("spaceinvaders_samples.h") as f:
        f.write("// Space Invaders audio samples: 12 kHz signed 8-bit as 4-bit IMA-ADPCM\n")
        f.write(f"// Generated by {module_path(__file__)}, do not edit.\n\n")
        for name in _SAMPLES:
            pcm = np.frombuffer((ctx.paths.samples / f"invaders_{name}.s8").read_bytes(), dtype=np.int8)
            size = emit_adpcm(f, f"si_sample_{name}", pcm, compress=True)
            f.write("\n")
            ctx.log.info(f"si_sample_{name}: {len(pcm)} -> {size} bytes")


def _convert(ctx: Context) -> None:
    _convert_rom(ctx)
    _convert_samples(ctx)


JOB = Job(name="invaders", convert=_convert, machine="spaceinvaders", zips=("invaders.zip",))
