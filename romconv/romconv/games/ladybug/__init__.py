"""Lady Bug ROM converter: ladybug.zip -> galagino headers, with the per-position delta patches of
the *.table files (next to this file)."""
from pathlib import Path

from romconv.core.context import Context
from romconv.core.job import Job
from romconv.emit.asset import emit_compressed
from romconv.gfx.patchtable import apply_patch_values, read_patch_table

_HERE = Path(__file__).parent

# Costanti specifiche di Lady Bug
_TILE_COUNT = 512
_TILE_SIZE = 16

_SPRITE_COUNT = 128
_SPRITE_SIZE = 64

_CPU_FILES = (
    ("l1.c4", 0x1000),
    ("l2.d4", 0x1000),
    ("l3.e4", 0x1000),
    ("l4.h4", 0x1000),
    ("l5.j4", 0x1000),
    ("l6.k4", 0x1000),
)
_TILES_FILE = "l0.h7"
_SPRITE_FILES = ("l7.m7", "l8.l7")

_TARGET_SIZE = 24 * 1024


def _generate_base_tilemap(ctx, tile_data):
    values = []
    expected_size = _TILE_COUNT * _TILE_SIZE
    if len(tile_data) != expected_size:
        ctx.log.warning(f" ATTENZIONE: tile data {len(tile_data)} bytes, attesi {expected_size}")
        if len(tile_data) < expected_size:
            tile_data.extend([0] * (expected_size - len(tile_data)))

    for tile in range(_TILE_COUNT):
        for row in range(8):
            addr = tile * _TILE_SIZE + row * 2
            if addr + 1 < len(tile_data):
                plane0 = tile_data[addr]
                plane1 = tile_data[addr + 1]
                word = 0
                for bit in range(8):
                    p0 = (plane0 >> (7 - bit)) & 1
                    p1 = (plane1 >> (7 - bit)) & 1
                    pixel = (p1 << 1) | p0
                    word |= (pixel << (bit * 2))
                values.append(word)
            else:
                values.append(0)
    return values


def _generate_base_spritemap(ctx, sprite_bank0, sprite_bank1):
    sprite_data = bytearray()
    sprite_data.extend(sprite_bank0)
    sprite_data.extend(sprite_bank1)

    expected_size = _SPRITE_COUNT * _SPRITE_SIZE
    if len(sprite_data) != expected_size:
        ctx.log.warning(f" ATTENZIONE: sprite data {len(sprite_data)} bytes, attesi {expected_size}")
        if len(sprite_data) < expected_size:
            sprite_data.extend([0] * (expected_size - len(sprite_data)))

    original_sprites = []
    for sprite in range(_SPRITE_COUNT):
        for row in range(16):
            addr = sprite * _SPRITE_SIZE + row * 4
            if addr + 3 < len(sprite_data):
                plane0_low = sprite_data[addr]
                plane0_high = sprite_data[addr + 1]
                plane1_low = sprite_data[addr + 2]
                plane1_high = sprite_data[addr + 3]

                low_word = 0
                high_word = 0

                for bit in range(8):
                    p0 = (plane0_low >> (7 - bit)) & 1
                    p1 = (plane1_low >> (7 - bit)) & 1
                    pixel = (p1 << 1) | p0
                    low_word |= (pixel << (bit * 2))

                    p0 = (plane0_high >> (7 - bit)) & 1
                    p1 = (plane1_high >> (7 - bit)) & 1
                    pixel = (p1 << 1) | p0
                    high_word |= (pixel << (bit * 2))

                long_val = (high_word << 16) | low_word
                original_sprites.append(long_val)
            else:
                original_sprites.append(0)

    return original_sprites


def _write_cpu_rom_header(ctx, cpu_data):
    ctx.log.info("Generazione ladybug_rom.h...")

    if len(cpu_data) > _TARGET_SIZE:
        cpu_data = cpu_data[:_TARGET_SIZE]
    elif len(cpu_data) < _TARGET_SIZE:
        cpu_data.extend([0] * (_TARGET_SIZE - len(cpu_data)))

    with ctx.header("ladybug_rom.h") as f:
        f.write("// Lady Bug CPU ROM - 24KB (6 x 4KB)\n")
        f.write("// Generated from l1.c4-l6.k4 concatenated\n")
        f.write(f"// Total size: {len(cpu_data)} bytes\n\n")
        emit_compressed(f, "ladybug_rom_cpu1", "unsigned char", "", len(cpu_data), list(cpu_data))

    ctx.log.info(f" Scritti {len(cpu_data)} bytes")


def _write_tilemap_header(ctx, tile_values):
    with ctx.header("ladybug_tilemap.h") as f:
        f.write("// Lady Bug character tiles - 512 chars, 8x8, 2bpp packed\n")
        f.write("// Generated by ladybug_rom_convert.py\n\n")
        emit_compressed(f, "ladybug_tilemap", "unsigned short", "[8]", _TILE_COUNT, tile_values)


def _write_spritemap_header(ctx, sprites):
    """Scrive il file header degli sprite da una lista piatta di 2048 valori (128 sprite x 16 righe)"""
    with ctx.header("ladybug_spritemap.h") as f:
        f.write("// Lady Bug sprites - 128 sprites, 16x16, 2bpp packed, unflipped\n")
        f.write("// Generated by ladybug_rom_convert.py\n\n")
        emit_compressed(f, "ladybug_sprites", "uint32_t", "[16]", _SPRITE_COUNT, sprites)


def _write_colormap_header(ctx):
    char_palette = (
        (0x0000, 0x7fad, 0x7ffd, 0xea57),
        (0x0000, 0x00f8, 0xe007, 0xe0ff),
        (0x0000, 0xffaf, 0xffff, 0x75ad),
        (0x0000, 0xffff, 0x75ad, 0x6afd),
        (0x0000, 0xe007, 0xf5af, 0x6005),
        (0x0000, 0xea57, 0x7f05, 0x7ffd),
        (0x0000, 0xffff, 0xe0ff, 0x7ffd),
        (0x0000, 0x0000, 0x80fa, 0x7ffd),
    )

    sprite_palette = (
        (0x0000, 0x00f8, 0xe007, 0xe0ff),
        (0x0000, 0x9faa, 0xe007, 0xffff),
        (0x0000, 0x15f8, 0xe007, 0xffff),
        (0x0000, 0x60fd, 0xe0ff, 0xffff),
        (0x0000, 0xe007, 0xf5af, 0xffff),
        (0x0000, 0x60fd, 0xe0ff, 0xffff),
        (0x0000, 0x60fd, 0xf5af, 0xe0ff),
        (0x0000, 0x60fd, 0xe0ff, 0xffff),
    )

    with ctx.header("ladybug_cmap.h") as f:
        f.write("// Lady Bug color maps - RGB565\n")
        f.write("// Generated by ladybug_rom_convert.py\n\n")

        f.write("// Character color palette: 8 groups x 4 colors\n")
        f.write("const unsigned short ladybug_colormap[8][4] = {\n")
        for pal in char_palette:
            f.write("{" + ",".join(f"0x{col:04x}" for col in pal) + "},\n")
        f.write("};\n\n")

        f.write("// Sprite color palette: 8 groups x 4 colors\n")
        f.write("const unsigned short ladybug_sprite_colormap[8][4] = {\n")
        for pal in sprite_palette:
            f.write("{" + ",".join(f"0x{col:04x}" for col in pal) + "},\n")
        f.write("};\n")


def _convert(ctx: Context) -> None:
    ctx.log.info("Lady Bug ROM Converter - CON PATCH (delta)")

    ctx.log.info("Caricamento file ROM...")
    cpu_data = bytearray()
    for filename, expected_size in _CPU_FILES:
        data = ctx.rom(filename)
        if len(data) != expected_size:
            ctx.log.warning(f" ATTENZIONE: {filename} dimensione {len(data)} bytes, attesi {expected_size}")
            if len(data) > expected_size:
                data = data[:expected_size]
        cpu_data.extend(data)

    if len(cpu_data) != _TARGET_SIZE:
        ctx.log.warning(f" ATTENZIONE: cpu_data totale {len(cpu_data)} bytes, forzatura a {_TARGET_SIZE}")
        if len(cpu_data) > _TARGET_SIZE:
            cpu_data = cpu_data[:_TARGET_SIZE]
        else:
            cpu_data.extend([0] * (_TARGET_SIZE - len(cpu_data)))

    tile_data = ctx.rom(_TILES_FILE)
    sprite_bank0 = ctx.rom(_SPRITE_FILES[0])
    sprite_bank1 = ctx.rom(_SPRITE_FILES[1])

    # === PASSO 1: Genera valori base ===
    ctx.log.info("FASE 1: Generazione dati base...")

    tile_base = _generate_base_tilemap(ctx, tile_data)
    ctx.log.info(f" Generati {len(tile_base)} valori tile base")

    sprite_base = _generate_base_spritemap(ctx, sprite_bank0, sprite_bank1)
    ctx.log.info(f" Generati {len(sprite_base)} valori sprite base")

    cpu_list = list(cpu_data)
    ctx.log.info(f" CPU data: {len(cpu_list)} bytes")

    # === PASSO 2: Applica le patch ===
    ctx.log.info("FASE 2: Applicazione patch...")

    # Tile patch (16 bit)
    tile_final = apply_patch_values(tile_base, read_patch_table(_HERE / "til_patch.table"), 0xFFFF)

    # CPU patch (8 bit)
    cpu_final = bytearray(apply_patch_values(cpu_list, read_patch_table(_HERE / "rom_patch.table"), 0xFF))

    # Sprite patch: delta sugli sprite non flippati (ladybug::blit_sprite
    # applica il flip a runtime)
    sprite_final = apply_patch_values(sprite_base, read_patch_table(_HERE / "spr_patch.table"), 0xFFFFFFFF)

    # === PASSO 3: Scrivi i file finali ===
    ctx.log.info("FASE 3: Scrittura file finali...")

    _write_cpu_rom_header(ctx, cpu_final)
    _write_tilemap_header(ctx, tile_final)
    ctx.log.info(" Scritto ladybug_tilemap.h")
    _write_spritemap_header(ctx, sprite_final)
    ctx.log.info(" Scritto ladybug_spritemap.h")
    _write_colormap_header(ctx)
    ctx.log.info(" Scritto ladybug_cmap.h")

    ctx.log.info("--- OPERAZIONE COMPLETATA ---")


JOB = Job(name="ladybug", convert=_convert, machine="ladybug", zips=("ladybug.zip",))
