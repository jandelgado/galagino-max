# ============================================================
# Scrambled Egg ROM converter
# Converts "scregg.zip" (Data East set 1)
# ============================================================
from romconv.core.context import Context
from romconv.core.job import Job
from romconv.emit.asset import emit_compressed
from romconv.hw.btime import decode_chars, decode_tiles16

_MAINCPU = (("d00.e14", "e1a329a4452eeb90801d001140ce865bf1ea7716"),
            ("d10.d14", "73b3ca6e0d72cd0db951ae9ed1552cf8b7d91e68"),
            ("d20.c14", "fc7b2d9094fa5e25c1bf4b68386f640f4502e0c0"),
            ("d30.b14", "f2d2fe2236de1b3b2614cc95f61a90571638cd69"),
            ("d40.a14", "192cdc506fb0bbfed8ae687f2699397ace3bef30"))
_GFX1 = (("d50.j12", "88edd35479ceb58244f644a7e0520d225df3bf65"),
         ("d60.j10", "3067bbd9493614e80d8d3982fe80ef25688d256c"),
         ("d70.h12", "6a8d257a3fec901453c7216ad894badf96188ebf"),
         ("d80.h10", "2e38c27b546eeef0fe42340777c8687f4c65ee97"),
         ("d90.g12", "0da866db6a79f658de3efc609b9ca8520b4d22d0"),
         ("da0.g10", "e01b72501a01ffc0370cf19c9a379a54800cccc6"))
_PROM1 = ("dc0.c6", "d09738915da456449bb4e8d9eefb8e6378f0edea")  # palette


# ------------------------------------------------------------
def _write_rom(ctx, name, sym, data, comment):
    with ctx.header(name) as f:
        print(f"// {comment}", file=f)
        emit_compressed(f, sym, "unsigned char", "", len(data), list(data))


def _write_char_tiles(ctx, tiles):
    with ctx.header("scregg_chartiles.h") as f:
        print("// Scrambled Egg char set #1", file=f)
        flat = [v for t in tiles for y in range(8) for v in t[y]]
        emit_compressed(f, "scregg_chartiles", "unsigned char", "[8][8]", len(tiles), flat)


def _write_sprite_tiles(ctx, tiles):
    with ctx.header("scregg_spritetiles.h") as f:
        print("// Scrambled Egg sprites", file=f)
        flat = [v for t in tiles for y in range(16) for v in t[y]]
        emit_compressed(f, "scregg_spritetiles", "unsigned char", "[16][16]", len(tiles), flat)


def _write_c_array(ctx, filename, name, data, comment):
    with ctx.header(filename) as f:
        f.write("// Auto-generated by romconv/scregg/scregg_rom_convert.py - DO NOT EDIT\n")
        if comment:
            f.write(f"// {comment}\n")
        f.write(f"const unsigned char {name}[] = {{\n")
        for i in range(0, len(data), 16):
            chunk = data[i:i + 16]
            line = ','.join(f'0x{b:02X}' for b in chunk)
            f.write('  ' + line + ',\n')
        f.write('};\n')


# ------------------------------------------------------------
def _convert(ctx: Context) -> None:
    cpu01, cpu02, cpu03, cpu04, cpu05 = (ctx.rom(*f) for f in _MAINCPU)
    gfx1 = bytearray().join(ctx.rom(*f) for f in _GFX1)
    prom1 = ctx.rom(*_PROM1)

    assert len(gfx1) == 0x6000
    char_tiles, char_count = decode_chars(gfx1)
    _write_char_tiles(ctx, char_tiles)
    ctx.log.info(f"char tiles: {char_count}")

    sprite_tiles, sprite_count = decode_tiles16(gfx1)
    _write_sprite_tiles(ctx, sprite_tiles)
    ctx.log.info(f"sprite tiles: {sprite_count}")

    # --- ROM CPU (rimangono CIFRATE in flash, decrittate a runtime dal core
    # m6502 patchato con l'hook fetch - vedi decocpu7.cpp) ---
    # maincpu: solo 0xc000-0xffff popolato in questo set (16KB, 4 file);
    # 0xb000-0xbfff resta a 0 (non presente nel set "btime" Data East set 1).
    maincpu = cpu01 + cpu02 + cpu03 + cpu04 + cpu05
    assert len(maincpu) == 0x5000  # 0x3000-0x7fff
    _write_rom(ctx, "scregg_rom.h", "scregg_rom", bytes(maincpu),
               "Scrambled Egg main CPU ROM 0xb000-0xffff (0xb000-0xbfff empty in this")

    _write_c_array(ctx, "scregg_colorprom.h", "scregg_colorprom", prom1, "Scregg color PROMs")

    ctx.log.info("Scrambled Egg conversion finished.")


JOB = Job(name="scregg", convert=_convert, machine="scregg", zips=("scregg.zip",), plan=True)
