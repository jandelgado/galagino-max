#!/usr/bin/env python3
"""MAME Taito SJ frames (env GAME: elevator, jungleh) -> test fixture: video state, character RAM and a
CRC32 per line of the snapshot, cropped to the 240 panel columns.

Usage: mame_fixture.py <dump dir> <frame>:<snapshot png> ...
The dump dir holds <frame>.txt from mame_fixture.lua. elevatorb updates
video every second frame: state of F and F-1 must match (asserted). Env
STATE=prev takes the state of F-1, STATE=cur that of F without the check,
for games that update every frame.
"""
import binascii
import os
import struct
import sys

from PIL import Image

WIDTH, LINES, CROP = 256, 224, 8
GAME = os.environ.get("GAME", "elevator")
SETS = {"elevator": "elevatorb", "jungleh": "jungleh"}
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "source", "test",
                   f"test_{GAME}_video", "mame_frames.h")


def rgb565_swapped(r, g, b):
    c = ((r & 0xf8) << 8) | ((g & 0xfc) << 3) | (b >> 3)
    return struct.pack("<H", ((c >> 8) | (c << 8)) & 0xffff)


def line_crcs(png):
    im = Image.open(png).convert("RGB")
    assert im.size == (WIDTH, LINES), im.size
    return [binascii.crc32(b"".join(rgb565_swapped(*im.getpixel((x, y)))
                                    for x in range(CROP, WIDTH - CROP))) & 0xffffffff
            for y in range(LINES)]


def arr(data):
    return "{" + ",".join(f"0x{b:02x}" for b in data) + "}"


def main():
    d, picks = sys.argv[1], sys.argv[2:]
    with open(OUT, "w", newline="\n") as f:
        f.write(f"// MAME {SETS[GAME]} frames F: tilemaps 1-3, colscroll, sprites, palette,\n"
                "// scroll, colorbank, video mode, priority (mame_fixture.lua order),\n"
                "// character RAM, CRC32 per line of the snapshot, columns 8..247 (RGB565\n"
                "// swapped as galagino). Generated by romconv/internal/elevator/mame_fixture.py.\n"
                "#include <stdint.h>\n\nstruct MameFrame {\n  uint32_t frame;\n"
                "  uint8_t state[0xd6a];\n  uint8_t charram[0x3000];\n"
                "  uint32_t line_crc[224];\n};\n\nstatic const MameFrame MAME_FRAMES[] = {\n")
        for p in picks:
            frame, png = p.split(":")
            cur, prev, charram = open(os.path.join(d, f"{frame}.txt")).read().split()
            if os.environ.get("STATE") == "prev":
                cur = prev
            if os.environ.get("STATE") == "cur":
                prev = cur
            assert cur == prev, f"frame {frame}: video state changed since F-1"
            state, cr = bytes.fromhex(cur), bytes.fromhex(charram)
            assert len(state) == 0xd6a and len(cr) == 0x3000
            crcs = ",".join(f"0x{c:08x}u" for c in line_crcs(png))
            f.write(f"  {{{frame},\n   {arr(state)},\n   {arr(cr)},\n   {{{crcs}}}}},\n")
        f.write("};\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
