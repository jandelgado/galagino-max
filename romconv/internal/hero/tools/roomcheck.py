#!/usr/bin/env python3
"""Check the H.E.R.O. room playfield decode against MAME snapshots.

usage: roomcheck.py <rom.a26> <roomdir> [--fixture <out.h>]
roomdir: room_000.png .. room_255.png from capture_rooms.py (176x223).

Per band, each of the 40 playfield cells (4 px) counts as set when most of
its pixels are not black. Sprites cover too little of a cell to flip it.
Unknown: cells 0-1 (HMOVE bar) and the animated middle band of moving-wall
rooms. --fixture writes the MAME result as a C header for the host test.
"""
import subprocess
import sys

rom = open(sys.argv[1], "rb").read()
roomdir = sys.argv[2]
fixture = sys.argv[4] if len(sys.argv) > 4 and sys.argv[3] == "--fixture" else None

b1 = lambda a: rom[4096 + (a & 0xFFF)]
FIRST = [b1(0xFF00 + l) for l in range(20)]
MINER = [b1(0xFF28 + l) for l in range(20)]
SIZES = [b - a for a, b in zip(FIRST, FIRST[1:] + [256])]

W = 176
X0 = 8                                    # snapshot column of playfield pixel 0
BAND_ROWS = [(33, 71), (74, 110), (113, 150)]  # inner lines of top, mid, bottom


def decode(level, screen):
    """reference decode: ([(pf0, pf1, pf2, repeat)] top/mid/bottom, ball_x or None, moving)"""
    r = FIRST[level] + screen
    if screen == 0:
        top = (0xC0, 0x00)
    elif screen >= 11:
        top = (0xFF, 0xFF)
    else:
        top = (b1(0xFB00 + r - 1), b1(0xFD00 + r - 1))
    fe = b1(0xFE00 + r)
    a0 = ((fe & 0xFC) | 1) if fe & 0xFC else 0
    be = 0x00 if screen >= 10 or (MINER[level] != screen and a0 in (0x09, 0x99)) else 0xFF
    bands = [(0xFF,) + top + (0,),
             (be, b1(0xFA00 + r), b1(0xFC00 + r), fe & 1),
             (0xFF, b1(0xFB00 + r), b1(0xFD00 + r), 0)]
    ball = a0 - 1 if a0 in (0x09, 0x99) else (0x3C if screen == 0 else None)
    moving = level >= 13 and b1(0xFA00 + r) == 0xFF and b1(0xFC00 + r) == 0x7F
    return bands, ball, moving


def cells(pf0, pf1, pf2, repeat):
    left = [(pf0 >> (4 + i)) & 1 for i in range(4)]
    left += [(pf1 >> (7 - i)) & 1 for i in range(8)]
    left += [(pf2 >> i) & 1 for i in range(8)]
    return left + (left if repeat else left[::-1])


def load(png):
    return subprocess.run(["ffmpeg", "-loglevel", "error", "-i", png, "-f", "rawvideo",
                           "-pix_fmt", "rgb24", "-"], capture_output=True, check=True).stdout


def observe(img, y0, y1):
    out = []
    for c in range(40):
        on = n = 0
        for y in range(y0, y1 + 1):
            for x in range(X0 + 4 * c, X0 + 4 * c + 4):
                p = (y * W + x) * 3
                n += 1
                on += img[p:p + 3] != b"\0\0\0"
        out.append(int(2 * on > n))
    return out


bad = 0
rows = []
room = 0
for level in range(20):
    for screen in range(SIZES[level]):
        img = load(f"{roomdir}/room_{room:03d}.png")
        bands, ball, moving = decode(level, screen)
        fix = []
        for bi, (band, (y0, y1)) in enumerate(zip(bands, BAND_ROWS)):
            exp = cells(*band)
            if ball is not None:
                exp[ball // 4] = exp[ball // 4 + 1] = 1
            got = observe(img, y0, y1)
            known = [0, 0] + [1] * 38
            if moving and bi == 1:
                known = [0] * 40
            diff = [c for c in range(40) if known[c] and got[c] != exp[c]]
            if diff:
                bad += 1
                print(f"L{level + 1} S{screen} room {room} band {'TMB'[bi]} cells {diff}")
            fix.append((sum(b << i for i, b in enumerate(got)), sum(b << i for i, b in enumerate(known))))
        rows.append(fix)
        room += 1
print(f"bands differing: {bad} of {3 * room}")

if fixture:
    with open(fixture, "w") as f:
        print("// Generated by romconv/internal/hero/tools/roomcheck.py from MAME a2600", file=f)
        print("// snapshots; do not edit. Per room top/mid/bottom band: bit c = playfield", file=f)
        print("// cell c (pixels 4c..4c+3) seen set, known = cells MAME shows reliably.", file=f)
        print("#include <stdint.h>\n", file=f)
        for name, k in (("hero_mame_cells", 0), ("hero_mame_known", 1)):
            print(f"static const uint64_t {name}[256][3] = {{", file=f)
            for fix in rows:
                print("  { " + ", ".join(f"0x{b[k]:010x}ull" for b in fix) + " },", file=f)
            print("};\n", file=f)
sys.exit(1 if bad else 0)
