#!/usr/bin/env python3
"""MAME traces -> C header for the hero_game host test.

usage: trace_fixture.py <rom.a26> <out.h> <name>:<script.txt>:<frames>[:noball] ...
Each script starts game 1 with the reset switch; the fixture starts at the
first game frame of the respawn glide (y leaves $8B). noball: the script
pokes $A0 = 0 during the glide (start wall removed).
"""
import os
import subprocess
import sys
import tempfile

VARS = "81,84,9b,9f,9c,e9,ac,ab"
here = os.path.dirname(os.path.abspath(__file__))
rom, out = sys.argv[1], sys.argv[2]
with open(out, "w") as f:
    print("// Generated by romconv/internal/hero/tools/trace_fixture.py from MAME a2600;", file=f)
    print("// do not edit. One row per game frame: input (SWCHA high nibble, active", file=f)
    print("// low), expected x, y, screen, thrust, standing, power after the frame.", file=f)
    print("#include <stdint.h>\n\nstruct HeroTraceRow { uint8_t in, x, y, screen, thrust, standing, power; };", file=f)
    print("struct HeroTrace { const char *name; uint8_t frame0, noball; int rows; const HeroTraceRow *row; };\n", file=f)
    traces = []
    for spec in sys.argv[3:]:
        parts = spec.split(":")
        name, script, frames = parts[0], parts[1], parts[2]
        noball = int(len(parts) > 3 and parts[3] == "noball")
        with tempfile.TemporaryDirectory() as work:
            csv = os.path.join(work, "t.csv")
            subprocess.run([sys.executable, "-I", os.path.join(here, "trace.py"), rom, script, frames, csv, VARS],
                           check=True, stdout=subprocess.DEVNULL)
            rows = [l.strip().split(",") for l in open(csv).readlines()[1:]]
        start = next(i for i, r in enumerate(rows) if r[4] != "8b")
        rows = rows[start:]
        print(f"static const HeroTraceRow trace_{name}[] = {{", file=f)
        for r in rows:
            print("  {" + ", ".join("0x" + v for v in r[2:]) + "},", file=f)
        print("};\n", file=f)
        traces.append((name, int(rows[0][1], 16) - 1, noball, len(rows)))
    print("static const HeroTrace hero_traces[] = {", file=f)
    for name, frame0, noball, n in traces:
        print(f'  {{"{name}", 0x{frame0:02x}, {noball}, {n}, trace_{name}}},', file=f)
    print("};", file=f)
print(out)
