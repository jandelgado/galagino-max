#!/usr/bin/env python3
"""MAME traces -> C header for the hero_game host test.

usage: trace_fixture.py <rom.a26> <out.h> <name>:<script.txt>:<frames>[:<skip>] ...
Each script starts game 1 with the reset switch. A trace starts one frame
before the respawn glide (y $9F leaves $8B): the test loads the game state
from that record, then replays the inputs of the following records and
compares. Records: RAM $80-$FF, SWCHA, INPT4 and SWCHB as read in that frame
(harness.lua H_RAM_TAP), stored as changes to the previous record. skip:
start that many records later, after the script's RAM pokes; @n: start at
record n.
"""
import os
import subprocess
import sys
import tempfile

REC = 131
here = os.path.dirname(os.path.abspath(__file__))
rom, out = sys.argv[1], sys.argv[2]
with open(out, "w") as f:
    print("// Generated by romconv/internal/hero/tools/trace_fixture.py from MAME a2600;", file=f)
    print("// do not edit. One record per game frame, taken at the $81 increment:", file=f)
    print("// RAM $80-$FF, then SWCHA, INPT4 and SWCHB as read in that frame. Stored as", file=f)
    print("// changes to the previous record: count, then (index, value) pairs.", file=f)
    print("#include <stdint.h>\n", file=f)
    print("static const int HERO_REC = 131;", file=f)
    print("struct HeroTrace { const char *name; int rows; const uint8_t *delta; };\n", file=f)
    traces = []
    for spec in sys.argv[3:]:
        name, script, frames, *skip = spec.split(":")
        with tempfile.TemporaryDirectory() as work:
            env = dict(os.environ, H_SCRIPT=os.path.abspath(script), H_FRAMES=frames, H_RAM_TAP="1")
            subprocess.run([os.path.join(here, "run_mame.sh"), rom, work], env=env, check=True,
                           stdout=subprocess.DEVNULL)
            ram = open(os.path.join(work, "ram.bin"), "rb").read()
        recs = [ram[i:i + REC] for i in range(0, len(ram) - REC + 1, REC)]
        if skip and skip[0].startswith("@"):
            start = int(skip[0][1:])
        else:
            start = next(i for i, r in enumerate(recs) if r[0x9F - 0x80] != 0x8B) - 1 + int(skip[0] if skip else 0)
        recs = recs[start:]
        data = []
        prev = bytes(REC)
        for r in recs:
            changes = [(i, r[i]) for i in range(REC) if r[i] != prev[i]]
            data.append(len(changes))
            for i, v in changes:
                data += [i, v]
            prev = r
        print(f"static const uint8_t trace_{name}[] = {{", file=f)
        for i in range(0, len(data), 24):
            print("  " + ",".join(str(b) for b in data[i:i + 24]) + ",", file=f)
        print("};\n", file=f)
        traces.append((name, len(recs)))
    print("static const HeroTrace hero_traces[] = {", file=f)
    for name, n in traces:
        print(f'  {{"{name}", {n}, trace_{name}}},', file=f)
    print("};", file=f)
print(out)
