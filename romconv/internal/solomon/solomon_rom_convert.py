#!/usr/bin/env python3
"""Convert the MAME solomon ROM set into galagino headers (MAME tecmo/solomon.cpp)."""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "pyconv"))
from gfxutil import load_file, mame_decode
from asset_emit import emit_compressed, emit_plain

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..", "..")
ZIP = os.path.join(ROOT, "romszip", "solomon.zip")
OUT_DIR = os.path.join(ROOT, "source", "src", "machines", "solomon")
HEADER = "// Generated by romconv/internal/solomon/solomon_rom_convert.py; do not edit.\n"

# MAME ROM_START( solomon )
MAIN_0000 = ("6.3f", "b911aa157ad94aa539dbe329a197d8902860c809")
MAIN_4000_8000 = ("7.3h", "3b6a8dde72cddf95438539c5dc4622c95f932a04")
MAIN_F000 = ("8.3jk", "101acaa19b779cb8b4fffddbe63fe011c7d4b6e9")
AUDIO = ("1.3jk", "713036c0a80b623086aa674bb5f8a135b6fedb01")
FG = [("12.3t", "27302898c64330870c47025e61bd5acbd9483865"),
      ("11.3r", "2e070c0fd5b9d7eb9b7e0d53f25b1a5063ef3095")]
BG = [("10.3p", "8cc87ab8faacdb1973791d207bb25ea9b444b66d"),
      ("9.3m", "0fc3b4a0bd2b17b79e2d1f7d4fe445c09ce4e730")]
SPRITES = [("2.5lm", "8e7a78186473a6b5c42577ac9e4591ee2d1151f2"),
           ("3.6lm", "8eaf3150568c407bd8dc1cdf874b8417e5cca3d2"),
           ("4.7lm", "e29ffb9fcff50ce982d5e502e10a8e29a4c47390"),
           ("5.8lm", "1c7a01dab056ec7d787a6f55772b9fa6fe67305a")]

ARENA_BLOCK_A = 91000
ARENA_BLOCK_B = 110500
HALF = 0x4000
HIGH_ROM = 0x1000  # 8.3jk bytes mapped at f000


def load(entry):
    name, sha1 = entry
    return bytes(load_file(ZIP, [name], sha1))


def step(start, inc, n):
    return [start + i * inc for i in range(n)]


def pack_row(pens):
    v = 0
    for p in pens:
        v = (v << 4) | p
    return v


def main_image():
    # 0000-3fff 6.3f; 7.3h first half -> 8000, ROM_CONTINUE -> 4000;
    # 8.3jk first 0x1000 -> f000 (ROM_IGNORE), stored at image offset c000
    h = load(MAIN_4000_8000)
    return load(MAIN_0000) + h[HALF:] + h[:HALF] + load(MAIN_F000)[:HIGH_ROM]


def decode_tiles(rom):
    # gfx_8x8x4_packed_msb
    tiles = mame_decode(rom, 8, 8, step(0, 1, 4), step(0, 4, 8), step(0, 32, 8), 256, 2048)
    return [pack_row(row) for t in tiles for row in t]


def decode_sprites(rom):
    # spritelayout: bitplanes 512 * 32 * 8 bits apart, plane 0 = MSB
    planes = step(0, 512 * 32 * 8, 4)
    xoffs = step(0, 1, 8) + step(64, 1, 8)
    yoffs = step(0, 8, 8) + step(128, 8, 8)
    sprites = mame_decode(rom, 16, 16, planes, xoffs, yoffs, 256, 512)
    return [[[pack_row(row[0:8]), pack_row(row[8:16])] for row in s] for s in sprites]


def write(name, comment, body):
    path = os.path.join(OUT_DIR, f"{name}.h")
    with open(path, "w", newline="\n") as f:
        f.write(HEADER + f"// {comment}\n")
        body(f)
    print(f"  wrote {path}")


def bytes_body(data):
    return ",\n".join("  " + ",".join(f"0x{b:02x}" for b in data[i:i + 16])
                      for i in range(0, len(data), 16))


def sprites_body(sprites):
    def sprite(s):
        return "{" + ",".join(f"{{0x{a:08x},0x{b:08x}}}" for a, b in s) + "}"
    return ",\n".join("  " + sprite(s) for s in sprites)


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    rom = main_image()
    audio = load(AUDIO)
    fg = decode_tiles(b"".join(load(e) for e in FG))
    bg = decode_tiles(b"".join(load(e) for e in BG))
    sprites = decode_sprites(b"".join(load(e) for e in SPRITES))
    assert len(rom) == 0xd000 and len(audio) == 0x4000

    # PLAIN: no Arena room left after both tile sets (bg + audio fill block A,
    # fg block B); the main ROM compresses badly and sprites are read least
    write("solomon_main_rom", "main Z80 0000-bfff, f000-ffff at offset c000, flash",
          lambda f: emit_plain(f, "solomon_main_rom", "unsigned char", "", len(rom), bytes_body(rom)))
    write("solomon_sprites", "512 sprites 16x16 4 bpp, [row][0] px 0-7, [row][1] px 8-15, "
          "first in bits 31-28, flash",
          lambda f: emit_plain(f, "solomon_sprites", "uint32_t", "[16][2]", 512, sprites_body(sprites)))
    write("solomon_audio_rom", "sound Z80 0000-3fff",
          lambda f: emit_compressed(f, "solomon_audio_rom", "unsigned char", "", len(audio), list(audio)))
    write("solomon_fg_tiles", "2048 fg chars 8x8 4 bpp, pixel 0 in bits 31-28",
          lambda f: emit_compressed(f, "solomon_fg_tiles", "uint32_t", "[8]", 2048, fg))
    write("solomon_bg_tiles", "2048 bg chars 8x8 4 bpp, pixel 0 in bits 31-28",
          lambda f: emit_compressed(f, "solomon_bg_tiles", "uint32_t", "[8]", 2048, bg))

    # unpack order in the ctor: bg -> A, fg -> B, audio -> A
    sizes = {"bg": len(bg) * 4, "fg": len(fg) * 4, "audio": len(audio)}
    total = sum(sizes.values())
    print("  Arena budget: " + ", ".join(f"{k} {v}" for k, v in sizes.items())
          + f" = {total} / {ARENA_BLOCK_A + ARENA_BLOCK_B} bytes")
    assert sizes["bg"] + sizes["audio"] <= ARENA_BLOCK_A and sizes["fg"] <= ARENA_BLOCK_B
    print(f"  flash PLAIN: main {len(rom)}, sprites {len(sprites) * 128}")


if __name__ == "__main__":
    main()
