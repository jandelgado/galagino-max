#!/usr/bin/env python3
"""MAME solomon frames -> test fixture: RAM + per-line CRC32 of the cropped snapshot.

Usage: mame_fixture.py <dump dir> <frame>:<snapshot png> ...
The dump dir holds <frame>.txt from mame_fixture.lua.
"""
import binascii
import os
import struct
import sys

from PIL import Image

CROP_LEFT, OUT_WIDTH, NATIVE_WIDTH, LINES = 8, 240, 256, 224
# HUD lines as solomon_video.h hudTopX / hudBottomX
HUD_TOP_LINES, HUD_BOTTOM, HUD_TOP_KEEP, HUD_TOP_DROP, HUD_BOTTOM_KEEP = 8, 208, 16, 8, 120


def native_x(line, col):
    if line < HUD_TOP_LINES:
        return col if col < HUD_TOP_KEEP else col + HUD_TOP_DROP
    if line >= HUD_BOTTOM:
        return col if col < HUD_BOTTOM_KEEP else col + NATIVE_WIDTH - OUT_WIDTH
    return col + CROP_LEFT
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "source", "test",
                   "test_solomon", "mame_frames.h")


def rgb565_swapped(r, g, b):
    c = ((r & 0xf8) << 8) | ((g & 0xfc) << 3) | (b >> 3)
    return struct.pack("<H", ((c >> 8) | (c << 8)) & 0xffff)


def line_crcs(png):
    im = Image.open(png).convert("RGB")
    assert im.size == (NATIVE_WIDTH, LINES), im.size
    crcs = []
    for y in range(LINES):
        raw = b"".join(rgb565_swapped(*im.getpixel((native_x(y, x), y))) for x in range(OUT_WIDTH))
        crcs.append(binascii.crc32(raw) & 0xffffffff)
    return crcs


def arr(hexstr):
    return "{" + ",".join(f"0x{hexstr[i:i + 2]}" for i in range(0, len(hexstr), 2)) + "}"


def main():
    d, picks = sys.argv[1], sys.argv[2:]
    with open(OUT, "w", newline="\n") as f:
        f.write("// MAME solomon frames: video RAM d000-dfff, palette e400-e5ff, sprites\n"
                "// e000-e07f of frame - 1 (snapshot lag), CRC32 per 240 px line of the\n"
                "// snapshot cropped to x 8..247, HUD lines as hudTopX/hudBottomX\n"
                "// (RGB565 swapped as galagino).\n"
                "// Generated by romconv/internal/solomon/mame_fixture.py.\n"
                "#include <stdint.h>\n\nstruct MameFrame {\n  uint32_t frame;\n"
                "  uint8_t vram[0x1000];\n  uint8_t pal[0x200];\n  uint8_t spr[0x80];\n"
                "  uint32_t line_crc[224];\n};\n\nstatic const MameFrame MAME_FRAMES[] = {\n")
        for p in picks:
            frame, png = p.split(":")
            vram, pal, spr = open(os.path.join(d, f"{frame}.txt")).read().split()
            crcs = ",".join(f"0x{c:08x}u" for c in line_crcs(png))
            f.write(f"  {{{frame},\n   {arr(vram)},\n   {arr(pal)},\n   {arr(spr)},\n   {{{crcs}}}}},\n")
        f.write("};\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
