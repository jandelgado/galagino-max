#!/usr/bin/env python3
"""Convert the MAME tappera ROM set into galagino headers (MAME midway/mcr.cpp, mcr_m.cpp, midway.cpp).

Tapper (Budweiser, 1/12/84) is 512x480 ROT0 with 8x8 tiles doubled by the
hardware. galagino shows it at half resolution: tiles 1:1, 32x32 sprites
downsampled to 16x16 (one sampling variant per X flip; the game never sets
Y flip). Render maps native (x, y) to panel column x - 8, row y + 24.

romszip/tapper.zip holds the tappera program ROMs and the shared graphics
and sound ROMs under their old names.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "pyconv"))
from gfxutil import load_file
from mcr_hw import decode_tiles_raw, decode_sprites_raw, duty_gain
from asset_emit import emit_compressed

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..", "..")
ZIP = os.path.join(ROOT, "romszip", "tapper.zip")
SSIO_ZIP = os.path.join(ROOT, "romszip", "midssio.zip")
OUT_DIR = os.path.join(ROOT, "source", "src", "machines", "tapper")

# MAME ROM_START( tappera )
MAIN = [
    ("tappg0.bin", "373e9a9d73b71e100c02862662d025f5ead2f94d"),
    ("tappg1.bin", "e493e46fc70a765e54bfdd7ba7ca570e6a5c79d6"),
    ("tappg2.bin", "cb46a2248289ced7282b1463f433dcb970c42c1a"),
    ("tappg3.bin", "45bf1571a2418c7dc00ccc7061a3e04e65cb6bff"),
]
SOUND = [
    ("tapsnda7.bin", "9e281c340b7702523c86d56317efad9e3688e585"),
    ("tapsnda8.bin", "14334b9d2bfece3fe5bda0cbd53158ead8d27e53"),
    ("tapsnda9.bin", "b38bba5f12516d899e023f99147868e3402fbd7b"),
    ("tapsda10.bin", "0011407c1e886071282808c0a561789b1245a789"),
]
TILES = [
    ("tapbg1.bin", "eb30b9bb654324340f0fc5b44776ac2440c1e869"),
    ("tapbg0.bin", "23e29ec942e1e7516ae8068837af2d1c79592378"),
]
SPRITES = [
    ("tapfg1.bin", "a38667573d235efe2dc515e52af05825fe4e0f30"),
    ("tapfg0.bin", "2077f79177fda26f9c674b2ab525ec3833802059"),
    ("tapfg3.bin", "930142dd73fb30c4d3ec09a1e37517c6c6774024"),
    ("tapfg2.bin", "d553b8517c1d03a2be0b065f4da2fa99d9e6fb30"),
    ("tapfg5.bin", "8aead89e1adaee5f0b679661c4bfba36e0d639e8"),
    ("tapfg4.bin", "402c166d50b4a693959b3f0706a7931a5daef6ce"),
    ("tapfg7.bin", "95879a455ecfe2e3de7fe2a75078f9e6934960f5"),
    ("tapfg6.bin", "a24696f16d467d9eea4f25aef5f4c5ff55bf51ff"),
]
SSIO_PROM = ("82s123.12d", "9ac9b01d24affc0ee9227a4364c4fd8f8290343a")

ARENA_BUDGET = 182000


def load(zip_path, entry):
    name, sha1 = entry
    return bytes(load_file(zip_path, [name], sha1))


def load_all(entries):
    return b"".join(load(ZIP, e) for e in entries)


def pack_row(pens):
    # first pixel in the top nibble
    v = 0
    for p in pens:
        v = (v << 4) | p
    return v


def downsample(sprite, px, py):
    # 2:1 per axis, pixel (2k + px, 2l + py) of each block: what a 2:1
    # nearest scale of MAME's view shows. Sprites sit at even full-res
    # positions, so it samples even columns and rows; X flip swaps the
    # column parity.
    return [[sprite[2 * l + py][2 * k + px] for k in range(16)] for l in range(16)]


def header(path, comment):
    f = open(path, "w", newline="\n")
    f.write("// Generated by romconv/internal/tapper/tapper_rom_convert.py; do not edit.\n")
    f.write(f"// {comment}\n")
    return f


def emit(name, ctype, dims, count, flat, comment):
    path = os.path.join(OUT_DIR, f"{name}.h")
    with header(path, comment) as out:
        emit_compressed(out, name, ctype, dims, count, flat)
    print(f"  wrote {path}")


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    main_rom = load_all(MAIN)
    sound_rom = load_all(SOUND)
    tiles = decode_tiles_raw(load_all(TILES))
    sprites = decode_sprites_raw(load_all(SPRITES))
    gain = duty_gain(load(SSIO_ZIP, SSIO_PROM))

    tile_rows = [pack_row(row) for t in tiles for row in t]
    # 2 sampling variants: index flip_x * count + code
    sprite_rows = []
    for flip_x in range(2):
        for s in sprites:
            for row in downsample(s, flip_x, 0):
                sprite_rows += [pack_row(row[:8]), pack_row(row[8:])]

    emit("tapper_rom", "unsigned char", "", len(main_rom), list(main_rom), "main Z80 ROM 0x0000-0xdfff")
    emit("tapper_snd_rom", "unsigned char", "", len(sound_rom), list(sound_rom), "SSIO Z80 ROM 0x0000-0x3fff")
    emit("tapper_tilemap", "uint32_t", "[8]", len(tiles), tile_rows,
         f"{len(tiles)} tiles 8x8 4 bpp, row = 8 pens, first in bits 31-28")
    emit("tapper_spritemap", "uint32_t", "[16][2]", len(sprites) * 2, sprite_rows,
         f"{len(sprites)} sprites 32x32 downsampled to 16x16 4 bpp in 2 X flip variants, [row][0] pens 0-7, first in bits 31-28")

    path = os.path.join(OUT_DIR, "tapper_ssio_prom.h")
    with header(path, "SSIO AY voice gain / 16 per duty-cycle nibble (PROM 82s123.12d)") as f:
        f.write("static const uint8_t tapper_ssio_duty_gain[16] = { " + ", ".join(map(str, gain)) + " };\n")
    print(f"  wrote {path}: {gain}")

    sizes = {"main": len(main_rom), "sound": len(sound_rom),
             "tilemap": len(tile_rows) * 4, "spritemap": len(sprite_rows) * 4}
    total = sum(sizes.values())
    print(f"  tiles {len(tiles)}, sprites {len(sprites)}")
    print("  Arena budget: " + ", ".join(f"{k} {v}" for k, v in sizes.items())
          + f" = {total} / {ARENA_BUDGET} bytes")
    assert total < ARENA_BUDGET


if __name__ == "__main__":
    main()
