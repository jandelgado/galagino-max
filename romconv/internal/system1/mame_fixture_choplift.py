#!/usr/bin/env python3
"""MAME chopliftu frames -> host test fixture: RAM + per-line CRC32 of the
240 px window x 8..247 (Choplifter's fixed window) of the snapshot.

Usage: mame_fixture_choplift.py <dump dir> <frame>:<snapshot png> ...
The dump dir holds <frame>.txt from mame_fixture_choplift.lua.
"""
import binascii
import os
import sys

from PIL import Image

from mame_fixture import arr, rgb565_swapped

OUT_WIDTH, NATIVE_WIDTH, LINES, WINDOW = 240, 256, 224, 8
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "source",
                   "test", "test_choplift_video", "mame_choplift_frames.h")


# snapshot is 512 wide: half-res x samples the even 512 position
def line_crcs(png):
    im = Image.open(png).convert("RGB")
    assert im.size == (2 * NATIVE_WIDTH, LINES), im.size
    return [binascii.crc32(b"".join(rgb565_swapped(*im.getpixel((2 * x, y)))
                                    for x in range(WINDOW, WINDOW + OUT_WIDTH))) & 0xffffffff
            for y in range(LINES)]


def main():
    d, picks = sys.argv[1], sys.argv[2:]
    with open(OUT, "w", newline="\n") as f:
        f.write("// MAME chopliftu frames: video RAM e000-efff (pages 0 and 1), palette\n"
                "// RAM d800-ddff, sprite RAM d000-d7ff of the same frame, CRC32 per line\n"
                f"// of the snapshot window x {WINDOW} .. {WINDOW + OUT_WIDTH - 1} (RGB565 swapped).\n"
                "// Generated by romconv/internal/system1/mame_fixture_choplift.py.\n\n")
        f.write("static const MameFrame MAME_CHOPLIFT[] = {\n")
        for p in picks:
            frame, png = p.split(":")
            vram, pal, spr = open(os.path.join(d, f"{frame}.txt")).read().split()
            crcs = ",".join(f"0x{c:08x}u" for c in line_crcs(png))
            f.write(f"  {{{frame},\n   {arr(vram)},\n   {arr(pal)},\n   {arr(spr)},\n"
                    f"   {{{crcs}}}}},\n")
        f.write("};\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
