#!/usr/bin/env python3
"""Convert the MAME gravitar (Gravitar version 3) ROM set into galagino headers."""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "pyconv"))
from gfxutil import load_file
from asset_emit import emit_compressed

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..", "..")
ARCHIVE = os.path.join(ROOT, "romszip", "gravitar.zip")
OUT_DIR = os.path.join(ROOT, "source", "src", "machines", "gravitar")

# MAME gravitar: name -> SHA1. Dropped: the AVG state PROM 136002-125.n4
# (the display list is decoded at a high level) and the address decoding
# PROMs 136010-111.r1 / 136010-112.r2.
PROGRAM = [  # 0x9000-0xefff; 0xf000-0xffff repeats 306.m1
    ("136010-301.d1", "800b52ead9f56a3e372797fbc698c8fc791398da"),
    ("136010-302.ef1", "b9e846db14fa23f8d2def97030d8b072b2bbc0be"),
    ("136010-303.h1", "e09f58f6f36de6bf6724a1ab14ab35acbb0b3876"),
    ("136010-304.j1", "822b06be6f2d6298b2b10161fbabbb2caa74b2ef"),
    ("136010-305.kl1", "4a7124f91d3ee940686c51374a861efe6cb5d282"),
    ("136010-306.m1", "baf080deaa8eea43af2f3be71dacc63e4666c453"),
]
VECTOR = [  # 0x2800-0x5fff
    ("136010-210.l7", "2c50cd38d60739c126f1d0d8e7fbd46a0bde6e1c"),
    ("136010-207.mn7", "301ddb7a34b38140a1fdffc060cb08ff57f10cf1"),
    ("136010-208.np7", "9c2920cf2b73a93ac2808be654b08505037f53b1"),
    ("136010-309.r7", "5164f2a54244ce1e863d1ec0dd29bc9da7103a85"),
]
PROGRAM_BYTES = 0x6000
VECTOR_BYTES = 0x3800

# dvgMachine::MAX_LINES vec2d::Line (16 B) + StripRasterizer next/active
# (2 x uint16_t per line) + 36 strip heads, allocated in start()
MAX_LINES = 1024
LINE_BUFFER_BYTES = MAX_LINES * 16 + MAX_LINES * 2 * 2 + 36 * 2
# GO list: decode buffer (vec2d::Line per line) and published PackedLine
# (8 B) list (+ 2 B count + 4 B sequence)
GO_LIST_BYTES = MAX_LINES * 16 + MAX_LINES * 8 + 8


def load_all(files):
    return b"".join(bytes(load_file(ARCHIVE, [name], sha1)) for name, sha1 in files)


def write(filename, symbol, data, description):
    path = os.path.join(OUT_DIR, filename)
    with open(path, "w", newline="\n") as out:
        out.write("// Generated by romconv/internal/gravitar/gravitar_rom_convert.py; do not edit.\n")
        out.write(f"// {description}\n")
        emit_compressed(out, symbol, "unsigned char", "", len(data), list(data))
    print(f"  wrote {path}: {len(data)} bytes")
    return len(data)


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    program, vector = load_all(PROGRAM), load_all(VECTOR)
    assert len(program) == PROGRAM_BYTES and len(vector) == VECTOR_BYTES
    total = write("gravitar_rom.h", "gravitar_rom", program,
                  "Main M6502 ROM, 24 KiB mapped at 0x9000-0xefff; 0xf000-0xffff mirrors 0xe000.")
    total += write("gravitar_vrom.h", "gravitar_vrom", vector,
                   "AVG vector ROM, 14 KiB mapped at 0x2800-0x5fff.")
    total += LINE_BUFFER_BYTES + GO_LIST_BYTES
    print(f"  Arena budget: {total} / 182000 bytes")
    if total >= 182000:
        sys.exit("ERROR: Arena budget exceeded")


if __name__ == "__main__":
    main()
