#!/usr/bin/env python3
"""MAME arkangc frames -> test fixture: video RAM + per-line CRC32 of the snapshot.

Usage: mame_fixture.py <dump dir> <frame>:<snapshot png> ...
The dump dir holds <frame>.txt from mame_fixture.lua.
"""
import binascii
import os
import struct
import sys

from PIL import Image

WIDTH, LINES = 224, 256   # MAME snapshot, already rotated (ROT90)
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "source", "test",
                   "test_arkanoid_video", "mame_frames.h")


def rgb565_swapped(r, g, b):
    c = ((r & 0xf8) << 8) | ((g & 0xfc) << 3) | (b >> 3)
    return struct.pack("<H", ((c >> 8) | (c << 8)) & 0xffff)


def line_crcs(png):
    im = Image.open(png).convert("RGB")
    assert im.size == (WIDTH, LINES), im.size
    return [binascii.crc32(b"".join(rgb565_swapped(*im.getpixel((x, y))) for x in range(WIDTH))) & 0xffffffff
            for y in range(LINES)]


def arr(hexstr):
    return "{" + ",".join(f"0x{hexstr[i:i + 2]}" for i in range(0, len(hexstr), 2)) + "}"


def main():
    d, picks = sys.argv[1], sys.argv[2:]
    with open(OUT, "w", newline="\n") as f:
        f.write("// MAME arkangc frames F: video RAM e000-e83f + d008 latch of F and F-1\n"
                "// (snapshot may show sprites one frame late), CRC32 per 224 px line of\n"
                "// the snapshot (RGB565 swapped as galagino).\n"
                "// Generated by romconv/internal/arkanoid/mame_fixture.py.\n"
                "#include <stdint.h>\n\nstruct MameFrame {\n  uint32_t frame;\n"
                "  uint8_t ram[0x841];\n  uint8_t prev[0x841];\n"
                "  uint32_t line_crc[256];\n};\n\nstatic const MameFrame MAME_FRAMES[] = {\n")
        for p in picks:
            frame, png = p.split(":")
            ram, prev = open(os.path.join(d, f"{frame}.txt")).read().split()
            crcs = ",".join(f"0x{c:08x}u" for c in line_crcs(png))
            f.write(f"  {{{frame},\n   {arr(ram)},\n   {arr(prev)},\n   {{{crcs}}}}},\n")
        f.write("};\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
