#!/usr/bin/env python3
"""Convert the MAME dotron ROM set into galagino headers (MAME midway/mcr.cpp, mcr_m.cpp, midway.cpp).

Discs of Tron (upright 10/4/83) is 512x480, ORIENTATION_FLIP_X, with 8x8
tiles doubled by the hardware. galagino shows it at half resolution: tiles
1:1, 32x32 sprites downsampled to 16x16 (one sampling variant per flip). Both are stored mirrored in X, as
the player sees them; render then maps native (x, y) to panel column
247 - x, row y + 24.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "pyconv"))
from gfxutil import load_file
from mcr_hw import decode_tiles_raw, decode_sprites_raw, duty_gain
from asset_emit import emit_compressed

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..", "..")
ZIP = os.path.join(ROOT, "romszip", "dotron.zip")
SSIO_ZIP = os.path.join(ROOT, "romszip", "midssio.zip")
OUT_DIR = os.path.join(ROOT, "source", "src", "machines", "dotron")

# MAME ROM_START( dotron ), upright 10/4/83
MAIN = [
    ("disc_tron_uprt_pg0_10-4-83.1c", "e06a8097f02b9f445df0dd5c0ec13f9a0a1dcd8a"),
    ("disc_tron_uprt_pg1_10-4-83.2c", "8a1f088de9289cd902e72b55d3e72c3f07246778"),
    ("disc_tron_uprt_pg2_10-4-83.3c", "c773a68891fbf94808a2ee0036928c0c48d6673d"),
    ("disc_tron_uprt_pg3_10-4-83.4c", "9f861f99cb170513b68aee48bbfd60ee439d7fa9"),
]
SOUND = [
    ("disc_tron_uprt_snd0_10-4-83.a7", "6d538a3e48f98e269623850f1f6774848a89fd59"),
    ("disc_tron_uprt_snd1_10-4-83.a8", "5c9a64604252eea0628bf9d6221e8add82f66abe"),
    ("disc_tron_uprt_snd2_9-22-83.a9", "261b0463a73b403bc46df3e04f3d12173787d6e7"),
    ("disc_tron_uprt_snd3_9-22-83.a10", "039d8d664f067bc0d085ad7730ef63dbd6dc387e"),
]
TILES = [
    ("loc-bg2.6f", "782c8192dd58a3f23ff2338452dd03206d79030a"),
    ("loc-bg1.5f", "8044be9ffca9520fd77e0da492147e553f9f7da3"),
]
SPRITES = [
    ("loc-g.cp4", "b97539ffd2f5fc8b86fc2f8f233cc26ba16f82ee"),
    ("loc-h.cp3", "3795ba1640790041da51ebeac8517cc7d32e243e"),
    ("loc-e.cp6", "24177a8dd6dcb377cf8aee7c7b47b26f29e77e20"),
    ("loc-f.cp5", "b7fb3d1df9b80c056cf131574565addb529645e1"),
    ("loc-c.cp8", "6cd83909b4376abce287e435a10e5bc25e18b265"),
    ("loc-d.cp7", "74983c922eae1326ecd0ff14000851e0b424cc61"),
    ("loc-a.cp0", "3f330ffde52ac57c02dfdf8e105aefcc10f87a0b"),
    ("loc-b.cp9", "9dfafd58bd552bfda4e1799a175735ecc1369ba3"),
]
SSIO_PROM = ("82s123.12d", "9ac9b01d24affc0ee9227a4364c4fd8f8290343a")

ARENA_BUDGET = 182000


def load(zip_path, entry):
    name, sha1 = entry
    return bytes(load_file(zip_path, [name], sha1))


def load_all(entries):
    return b"".join(load(ZIP, e) for e in entries)


def pack_row(pens):
    # first pixel in the top nibble
    v = 0
    for p in pens:
        v = (v << 4) | p
    return v


def mirror(grid):
    # ORIENTATION_FLIP_X: the player sees native X mirrored
    return [row[::-1] for row in grid]


def downsample(sprite, px, py):
    # 2:1 per axis, pixel (2k + px, 2l + py) of each block: what a 2:1
    # nearest scale of MAME's player view shows. Sprites sit at even
    # full-res positions and the view is mirrored, so it samples odd native
    # columns and even rows; native flips swap that parity.
    return [[sprite[2 * l + py][2 * k + px] for k in range(16)] for l in range(16)]


def header(path, comment):
    f = open(path, "w", newline="\n")
    f.write("// Generated by romconv/internal/dotron/dotron_rom_convert.py; do not edit.\n")
    f.write(f"// {comment}\n")
    return f


def emit(name, ctype, dims, count, flat, comment):
    path = os.path.join(OUT_DIR, f"{name}.h")
    with header(path, comment) as out:
        emit_compressed(out, name, ctype, dims, count, flat)
    print(f"  wrote {path}")


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    main_rom = load_all(MAIN)
    sound_rom = load_all(SOUND)
    tiles = decode_tiles_raw(load_all(TILES))
    sprites = decode_sprites_raw(load_all(SPRITES))
    gain = duty_gain(load(SSIO_ZIP, SSIO_PROM))

    tile_rows = [pack_row(row) for t in tiles for row in mirror(t)]
    # 4 sampling variants: index (flip_y << 1 | flip_x) * count + code
    sprite_rows = []
    for flip_y in range(2):
        for flip_x in range(2):
            for s in sprites:
                for row in mirror(downsample(s, 1 - flip_x, flip_y)):
                    sprite_rows += [pack_row(row[:8]), pack_row(row[8:])]

    emit("dotron_rom", "unsigned char", "", len(main_rom), list(main_rom), "main Z80 ROM 0x0000-0xdfff")
    emit("dotron_snd_rom", "unsigned char", "", len(sound_rom), list(sound_rom), "SSIO Z80 ROM 0x0000-0x3fff")
    emit("dotron_tilemap", "uint32_t", "[8]", len(tiles), tile_rows,
         f"{len(tiles)} tiles 8x8 4 bpp, mirrored in X, row = 8 pens, first in bits 31-28")
    emit("dotron_spritemap", "uint32_t", "[16][2]", len(sprites) * 4, sprite_rows,
         f"{len(sprites)} sprites 32x32 downsampled to 16x16 4 bpp in 4 flip variants, mirrored in X, [row][0] pens 0-7, first in bits 31-28")

    path = os.path.join(OUT_DIR, "dotron_ssio_prom.h")
    with header(path, "SSIO AY voice gain / 16 per duty-cycle nibble (PROM 82s123.12d)") as f:
        f.write("static const uint8_t dotron_ssio_duty_gain[16] = { " + ", ".join(map(str, gain)) + " };\n")
    print(f"  wrote {path}: {gain}")

    sizes = {"main": len(main_rom), "sound": len(sound_rom),
             "tilemap": len(tile_rows) * 4, "spritemap": len(sprite_rows) * 4}
    total = sum(sizes.values())
    print(f"  tiles {len(tiles)}, sprites {len(sprites)}")
    print("  Arena budget: " + ", ".join(f"{k} {v}" for k, v in sizes.items())
          + f" = {total} / {ARENA_BUDGET} bytes")
    assert total < ARENA_BUDGET


if __name__ == "__main__":
    main()
