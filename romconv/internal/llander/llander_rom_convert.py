#!/usr/bin/env python3
"""Convert the MAME llander (Lunar Lander rev 2) ROM set into galagino headers."""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "pyconv"))
from gfxutil import load_file
from asset_emit import emit_compressed

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..", "..")
ARCHIVE = os.path.join(ROOT, "romszip", "llander.zip")
OUT_DIR = os.path.join(ROOT, "source", "src", "machines", "llander")

# MAME llander: name -> SHA1, in address order. The DVG state PROM
# 034602-01.c8 is dropped: the display list is decoded at a high level.
PROGRAM = [  # 0x6000-0x7fff
    ("034572-02.f1", "5a15eaeaf825ccdf9ce013a6789cf51da20f785c"),
    ("034571-02.de1", "4be6cef5af38734d580cbfb7e4070fe7981ddfd6"),
    ("034570-01.c1", "ecf4430a0040c227c896aa2cd81ee03960b4d641"),
    ("034569-02.b1", "9b21ba5e1518079c326ca6e15b9993e6c4483caa"),
]
VECTOR = [  # 0x4800-0x5fff
    ("034599-01.r3", "6ecb40169b797d9eb623bcb17872f745b1bf20fa"),
    ("034598-01.np3", "eb4ffc289d254f699f821df3146aa2c6cd78597f"),
    ("034597-01.m3", "e685b094c1261a351e4e82dfb487462163f136a4"),
]

# dvgMachine::MAX_LINES vec2d::Line (16 B) + StripRasterizer next/active
# (2 x uint16_t per line) + 36 strip heads, allocated in start()
MAX_LINES = 1024
LINE_BUFFER_BYTES = MAX_LINES * 16 + MAX_LINES * 2 * 2 + 36 * 2
# GO list: decode buffer (vec2d::Line per line) and published PackedLine
# (8 B) list (+ 2 B count + 4 B sequence)
GO_LIST_BYTES = MAX_LINES * 16 + MAX_LINES * 8 + 8


def load_all(files):
    return b"".join(bytes(load_file(ARCHIVE, [name], sha1)) for name, sha1 in files)


def write(filename, symbol, data, description):
    path = os.path.join(OUT_DIR, filename)
    with open(path, "w", newline="\n") as out:
        out.write("// Generated by romconv/internal/llander/llander_rom_convert.py; do not edit.\n")
        out.write(f"// {description}\n")
        emit_compressed(out, symbol, "unsigned char", "", len(data), list(data))
    print(f"  wrote {path}: {len(data)} bytes")
    return len(data)


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    total = write("llander_rom.h", "llander_rom", load_all(PROGRAM),
                  "Main M6502 ROM, 8 KiB mapped at 0x6000-0x7fff.")
    total += write("llander_vrom.h", "llander_vrom", load_all(VECTOR),
                   "DVG vector ROM, 6 KiB mapped at 0x4800-0x5fff.")
    total += LINE_BUFFER_BYTES + GO_LIST_BYTES
    print(f"  Arena budget: {total} / 182000 bytes")
    if total >= 182000:
        sys.exit("ERROR: Arena budget exceeded")


if __name__ == "__main__":
    main()
