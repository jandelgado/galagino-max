#!/usr/bin/env python3
"""Convert the MAME spacduel (Space Duel version 2) ROM set into galagino headers."""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "pyconv"))
from gfxutil import load_file
from asset_emit import emit_compressed

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..", "..")
ARCHIVE = os.path.join(ROOT, "romszip", "spacduel.zip")
OUT_DIR = os.path.join(ROOT, "source", "src", "machines", "spacduel")

# MAME spacduel: name -> SHA1. The AVG state PROM 136002-125.n4 is dropped:
# the display list is decoded at a high level.
PROGRAM = [
    ("136006-201.r1", "9bacb64d257edd31f53db878477604f50681d78f"),
    ("136006-102.np1", "c05c52bb08acccb60950a15f05c960c3bc163d3e"),
    ("136006-103.m1", "d36d62cdf7fe76ee9cdbfc2e76ac5d90f22986ba"),
    ("136006-104.kl1", "9e8773e78d65d74db824cfd7108e7038f26757db"),
    ("136006-105.j1", "b15891d22a47ac3448d2ced40c04d0ab80606c7d"),
]
VECTOR = [
    ("136006-106.r7", "f53be76a49dba319050ca7767de3441521910e83"),
    ("136006-107.np7", "58060b20b2511d30d2ec06479d21840bdd0b53c6"),
]

# dvgMachine::MAX_LINES vec2d::Line (16 B) + StripRasterizer next/active
# (2 x uint16_t per line) + 36 strip heads, allocated in start()
MAX_LINES = 1024
LINE_BUFFER_BYTES = MAX_LINES * 16 + MAX_LINES * 2 * 2 + 36 * 2
# GO list: decode buffer (vec2d::Line per line) and published PackedLine
# (8 B) list (+ 2 B count + 4 B sequence)
GO_LIST_BYTES = MAX_LINES * 16 + MAX_LINES * 8 + 8


def load_all(files):
    return b"".join(bytes(load_file(ARCHIVE, [name], sha1)) for name, sha1 in files)


def write(filename, symbol, data, description):
    path = os.path.join(OUT_DIR, filename)
    with open(path, "w", newline="\n") as out:
        out.write("// Generated by romconv/internal/spacduel/spacduel_rom_convert.py; do not edit.\n")
        out.write(f"// {description}\n")
        emit_compressed(out, symbol, "unsigned char", "", len(data), list(data))
    print(f"  wrote {path}: {len(data)} bytes")
    return len(data)


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    total = write("spacduel_rom.h", "spacduel_rom", load_all(PROGRAM),
                  "Main M6502 ROM, 20 KiB mapped at 0x4000-0x8fff; 0x9000-0xffff mirrors 0x8000.")
    total += write("spacduel_vrom.h", "spacduel_vrom", load_all(VECTOR),
                   "AVG vector ROM, 6 KiB mapped at 0x2800-0x3fff.")
    total += LINE_BUFFER_BYTES + GO_LIST_BYTES
    print(f"  Arena budget: {total} / 182000 bytes")
    if total >= 182000:
        sys.exit("ERROR: Arena budget exceeded")


if __name__ == "__main__":
    main()
