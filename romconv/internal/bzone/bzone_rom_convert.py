#!/usr/bin/env python3
"""Convert the MAME bzone (Battle Zone rev 2) ROM set into galagino headers."""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "pyconv"))
from gfxutil import load_file
from asset_emit import emit_compressed

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..", "..")
ARCHIVE = os.path.join(ROOT, "romszip", "bzone.zip")
OUT_DIR = os.path.join(ROOT, "source", "src", "machines", "bzone")

# MAME bzone: name -> SHA1. The AVG state PROM 036408-01.k7 and the
# Mathbox PROMs are dropped: display list and Mathbox are emulated at a
# high level.
PROGRAM = [
    ("036414-02.e1", "40e356ddc5c042bc1ce0b71f51e8b6de72daf1e4"),
    ("036413-01.h1", "42638cff53a9791a0f18d316f62a0ea8eea4e194"),
    ("036412-01.j1", "6bbb8316d9f8588ea0893932f9174788292b8edc"),
    ("036411-01.k1", "54c5e06b2e69eb731a6c9b1704e4340f493e7ea5"),
    ("036410-01.lm1", "33ae0f68b4e2eae9f3aecbee2d0b29003ce460b2"),
    ("036409-01.n1", "448fab30535e6fad7e0ab4427bc06bbbe075e797"),
]
VECTOR = [
    ("036422-01.bc3", "147d97a3b475e738ce00b1a7909bbd787ad06eda"),
    ("036421-01.a3", "b71e0ab0e220c3e64dc2b094c701fb1a960b64e4"),
]

# dvgMachine::MAX_LINES vec2d::Line (16 B) + StripRasterizer next/active
# (2 x uint16_t per line) + 36 strip heads, allocated in start()
MAX_LINES = 1024
LINE_BUFFER_BYTES = MAX_LINES * 16 + MAX_LINES * 2 * 2 + 36 * 2


def load_all(files):
    return b"".join(bytes(load_file(ARCHIVE, [name], sha1)) for name, sha1 in files)


def write(filename, symbol, data, description):
    path = os.path.join(OUT_DIR, filename)
    with open(path, "w", newline="\n") as out:
        out.write("// Generated by romconv/internal/bzone/bzone_rom_convert.py; do not edit.\n")
        out.write(f"// {description}\n")
        emit_compressed(out, symbol, "unsigned char", "", len(data), list(data))
    print(f"  wrote {path}: {len(data)} bytes")
    return len(data)


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    total = write("bzone_rom.h", "bzone_rom", load_all(PROGRAM),
                  "Main M6502 ROM, 12 KiB mapped at 0x5000-0x7fff.")
    total += write("bzone_vrom.h", "bzone_vrom", load_all(VECTOR),
                   "AVG vector ROM, 4 KiB mapped at 0x3000-0x3fff.")
    total += LINE_BUFFER_BYTES
    print(f"  Arena budget: {total} / 182000 bytes")
    if total >= 182000:
        sys.exit("ERROR: Arena budget exceeded")


if __name__ == "__main__":
    main()
