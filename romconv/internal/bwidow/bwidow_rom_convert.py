#!/usr/bin/env python3
"""Convert the MAME bwidow (Black Widow) ROM set into galagino headers."""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "pyconv"))
from gfxutil import load_file
from asset_emit import emit_compressed

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..", "..")
ARCHIVE = os.path.join(ROOT, "romszip", "bwidow.zip")
OUT_DIR = os.path.join(ROOT, "source", "src", "machines", "bwidow")

# MAME bwidow: name -> SHA1. Dropped: the AVG state PROM 136002-125.n4
# (the display list is decoded at a high level).
PROGRAM = [  # 0x9000-0xefff; 0xf000-0xffff repeats 106.m1
    ("136017-101.d1", "b62f7622ca60248e1b8376ee135ae3d94d0b4437"),
    ("136017-102.ef1", "614c74daa468a7430ed965a3a9d07b6ad846016c"),
    ("136017-103.h1", "3aa6c40721a4289c1cf01f37c89b6b0a96336c68"),
    ("136017-104.j1", "e83d8242e4592149719be6a68cf3aba46116072f"),
    ("136017-105.kl1", "33da2ba3cefa3d0dddc8647f9b6caf5d5bfe9b3b"),
    ("136017-106.m1", "f1398e3ff2b62af1509bc117028845b671ff1ca2"),
]
VECTOR = [  # 0x2800-0x5fff
    ("136017-107.l7", "bbae93058228820ee67b05f23e45fb54ee0963ff"),
    ("136017-108.mn7", "935295d66ad40ad702eb7a694296e836f53d22ec"),
    ("136017-109.np7", "2b324877bf55151747eaacd9a58f846712bfbc14"),
    ("136017-110.r7", "72aa1d24f20cc86701189df486488edc434b1be1"),
]
PROGRAM_BYTES = 0x6000
VECTOR_BYTES = 0x3800

# dvgMachine::MAX_LINES vec2d::Line (16 B) + StripRasterizer next/active
# (2 x uint16_t per line) + 36 strip heads, allocated in start()
MAX_LINES = 1024
LINE_BUFFER_BYTES = MAX_LINES * 16 + MAX_LINES * 2 * 2 + 36 * 2
# GO list: decode buffer (vec2d::Line per line) and published PackedLine
# (8 B) list (+ 2 B count + 4 B sequence)
GO_LIST_BYTES = MAX_LINES * 16 + MAX_LINES * 8 + 8


def load_all(files):
    return b"".join(bytes(load_file(ARCHIVE, [name], sha1)) for name, sha1 in files)


def write(filename, symbol, data, description):
    path = os.path.join(OUT_DIR, filename)
    with open(path, "w", newline="\n") as out:
        out.write("// Generated by romconv/internal/bwidow/bwidow_rom_convert.py; do not edit.\n")
        out.write(f"// {description}\n")
        emit_compressed(out, symbol, "unsigned char", "", len(data), list(data))
    print(f"  wrote {path}: {len(data)} bytes")
    return len(data)


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    program, vector = load_all(PROGRAM), load_all(VECTOR)
    assert len(program) == PROGRAM_BYTES and len(vector) == VECTOR_BYTES
    total = write("bwidow_rom.h", "bwidow_rom", program,
                  "Main M6502 ROM, 24 KiB mapped at 0x9000-0xefff; 0xf000-0xffff mirrors 0xe000.")
    total += write("bwidow_vrom.h", "bwidow_vrom", vector,
                   "AVG vector ROM, 14 KiB mapped at 0x2800-0x5fff.")
    total += LINE_BUFFER_BYTES + GO_LIST_BYTES
    print(f"  Arena budget: {total} / 182000 bytes")
    if total >= 182000:
        sys.exit("ERROR: Arena budget exceeded")


if __name__ == "__main__":
    main()
