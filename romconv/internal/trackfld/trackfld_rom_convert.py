#!/usr/bin/env python3
"""Convert the MAME trackfld ROM set into galagino headers (MAME konami/trackfld.cpp)."""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "pyconv"))
from gfxutil import load_file, mame_decode, rgb888_to_rgb565_le
from arena_layout import LOCAL
from asset_emit import emit_compressed
from resnet import resistor_weights, combine

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..", "..")
ZIP = os.path.join(ROOT, "romszip", "trackfld.zip")
OUT_DIR = os.path.join(ROOT, "source", "src", "machines", "trackfld")

# MAME ROM_START( trackfld ), SHA1s from mame -listxml trackfld
MAIN = [
    ("a01_e01.bin", "f7ddae2c5412a2849efd7f9629e92a5b0328e7cb"),
    ("a02_e02.bin", "31301031a525f893c31461f634350f01a9492ef4"),
    ("a03_k03.bin", "380ab2162153a61910a6fe5b6d091ca9451ad4fd"),
    ("a04_e04.bin", "6c42cc76302485954a31520bdd08469fa948c72f"),
    ("a05_e05.bin", "50e65d9b0ea37d2afb2dfdf1f3e1378e3290bc81"),
]
SOUND = ("c2_d13.bin", "ea9135acd7ad162c19c5cdde356e69792d61b675")
SPRITES = [
    ("c11_d06.bin", "1da9ea20e7af0b49c62fb39834a7ec686491af04"),
    ("c12_d07.bin", "33d73b18903e3e6bfb30f1a06db4b8105d4040d8"),
    ("c13_d08.bin", "4448b6242790783d37acf50704d597af5878c2ab"),
    ("c14_d09.bin", "884a12a8f63600da4f23b29be6dbaacef37add20"),
]
TILES = [
    ("h16_e12.bin", "dfff92c0f59dd3d8d3d6256944bfd48792cef6a9"),
    ("h15_e11.bin", "0f41cde82bb60c3f1591ee14dc3cff4642bbddc1"),
    ("h14_e10.bin", "5ba25900e653ce4edcf35f1fbce758a327a715ce"),
]
PAL = ("361b16.f1", "4d6a851f4886778307f75771645078b97ad55f5f")
SPR_CLUT = ("361b17.b16", "894b5cedf01ba9225a0d6215291857e455b84903")
TILE_CLUT = ("361b18.e15", "6740a62cf7b6938a4f936a2fed429704612060a5")
VLM = ("c9_d15.bin", "caee3d8546eb7a75ce2a578c6a1a630246aec6b8")

ARENA_CAPACITY = sum(LOCAL)


def load(entry):
    name, sha1 = entry
    return bytes(load_file(ZIP, [name], sha1))


def load_all(entries):
    return b"".join(load(e) for e in entries)


def step(start, inc, n):
    return [start + i * inc for i in range(n)]


def pack_row(pens):
    v = 0
    for p in pens:
        v = (v << 4) | p
    return v


def decode_tiles(rom):
    # gfx_8x8x4_packed_msb, 32 bytes per char
    count = len(rom) * 8 // 256
    tiles = mame_decode(rom, 8, 8, step(0, 1, 4), step(0, 4, 8), step(0, 32, 8), 256, count)
    return count, [pack_row(row) for t in tiles for row in t]


def decode_sprites(rom):
    # spritelayout: planes {half+4, half+0, 4, 0}, 4 columns of 4 px, 64 bytes per sprite
    half = len(rom) * 4
    count = half // 512
    planes = [half + 4, half, 4, 0]
    xoffs = [64 * c + i for c in range(4) for i in range(4)]
    yoffs = step(0, 8, 8) + step(256, 8, 8)
    sprites = mame_decode(rom, 16, 16, planes, xoffs, yoffs, 512, count)
    return count, [pack_row(row[h * 8:h * 8 + 8]) for s in sprites for row in s for h in range(2)]


def palette(prom):
    # compute_resistor_weights(0, 255, -1, 3, {1000, 470, 220}, 1000, 0 (r, g), 2, {470, 220}, 1000, 0)
    (rw, gw, bw), _ = resistor_weights(0, 255, -1.0, [([1000, 470, 220], 1000, 0),
                                                      ([1000, 470, 220], 1000, 0),
                                                      ([470, 220], 1000, 0)])

    def bit(v, n):
        return (v >> n) & 1

    out = []
    for v in prom:
        r = combine(rw, bit(v, 0), bit(v, 1), bit(v, 2))
        g = combine(gw, bit(v, 3), bit(v, 4), bit(v, 5))
        b = combine(bw, bit(v, 6), bit(v, 7))
        out.append(rgb888_to_rgb565_le(r, g, b))
    return out


def write_cmap(path, pal, tile_clut, spr_clut):
    def table(f, name, clut, base):
        f.write(f"const unsigned short {name}_cmap[16][16] = {{\n")
        transp = []
        for c in range(16):
            idx = [clut[c * 16 + p] & 0x0f for p in range(16)]
            transp.append(sum(1 << p for p in range(16) if idx[p] == 0))
            f.write("  { " + ", ".join(f"0x{pal[base | i]:04x}" for i in idx) + " },\n")
        f.write("};\n\n")
        f.write("// bit p set = pen p transparent (lookup nibble 0)\n")
        f.write(f"const unsigned short {name}_transp[16] = {{ "
                + ", ".join(f"0x{t:04x}" for t in transp) + " };\n\n")

    with open(path, "w", newline="\n") as f:
        f.write("// Generated by romconv/internal/trackfld/trackfld_rom_convert.py; do not edit.\n")
        f.write("// Track & Field color maps, RGB565 byte-swapped for the SPI display.\n\n")
        f.write("// Characters: 16 colors x 16 pens, lookup 361b18 -> palette 0x10 | nibble\n")
        table(f, "trackfld_tile", tile_clut, 0x10)
        f.write("// Sprites: 16 colors x 16 pens, lookup 361b17 -> palette nibble\n")
        table(f, "trackfld_spr", spr_clut, 0x00)
    print(f"  wrote {path}")


def emit(name, ctype, dims, count, flat, comment):
    path = os.path.join(OUT_DIR, f"{name}.h")
    with open(path, "w", newline="\n") as out:
        out.write("// Generated by romconv/internal/trackfld/trackfld_rom_convert.py; do not edit.\n")
        out.write(f"// {comment}\n")
        emit_compressed(out, name, ctype, dims, count, flat)
    print(f"  wrote {path}")


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    main_rom = load_all(MAIN)
    sound_rom = load(SOUND)
    vlm = load(VLM)
    tile_count, tiles = decode_tiles(load_all(TILES))
    sprite_count, sprites = decode_sprites(load_all(SPRITES))

    emit("trackfld_rom_main", "unsigned char", "", len(main_rom), list(main_rom),
         "KONAMI-1 6809 ROM 0x6000-0xffff (encrypted opcodes)")
    emit("trackfld_rom_sound", "unsigned char", "", len(sound_rom), list(sound_rom), "Z80 ROM 0x0000-0x1fff")
    emit("trackfld_vlm", "unsigned char", "", len(vlm), list(vlm), "VLM5030 speech ROM")
    emit("trackfld_tilemap", "uint32_t", "[8]", tile_count, tiles,
         f"{tile_count} chars 8x8 4 bpp, row = 8 pens, pixel 0 in bits 31-28")
    emit("trackfld_spritemap", "uint32_t", "[16][2]", sprite_count, sprites,
         f"{sprite_count} sprites 16x16 4 bpp, [row][0] pixels 0-7, [row][1] pixels 8-15, first in bits 31-28")
    write_cmap(os.path.join(OUT_DIR, "trackfld_cmap.h"), palette(load(PAL)),
               load(TILE_CLUT), load(SPR_CLUT))

    sizes = {"main": len(main_rom), "sound": len(sound_rom), "vlm": len(vlm),
             "tilemap": len(tiles) * 4, "spritemap": len(sprites) * 4}
    total = sum(sizes.values())
    print(f"  tiles {tile_count}, sprites {sprite_count}")
    print("  Arena budget: " + ", ".join(f"{k} {v}" for k, v in sizes.items())
          + f" = {total} / {ARENA_CAPACITY} bytes")
    assert total < ARENA_CAPACITY


if __name__ == "__main__":
    main()
