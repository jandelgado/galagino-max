#!/usr/bin/env python3
"""Convert the MAME atetris (Tetris set 1) ROM set into galagino headers."""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "pyconv"))
from gfxutil import load_file
from asset_emit import emit_compressed

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..", "..")
ARCHIVE = os.path.join(ROOT, "romszip", "atetris.zip")
OUT_DIR = os.path.join(ROOT, "source", "src", "machines", "atetris")

MAIN = ("136066-1100.45f", "5e1189227f26563fd3e5372121ea5c915620f892")
TILES = ("136066-1101.35a", "d8577985fc8ed4e74f74c68b7c00c4855b7c3270")


def tile_words(gfx):
    # MAME gfx_8x8x4_packed_msb: 32 bytes per tile, 4 per row, high nibble
    # = left pixel, pen = nibble. Word per row: pixel i in bits 4i..4i+3.
    words = []
    for row in range(len(gfx) // 4):
        w = 0
        for i in range(8):
            b = gfx[row * 4 + (i >> 1)]
            w |= ((b >> 4) if i % 2 == 0 else (b & 15)) << (4 * i)
        words.append(w)
    return words


def write(filename, description, emit):
    path = os.path.join(OUT_DIR, filename)
    with open(path, "w", newline="\n") as out:
        out.write("// Generated by romconv/internal/atetris/atetris_rom_convert.py; do not edit.\n")
        out.write(f"// {description}\n")
        emit(out)
    print(f"  wrote {path}")


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    rom = bytes(load_file(ARCHIVE, [MAIN[0]], MAIN[1]))
    gfx = bytes(load_file(ARCHIVE, [TILES[0]], TILES[1]))
    write("atetris_rom.h", "Main M6502 ROM, 64 KiB: 0x0000-0x7fff slapstic banks, 0x8000-0xffff fixed.",
          lambda f: emit_compressed(f, "atetris_rom", "unsigned char", "", len(rom), list(rom)))
    words = tile_words(gfx)
    write("atetris_tiles.h", "2048 8x8 tiles, uint32_t per row, pixel i in bits 4i..4i+3.",
          lambda f: emit_compressed(f, "atetris_tiles", "uint32_t", "[8]", len(words) // 8, words))
    total = len(rom) + len(words) * 4
    print(f"  Arena budget: {total} / 182000 bytes")
    if total >= 182000:
        sys.exit("ERROR: Arena budget exceeded")


if __name__ == "__main__":
    main()
