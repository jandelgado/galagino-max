#!/usr/bin/env python3
# Raw signed 8-bit sample (samples/*.s8) -> IMA-ADPCM asset header,
# played by ima_adpcm::Voice. The sample rate is kept: the machine plays
# it as before. -c: COMPRESSED (unpacked to the Arena), else PLAIN.
#
#   internal/sampleconv.py [-c] <name> <in.s8> <out.h>
import sys
sys.path.insert(0, "internal/pyconv")

import numpy as np
from adpcm import emit_adpcm

def main():
    args = sys.argv[1:]
    compress = bool(args) and args[0] == "-c"
    if compress:
        args = args[1:]
    if len(args) != 3:
        print("ERROR: usage: sampleconv.py [-c] <name> <in.s8> <out.h>")
        sys.exit(1)
    name, src, dst = args
    with open(src, "rb") as f:
        pcm = np.frombuffer(f.read(), dtype=np.int8)

    with open(dst, "w") as f:
        print(f"// {name}: {src}, signed 8-bit, as 4-bit IMA-ADPCM", file=f)
        print("// (2-byte predictor, then one nibble per sample). Generated by", file=f)
        print("// romconv/internal/sampleconv.py, do not edit.", file=f)
        size = emit_adpcm(f, name, pcm, compress)
    print(f"{name}: {len(pcm)} -> {size} bytes")

if __name__ == "__main__":
    main()
