#!/usr/bin/env python3
# Remote bundles of every catalog game (mode 3, ASSETS_REMOTE): reads the
# sidecars asset_emit.py leaves in romconv/build/assets/<dir>/, writes the
# wire bundle to galagino-server/data/g/<hash> and <game>_bundle.h with its
# BundleRef. Reports the ratio cost of the 64 KB dictionary of PLAIN assets.
#
# Usage (from romconv/): bundles.py [game ...]   default: every catalog game
import json
import lzma
import os
import re
import sys

from asset_emit import ASSET_DIR, PLAIN_DICT_BYTES
from bundle import BundleWriter, bundle_hash, write_bundle
from catalog import CATALOG, bundle_dirs

HERE = os.path.dirname(os.path.abspath(__file__))
MACHINES = os.path.join(HERE, "..", "..", "..", "source", "src", "machines")
SERVER = os.path.join(HERE, "..", "..", "..", "galagino-server", "data")


def _read(path):
    with open(path, "rb") as f:
        return f.read()


def _remote_plain(machines, dirname):
    """<name> -> remote layout PLAIN flag from <dir>_arena_plan.h."""
    path = os.path.join(machines, dirname, f"{dirname}_arena_plan.h")
    if not os.path.exists(path):
        return {}
    text = open(path).read()
    m = re.search(r"#ifdef ASSETS_REMOTE\n(.*?)#else", text, re.S)
    if not m:
        raise ValueError(f"{path}: no ASSETS_REMOTE block")
    return {n: v == "1" for n, v in re.findall(r"#define (\w+)_PLAIN ([01])", m.group(1))}


def _decode64(packed):
    """Decode as the device does: a dictionary of PLAIN_DICT_BYTES."""
    props = packed[0]
    filters = [{"id": lzma.FILTER_LZMA1, "dict_size": PLAIN_DICT_BYTES, "lc": props % 9,
                "lp": props // 9 % 5, "pb": props // 45}]
    return lzma.decompress(packed[1:], format=lzma.FORMAT_RAW, filters=filters)


def _assets(game, assets, machines):
    """(name, raw, stored, mode, full-dictionary bytes) of the game's dirs."""
    out = []
    for d in bundle_dirs(game):
        src = os.path.join(assets, d)
        if not os.path.isdir(src):
            continue
        plan = _remote_plain(machines, d)
        for fn in sorted(os.listdir(src)):
            if not fn.endswith(".json"):
                continue
            name = fn[:-5]
            meta = json.loads(_read(os.path.join(src, fn)))
            mode = meta["mode"]
            if mode == "PLANNED":
                if name not in plan:
                    raise ValueError(f"{name}: planned, but not in {d}_arena_plan.h")
                mode = "PLAIN" if plan[name] else "COMPRESSED"
            raw = _read(os.path.join(src, name + ".raw"))
            full = _read(os.path.join(src, name + ".lz"))
            stored = full if mode == "COMPRESSED" else _read(os.path.join(src, name + ".lz64"))
            if mode == "PLAIN" and _decode64(stored) != raw:
                raise ValueError(f"{name}: 64 KB dictionary stream does not decode")
            out.append((name, raw, stored, mode, len(full)))
    return out


def _sym(game):
    """C symbol prefix: digit-led names get a `_` (1943)."""
    return ("_" + game) if game[0].isdigit() else game


def _header(game, hex_name, digest, wire, entry):
    sym = _sym(game)
    hash_c = ", ".join("0x%02x" % b for b in digest)
    return "\n".join([
        "// Generated by romconv/internal/pyconv/bundles.py; do not edit.",
        '#include "../../net/bundle.h"',
        # nothing to download while every dir is in the app (amidar built in
        # keeps turtles' and scramble's assets, so turtles needs no bundle)
        "#if " + " || ".join(f"!defined(BUILTIN_{d.upper()})" for d in bundle_dirs(game)),
        f"// GET /g/{hex_name}",
        f'static constexpr BundleRef {sym}_bundle = {{ {{ {hash_c} }}, {wire}u, {entry}u, "{game.upper()}" }};',
        f"#define {sym}_bundle_ref (&{sym}_bundle)",
        "#else",
        f"#define {sym}_bundle_ref nullptr",
        "#endif",
        ""])


def make_bundle(game, assets=ASSET_DIR, machines=MACHINES, server=SERVER):
    """Write the bundle and <game>_bundle.h, return report numbers."""
    items = _assets(game, assets, machines)
    os.makedirs(os.path.join(machines, game), exist_ok=True)
    path = os.path.join(machines, game, f"{game}_bundle.h")
    if not items:
        # tables only (hero): nothing to download
        with open(path, "w", newline="\n") as f:
            f.write("// Generated by romconv/internal/pyconv/bundles.py; do not edit.\n"
                    f"// no asset blobs: always built in\n#define {_sym(game)}_bundle_ref nullptr\n")
        return None

    w = BundleWriter()
    plain_raw = plain64 = plain_full = 0
    for name, raw, stored, mode, full in items:
        w.add(name, raw, stored, mode)
        if mode == "PLAIN":
            plain_raw, plain64, plain_full = plain_raw + len(raw), plain64 + len(stored), plain_full + full

    wire = w.build()
    entry = len(w.entry())
    hex_name = write_bundle(wire, server)
    with open(path, "w", newline="\n") as f:
        f.write(_header(game, hex_name, bundle_hash(wire), len(wire), entry))
    return {"hex": hex_name, "wire": len(wire), "entry": entry,
            "plain_raw": plain_raw, "plain64": plain64, "plain_full": plain_full}


def main(games):
    total = {"wire": 0, "entry": 0, "plain_raw": 0, "plain64": 0, "plain_full": 0}
    for game in games:
        try:
            r = make_bundle(game)
        except ValueError as e:
            print(f"ERROR {game}: {e}")
            sys.exit(1)
        if not r:
            print(f"  {game:12} no asset blobs, always built in")
            continue
        for k in total:
            total[k] += r[k]
        print(f"  {game:12} wire {r['wire']:7} entry {r['entry']:7}  PLAIN raw {r['plain_raw']:7}"
              f" 64K-dict {r['plain64']:7} full-dict {r['plain_full']:7}  g/{r['hex']}")
    loss = total["plain64"] - total["plain_full"]
    print(f"  total wire {total['wire']} entry {total['entry']}; PLAIN raw {total['plain_raw']},"
          f" 64 KB dictionary {total['plain64']} vs full {total['plain_full']} (+{loss} bytes)")


if __name__ == "__main__":
    main(sys.argv[1:] or sorted(CATALOG))
