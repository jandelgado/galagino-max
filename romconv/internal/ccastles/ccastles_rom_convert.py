#!/usr/bin/env python3
"""Convert the MAME ccastlesj (joystick) ROM set, clone of ccastles, into galagino headers."""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "pyconv"))
from gfxutil import load_file, mame_decode
from asset_emit import emit_compressed

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..", "..")
CLONE = os.path.join(ROOT, "romszip", "ccastlesj.zip")
PARENT = os.path.join(ROOT, "romszip", "ccastles.zip")
OUT_DIR = os.path.join(ROOT, "source", "src", "machines", "ccastles")

# (zip, name, sha1), MAME ROM_START( ccastlesj )
MAIN = [
    (CLONE, "a000.12m", "fbd6a5a0e4e865421ed3720aa61221d03583f248"),       # 0xa000
    (CLONE, "c000.13m", "ade2c63656339c3e7e634470a17bc30da1006979"),       # 0xc000
    (CLONE, "e000.14m", "076caffe67910bdcd1f51a41f2cc4ebdb930c7ca"),       # 0xe000
    (PARENT, "136022-102.1h", "69c3da2cbefc5e03a77357e817e3015da5d8334a"),  # 0x10000
    (PARENT, "136022-101.1f", "81fa95b4d9beacb06d6b4afdf346d94117396557"),  # 0x12000
]
GFX = [
    (PARENT, "136022-106.8d", "01c279edee322cc28f34506c312e4a9e3363b1be"),
    (PARENT, "136022-107.8b", "82bdf764ac23e72598883283c5e957169387abd4"),
]
SYNC = (PARENT, "82s129-136022-108.7k", "c3f3e4e7f313ecfd101cc52dfc44bd6b51a2ac88")
WPROM = (PARENT, "82s129-136022-110.11l", "ae155918fdafd14299bc448b43eed8ad9c1ef5ef")
PRIPROM = (PARENT, "82s129-136022-111.10k", "278bf61a290ae72ddaae2bafb4ab6739d3fb6238")

VRAM_BYTES = 32768  # Arena, allocated by the machine


def load(entry):
    zipname, name, sha1 = entry
    return bytes(load_file(zipname, [name], sha1))


def check_sync(sync):
    # ccastles.h hardcodes vblank lines 0..23 and IRQs at 0, 64, 128, 192
    vblank = [y for y in range(256) if sync[y] & 1]
    irq = [y for y in range(256) if not sync[(y - 1) & 255] & 8 and sync[y] & 8]
    if vblank != list(range(24)) or irq != [0, 64, 128, 192]:
        sys.exit(f"ERROR: sync PROM differs: vblank {vblank}, irq {irq}")


def sprite_words(gfx):
    # ccastles_spritelayout: 8x16, planes {4, RGN_FRAC(1,2)+0, RGN_FRAC(1,2)+4}
    half = len(gfx) * 8 // 2
    sprites = mame_decode(gfx, 8, 16, [4, half, half + 4], [0, 1, 2, 3, 8, 9, 10, 11],
                          [y * 16 for y in range(16)], 32 * 8, 256)
    words = []
    for s in sprites:
        for row in s:
            words.append(sum(p << (4 * i) for i, p in enumerate(row)))
    return words


def write(filename, description, emit):
    path = os.path.join(OUT_DIR, filename)
    with open(path, "w", newline="\n") as out:
        out.write("// Generated by romconv/internal/ccastles/ccastles_rom_convert.py; do not edit.\n")
        out.write(f"// {description}\n")
        emit(out)
    print(f"  wrote {path}")


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    rom = b"".join(load(e) for e in MAIN)
    assert len(rom) == 0xa000
    gfx = b"".join(load(e) for e in GFX)
    check_sync(load(SYNC))
    proms = load(WPROM) + load(PRIPROM)
    words = sprite_words(gfx)

    write("ccastles_rom.h", "M6502 ROM: 0x0000 = CPU 0xa000-0xffff (bank 0), 0x6000 = bank 1 for 0xa000-0xdfff.",
          lambda f: emit_compressed(f, "ccastles_rom", "unsigned char", "", len(rom), list(rom)))
    write("ccastles_sprites.h", "256 8x16 sprites, uint32_t per row, pixel i in bits 4i..4i+2, pen 7 transparent.",
          lambda f: emit_compressed(f, "ccastles_sprites", "uint32_t", "[16]", len(words) // 16, words))
    write("ccastles_proms.h", "0x000 write protect PROM 110, 0x100 priority PROM 111.",
          lambda f: emit_compressed(f, "ccastles_proms", "unsigned char", "", len(proms), list(proms)))

    total = len(rom) + len(words) * 4 + len(proms) + VRAM_BYTES
    print(f"  Arena budget: {total} / 182000 bytes (rom {len(rom)}, sprites {len(words) * 4}, "
          f"proms {len(proms)}, vram {VRAM_BYTES})")
    if total >= 182000:
        sys.exit("ERROR: Arena budget exceeded")


if __name__ == "__main__":
    main()
