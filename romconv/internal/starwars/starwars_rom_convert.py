#!/usr/bin/env python3
"""Convert the MAME starwars (Star Wars set 1) ROM set into galagino headers."""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "pyconv"))
from gfxutil import load_file
from asset_emit import emit_compressed

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..", "..")
ARCHIVE = os.path.join(ROOT, "romszip", "starwars.zip")
OUT_DIR = os.path.join(ROOT, "source", "src", "machines", "starwars")

# MAME starwars: name -> SHA1. The AVG state PROM 136021-109.4b is dropped:
# the display list is decoded at instruction level.
ROM0 = ("136021.214.1f", "c1d3637cb31ece0890c25f6122d6bcd27e6ffe0c")  # 16 KiB: bank pages 0, 1
PROGRAM = [
    ("136021.102.1hj", "f8943b67f2ea032ab9538084756ba86f892be5ca"),  # 0x8000
    ("136021.203.1jk", "dd53b643be856787bbc4da63e5eb132f98f623c3"),  # 0xa000
    ("136021.104.1kl", "981b505d6e06d7149f8bcb3e81e4d0c790f2fc86"),  # 0xc000
    ("136021.206.1m", "4960f4446271316e3f730eeb2531dbc702947395"),  # 0xe000
]
VECTOR = [("136021-105.1l", "032c933fd94a6b0b294beee29159a24494ae969b")]
SOUND = [
    ("136021-107.1jk", "c38661b2b846fe93487eef09ca3cda19c44f08a0"),  # 0x4000, 0xc000
    ("136021-208.1h", "c858ae1702efdd48615453ab46e488848891d139"),  # 0x6000, 0xe000
]
# matrix processor microcode, PROM 0 holds the most significant nibble
MATH_PROMS = [
    ("136021-110.7h", "d247cbb0afb4538d5161f8ce9eab337cdb3f2da4"),
    ("136021-111.7j", "f3420c6e15602956fd94982a5d8d4ddd015ed977"),
    ("136021-112.7k", "4dcf5153221feca329b8e8d199bd4fc00b151d9c"),
    ("136021-113.7l", "e13541b09d1724204fdb171528e9a1c83c799c1c"),
]

# Other Arena users, allocated in starwars::start(); keep in sync:
# - lines: starwars::MAX_LINES vec2d::Line (16 B) + StripRasterizer
#   next/active (2 x uint16_t per line) + 36 strip heads
# - GO list: decode buffer (vec2d::Line per line) and published
#   PackedLine (8 B) list (+ 2 B count + 4 B sequence)
# - Math RAM 0x5000-0x5fff
MAX_LINES = 2048
LINE_BUFFER_BYTES = MAX_LINES * 16 + MAX_LINES * 2 * 2 + 36 * 2
GO_LIST_BYTES = MAX_LINES * 16 + MAX_LINES * 8 + 8
MATH_RAM_BYTES = 0x1000


def load(name, sha1):
    return bytes(load_file(ARCHIVE, [name], sha1))


def load_all(files):
    return b"".join(load(name, sha1) for name, sha1 in files)


def write(filename, symbol, ctype, data, description):
    path = os.path.join(OUT_DIR, filename)
    with open(path, "w", newline="\n") as out:
        out.write("// Generated by romconv/internal/starwars/starwars_rom_convert.py; do not edit.\n")
        out.write(f"// {description}\n")
        emit_compressed(out, symbol, ctype, "", len(data), list(data))
    size = len(data) * (2 if ctype == "unsigned short" else 1)
    print(f"  wrote {path}: {size} bytes")
    return size


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    rom0 = load(*ROM0)
    program = rom0[:0x2000] + load_all(PROGRAM) + rom0[0x2000:]
    total = write("starwars_rom.h", "starwars_rom", "unsigned char", program,
                  "Main M6809 ROM: 0x6000-0xffff (bank page 0 at 0x6000), then bank page 1.")
    total += write("starwars_vrom.h", "starwars_vrom", "unsigned char", load_all(VECTOR),
                   "AVG vector ROM, 4 KiB mapped at 0x3000-0x3fff.")
    total += write("starwars_srom.h", "starwars_srom", "unsigned char", load_all(SOUND),
                   "Sound M6809 ROM, 16 KiB mapped at 0x4000-0x7fff and 0xc000-0xffff.")

    proms = [load(name, sha1) for name, sha1 in MATH_PROMS]
    micro = [(proms[0][i] & 0xf) << 12 | (proms[1][i] & 0xf) << 8 | (proms[2][i] & 0xf) << 4 |
             (proms[3][i] & 0xf) for i in range(0x400)]
    total += write("starwars_mproms.h", "starwars_mproms", "unsigned short", micro,
                   "Matrix processor microcode, 1024 words: strobes 15-8, AM 7, address 6-0.")

    total += LINE_BUFFER_BYTES + GO_LIST_BYTES + MATH_RAM_BYTES
    print(f"  Arena budget: {total} / 182000 bytes")
    if total >= 182000:
        sys.exit("ERROR: Arena budget exceeded")


if __name__ == "__main__":
    main()
