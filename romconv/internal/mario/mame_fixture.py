#!/usr/bin/env python3
"""Turn a mame_ref.lua capture (ram_trace.txt + snapshot PNG) into the
host test fixture source/test/test_mario_video/mame_mario_frame.h.

usage: mame_fixture.py <ram_trace.txt> <snapshot.png> <frame> <out.h>
Tiles and registers from <frame>, sprites from <frame> - 1 (MAME's
snapshot shows the previous frame's sprite list)."""
import sys
import zlib

from PIL import Image


def rgb565_swapped(r, g, b):
    v = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
    return ((v & 0xff) << 8) | (v >> 8)


def main(trace, png, frame, out):
    rows = {}
    for line in open(trace):
        f, scroll, latch, ram = line.split()
        rows[int(f)] = (int(scroll), latch, bytes.fromhex(ram))
    scroll, latch, ram = rows[frame]
    sprites = rows[frame][2][0x1000:0x1180]
    latch_byte = sum(int(c) << i for i, c in enumerate(latch))

    im = Image.open(png).convert("RGB")
    assert im.size == (256, 224)
    crcs = []
    for y in range(224):
        line = b"".join(rgb565_swapped(*im.getpixel((x, y))).to_bytes(2, "little") for x in range(256))
        crcs.append(zlib.crc32(line))

    with open(out, "w", newline="\n") as f:
        f.write(f"// Generated by romconv/internal/mario/mame_fixture.py from MAME frame {frame}.\n")
        f.write("#include <stdint.h>\n")
        f.write(f"static const uint8_t mame_scroll = {scroll};\n")
        f.write(f"static const uint8_t mame_latch = 0x{latch_byte:02x};\n")
        f.write(f"static const uint8_t mame_player1_x = 0x{ram[0x107]:02x};\n")
        f.write("static const uint8_t mame_tiles[0x400] = {" + ",".join(str(b) for b in ram[0x1400:0x1800]) + "};\n")
        f.write("static const uint8_t mame_sprites[0x180] = {" + ",".join(str(b) for b in sprites) + "};\n")
        f.write("// CRC32 of each visible line, 256 RGB565 byte-swapped pixels\n")
        f.write("static const uint32_t mame_line_crc[224] = {" + ",".join(f"0x{c:08x}" for c in crcs) + "};\n")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2], int(sys.argv[3]), sys.argv[4])
