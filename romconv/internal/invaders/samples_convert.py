#!/usr/bin/env python3
"""
Space Invaders shot and invader hit samples (samples/invaders_*.s8,
12 kHz signed 8-bit, each played twice at 24 kHz) to IMA-ADPCM.
"""

import os
import sys

import numpy as np

sys.path.insert(0, os.path.join("..", "pyconv"))
from adpcm import emit_adpcm

SAMPLES_DIR = os.path.normpath(os.path.join("..", "..", "..", "samples"))
OUT_DIR = os.path.normpath(os.path.join("..", "..", "..", "source", "src", "machines", "spaceinvaders"))
HEADER = os.path.join(OUT_DIR, "spaceinvaders_samples.h")

def main():
    with open(HEADER, "w") as f:
        f.write("// Space Invaders audio samples: 12 kHz signed 8-bit as 4-bit IMA-ADPCM\n")
        f.write("// Generated by romconv/internal/invaders/samples_convert.py, do not edit.\n\n")
        for name in ("shot", "invhit"):
            with open(os.path.join(SAMPLES_DIR, f"invaders_{name}.s8"), "rb") as s8:
                pcm = np.frombuffer(s8.read(), dtype=np.int8)
            size = emit_adpcm(f, f"si_sample_{name}", pcm, compress=True)
            f.write("\n")
            print(f"  si_sample_{name}: {len(pcm)} -> {size} bytes")

if __name__ == "__main__":
    main()
