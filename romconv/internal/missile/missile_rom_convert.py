#!/usr/bin/env python3
"""Convert the MAME missile (rev 3) ROM set into galagino headers."""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "pyconv"))
from gfxutil import load_file
from asset_emit import emit_compressed

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..", "..")
ZIP = os.path.join(ROOT, "romszip", "missile.zip")
OUT_DIR = os.path.join(ROOT, "source", "src", "machines", "missile")

# (names, sha1), MAME ROM_START( missile ), CPU 0x5000-0x7fff
MAIN = [
    (["035820-02.h1"], "9a39978138dc28fdefe193bfae1b226391e471db"),
    (["035821-02.jk1"], "0916925d3c94d766d33f0e4badf6b0add835d748"),
    (["035822-03e.kl1"], "2deb1219223032a9c83114e4e8b2fc11a570754c"),
    (["035823-02.ln1", "035823-02.lm1"], "d0f22894f779c74ceef644c9f03d840d9545efea"),
    (["035824-02.np1"], "9718f84a73c66b4e8ef7805a7ab638a7380624e1"),
    (["035825-02.r1"], "0339a6ce6744d2091cc7e07675e509b202b0f380"),
]
WPROM = (["035826-01.l6"], "2beebf7855e29849ada1823eae031fc98220bc43")


def load(entry):
    names, sha1 = entry
    return bytes(load_file(ZIP, names, sha1))


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    rom = b"".join(load(e) for e in MAIN)
    assert len(rom) == 0x3000
    data = rom + load(WPROM)

    path = os.path.join(OUT_DIR, "missile_rom.h")
    with open(path, "w", newline="\n") as out:
        out.write("// Generated by romconv/internal/missile/missile_rom_convert.py; do not edit.\n")
        out.write("// M6502 ROM: 0x0000 = CPU 0x5000-0x7fff, 0x3000 = write PROM 035826-01 (32 bytes).\n")
        emit_compressed(out, "missile_rom", "unsigned char", "", len(data), list(data))
    print(f"  wrote {path}")
    print(f"  Arena budget: {len(data)} / 182000 bytes (rom {len(rom)}, prom 32); VRAM in memory[]")


if __name__ == "__main__":
    main()
