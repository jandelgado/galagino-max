#!/usr/bin/env python3
"""Convert the MAME yiear ROM set into galagino headers (MAME konami/yiear.cpp)."""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "pyconv"))
from gfxutil import load_file, mame_decode, rgb888_to_rgb565_le
from arena_layout import LOCAL
from asset_emit import emit_compressed

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..", "..")
ZIP = os.path.join(ROOT, "romszip", "yiear.zip")
OUT_DIR = os.path.join(ROOT, "source", "src", "machines", "yiear")

# MAME ROM_START( yiear ), version I
MAIN = [
    ("407_i08.10d", "1b192130b5cd879ab686a21aa2b518c90edd89aa"),
    ("407_i07.8d", "d604a995a5505251904447ad697fc9e7f94bf241"),
]
TILES = [
    ("407_c01.6h", "c267931d69794c292b7ebae5bc35ad842194683a"),
    ("407_c02.7h", "a2fd10bddfa4e95e9d49892737ace146209bfa2b"),
]
SPRITES = [
    ("407_d05.16h", "0794935b490497b21b99045c90231b7bac151d42"),
    ("407_d06.17h", "5f2a4983b20251c712358547a7c62c0331c6cb6f"),
    ("407_d03.14h", "c5757d16c28f5966fd04675c0c640ef9b6b76ca5"),
    ("407_d04.15h", "555ba18a9648681e5140b3fd84af16959ee5296d"),
]
PROM = ("407c10.1g", "10cd39f4e951ba6ca5610081c8c1fcd9d68b34d2")
VLM = ("407_c09.8b", "f139f6cb41351eb81ee47d777db03012aa5fadb1")

TILE_COUNT = 512
SPRITE_COUNT = 512
ARENA_CAPACITY = sum(LOCAL)


def load(entry):
    name, sha1 = entry
    return bytes(load_file(ZIP, [name], sha1))


def load_all(entries):
    return b"".join(load(e) for e in entries)


def step(start, inc, n):
    return [start + i * inc for i in range(n)]


def pack_row(pens):
    v = 0
    for p in pens:
        v = (v << 4) | p
    return v


def decode_tiles(rom):
    # charlayout: planes {4, 0, half+4, half+0}, 16 bytes per char
    half = len(rom) * 4
    planes = [4, 0, half + 4, half]
    xoffs = step(0, 1, 4) + step(64, 1, 4)
    tiles = mame_decode(rom, 8, 8, planes, xoffs, step(0, 8, 8), 128, TILE_COUNT)
    return [pack_row(row) for t in tiles for row in t]


def decode_sprites(rom):
    # spritelayout: 4 columns of 4 px, 64 bytes per sprite
    half = len(rom) * 4
    planes = [4, 0, half + 4, half]
    xoffs = [64 * c + i for c in range(4) for i in range(4)]
    yoffs = step(0, 8, 8) + step(256, 8, 8)
    sprites = mame_decode(rom, 16, 16, planes, xoffs, yoffs, 512, SPRITE_COUNT)
    return [pack_row(row[h * 8:h * 8 + 8]) for s in sprites for row in s for h in range(2)]


def palette(prom):
    def bit(v, n):
        return (v >> n) & 1

    out = []
    for v in prom:
        r = 0x21 * bit(v, 0) + 0x47 * bit(v, 1) + 0x97 * bit(v, 2)
        g = 0x21 * bit(v, 3) + 0x47 * bit(v, 4) + 0x97 * bit(v, 5)
        b = 0x52 * bit(v, 6) + 0xad * bit(v, 7)
        out.append(rgb888_to_rgb565_le(r, g, b))
    return out


def header(out, comment):
    out.write("// Generated by romconv/internal/yiear/yiear_rom_convert.py; do not edit.\n")
    out.write(f"// {comment}\n")


def emit(name, ctype, dims, count, flat, comment):
    path = os.path.join(OUT_DIR, f"{name}.h")
    with open(path, "w", newline="\n") as out:
        header(out, comment)
        emit_compressed(out, name, ctype, dims, count, flat)
    print(f"  wrote {path}")


def write_palette(pal):
    path = os.path.join(OUT_DIR, "yiear_palette.h")
    with open(path, "w", newline="\n") as out:
        header(out, "PROM 407c10, RGB565 byte-swapped: sprites 0-15, tiles 16-31")
        out.write("const unsigned short yiear_palette[32] = {\n  "
                  + ", ".join(f"0x{c:04x}" for c in pal) + "\n};\n")
    print(f"  wrote {path}")


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    rom = load_all(MAIN)
    vlm = load(VLM)
    tiles = decode_tiles(load_all(TILES))
    sprites = decode_sprites(load_all(SPRITES))

    emit("yiear_rom", "unsigned char", "", len(rom), list(rom), "6809 ROM 0x8000-0xffff")
    emit("yiear_vlm", "unsigned char", "", len(vlm), list(vlm), "VLM5030 speech ROM")
    emit("yiear_tilemap", "uint32_t", "[8]", TILE_COUNT, tiles,
         "512 chars 8x8 4 bpp, row = 8 pens, pixel 0 in bits 31-28")
    emit("yiear_spritemap", "uint32_t", "[16][2]", SPRITE_COUNT, sprites,
         "512 sprites 16x16 4 bpp, [row][0] pixels 0-7, [row][1] pixels 8-15, first in bits 31-28")
    write_palette(palette(load(PROM)))

    sizes = {"rom": len(rom), "vlm": len(vlm), "tilemap": len(tiles) * 4,
             "spritemap": len(sprites) * 4}
    total = sum(sizes.values())
    print("  Arena budget: " + ", ".join(f"{k} {v}" for k, v in sizes.items())
          + f" = {total} / {ARENA_CAPACITY} bytes")
    assert total < ARENA_CAPACITY


if __name__ == "__main__":
    main()
