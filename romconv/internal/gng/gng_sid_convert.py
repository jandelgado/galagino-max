#!/usr/bin/env python3
"""Pack the C64 Ghosts'n Goblins SID tune (Mark Cooksey, HVSC) into a galagino header.

Music for the gng machine. User supplied, like
ROMs: romszip/Ghosts_n_Goblins.sid from HVSC MUSICIANS/C/Cooksey_Mark/.
"""
import hashlib
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "pyconv"))
from asset_emit import emit_plain
from convutil import fatal

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..", "..")
SID_FILE = os.path.join(ROOT, "romszip", "Ghosts_n_Goblins.sid")
SID_SHA1 = "2ee5606a190208b4ea424bd7152c28148af62d51"
OUT = os.path.join(ROOT, "source", "src", "machines", "gng", "gng_sid.h")


def main():
    if not os.path.exists(SID_FILE):
        fatal(f"missing {os.path.abspath(SID_FILE)} (HVSC Cooksey_Mark/Ghosts_n_Goblins.sid)")
    with open(SID_FILE, "rb") as f:
        data = f.read()
    if hashlib.sha1(data).hexdigest() != SID_SHA1:
        fatal(f"{SID_FILE}: SHA1 mismatch, expected {SID_SHA1}")

    with open(OUT, "w", newline="\n") as out:
        out.write("// Generated by romconv/internal/gng/gng_sid_convert.py; do not edit.\n")
        out.write("// C64 Ghosts'n Goblins PSID (Mark Cooksey, 1986 Elite), whole file\n")
        # plain: SidPlayer copies the payload into its RAM window anyway
        body = ",\n".join(",".join("0x%02x" % v for v in data[i:i + 16]) for i in range(0, len(data), 16))
        emit_plain(out, "gng_sid", "unsigned char", "", len(data), body)
    print(f"  wrote {OUT}: {len(data)} bytes")


if __name__ == "__main__":
    main()
