#!/usr/bin/env python3
"""Ghosts'n Goblins ROMs (MAME gng, romszip/gng.zip) to galagino headers.

ROT0 game shown upright: gfx stay unrotated. Layouts from MAME
capcom/gng.cpp (charlayout, tilelayout, spritelayout). Formats match
commando: chars unsigned short[8] (pixel x at bits 2x), tiles and sprites
uint32_t[32] (row y = words 2y, 2y+1, pixel x in nibble x).

  gng_rom      CPU $4000-$FFFF (mm_c_04 + mm_c_03), PLAIN
  gng_bank     banked $4000-$5FFF pages 0-3 (mm_c_05), PLAIN
  gng_sound    sound Z80 ROM up to SOUND_SIZE, Arena
  gng_chars    1024 fg chars, PLAIN
  gng_tiles    unique bg tiles, Arena (100 KB, compresses 2.5x)
  gng_tile_map bg tile code -> gng_tiles index, Arena
  gng_spritesN sprite codes 256 N .. 256 N + 255, Arena (codes 768+ blank);
               bank 2 PLAIN
PLAIN assets compress worst (ROMs ~50%) or are the cheapest to leave out:
the Arena then holds the bg tiles, which save most.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "pyconv"))
from asset_emit import emit_compressed, emit_plain
from convutil import fatal
from gfxutil import load_file, mame_decode

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..", "..")
ZIP = os.path.join(ROOT, "romszip", "gng.zip")
OUT = os.path.join(ROOT, "source", "src", "machines", "gng")

SHA1 = {
    "mm_c_04": "6863fee3c97c76ba314ccbada7efacb6783e7d32",
    "mm_c_03": "d29e12082c4d5c06a9910b3500ef66242cdec905",
    "mm_c_05": "064871918547a56be330c6994d4db2c9932e14db",
    "gg2.bin": "7ef9ec5c2072e21c787a6bbf700033f50c759c1d",
    "gg1.bin": "0a1518e19a2e0a4cc3dde4b9568202ea911b5ece",
    "gg11.bin": "f9d77eee5e2738b7e83ba02fcc55dd480391479f",
    "gg10.bin": "8434c994cc55d2586641f3b90b6b15fd65dfb67c",
    "gg9.bin": "bbb1fba0eb19471f66d29526fa8423ccb047bd63",
    "gg8.bin": "1c42fa02cb27b35d10c3f7f036005e747f9f6b79",
    "gg7.bin": "1947f159189b3a53f1251d8653b6e7c65c91fc3c",
    "gg6.bin": "944da1ce29a18bf0fc8deff78bceacba0bf23a07",
    "gg17.bin": "42d367f57bb2fdf60a0445ac1533da99cfeaa617",
    "gg16.bin": "9e06012bcd82f98fad43de666ef9a75979d940ab",
    "gg15.bin": "e3a1421d465b87148ffa94f5673b2307f0246afe",
    "gg14.bin": "207a7407288182a4f3eddaea634c6a6452131182",
    "gg13.bin": "cb641c25bb04b970b2cbeca41adb792bbe142fb5",
    "gg12.bin": "3f129ca6d695548b659955fe538584bd9ac2ff17",
}

SOUND_SIZE = 0x5700  # gg2.bin is 0xff from $56C9 on
SPRITE_BANKS = 3     # codes 768-1023 come from the erased (0xff) region
ARENA_SPRITE_BANKS = (0, 1)  # bank 2 PLAIN, see above


def rom(name):
    return bytes(load_file(ZIP, [name], SHA1[name]))


def pack_4bpp(tile):
    """uint32_t[32]: row y -> pixels 0-7, 8-15, pixel x in nibble x & 7."""
    words = []
    for row in tile:
        for half in (row[0:8], row[8:16]):
            words.append(sum(p << (4 * i) for i, p in enumerate(half)))
    return words


def pack_2bpp(char):
    return [sum(p << (2 * x) for x, p in enumerate(row)) for row in char]


def hex_rows(rows):
    return ",\n".join(" { " + ",".join("0x%x" % v for v in r) + " }" for r in rows)


def byte_body(data):
    return ",\n".join(",".join("0x%02x" % b for b in data[i:i + 16]) for i in range(0, len(data), 16))


def write(name, emit):
    path = os.path.join(OUT, name)
    with open(path, "w", newline="\n") as f:
        f.write("// Generated by romconv/internal/gng/gng_rom_convert.py; do not edit.\n")
        emit(f)


def convert_cpu():
    fixed = rom("mm_c_04") + rom("mm_c_03")
    write("gng_rom.h", lambda f: emit_plain(f, "gng_rom", "unsigned char", "", len(fixed), byte_body(fixed)))
    bank = rom("mm_c_05")
    write("gng_bank.h", lambda f: emit_plain(f, "gng_bank", "unsigned char", "", len(bank), byte_body(bank)))

    sound = rom("gg2.bin")
    if any(b != 0xff for b in sound[SOUND_SIZE:]):
        fatal("gg2.bin: data above SOUND_SIZE")
    sound = sound[:SOUND_SIZE]
    write("gng_sound.h", lambda f: emit_compressed(f, "gng_sound", "unsigned char", "", len(sound), sound))
    return len(sound)


def convert_chars():
    data = rom("gg1.bin")
    chars = mame_decode(data, 8, 8, [4, 0], [0, 1, 2, 3, 8, 9, 10, 11],
                        [16 * y for y in range(8)], 128, 1024)
    flat = [v for c in chars for v in pack_2bpp(c)]
    rows = [flat[i:i + 8] for i in range(0, len(flat), 8)]
    write("gng_chars.h", lambda f: emit_plain(f, "gng_chars", "unsigned short", "[8]", len(chars), hex_rows(rows)))


def convert_tiles():
    data = b"".join(rom(n) for n in ("gg11.bin", "gg10.bin", "gg9.bin", "gg8.bin", "gg7.bin", "gg6.bin"))
    third = len(data) // 3 * 8
    tiles = mame_decode(data, 16, 16, [2 * third, third, 0],
                        list(range(8)) + list(range(128, 136)), [8 * y for y in range(16)], 256, 1024)

    # duplicates share one entry: 1024 codes -> unique tiles
    unique, index, tile_map = [], {}, []
    for t in tiles:
        words = tuple(pack_4bpp(t))
        if words not in index:
            index[words] = len(unique)
            unique.append(words)
        tile_map.append(index[words])

    def emit(f):
        emit_compressed(f, "gng_tiles", "uint32_t", "[32]", len(unique), [v for t in unique for v in t])
        emit_compressed(f, "gng_tile_map", "unsigned short", "", len(tile_map), tile_map)

    write("gng_tiles.h", emit)
    print(f"  bg tiles: {len(unique)} unique of {len(tiles)}, {128 * len(unique)} bytes")
    return 128 * len(unique) + 2 * len(tile_map)


def convert_sprites():
    blank = b"\xff" * 0x4000
    region = (rom("gg17.bin") + rom("gg16.bin") + rom("gg15.bin") + blank +
              rom("gg14.bin") + rom("gg13.bin") + rom("gg12.bin") + blank)
    half = len(region) // 2 * 8
    xoffs = [0, 1, 2, 3, 8, 9, 10, 11, 256, 257, 258, 259, 264, 265, 266, 267]
    sprites = mame_decode(region, 16, 16, [half + 4, half, 4, 0], xoffs,
                          [16 * y for y in range(16)], 512, 256 * SPRITE_BANKS)

    def emit(f):
        for b in range(SPRITE_BANKS):
            flat = [v for s in sprites[256 * b:256 * (b + 1)] for v in pack_4bpp(s)]
            if b in ARENA_SPRITE_BANKS:
                emit_compressed(f, f"gng_sprites{b}", "uint32_t", "[32]", 256, flat)
            else:
                rows = [flat[i:i + 32] for i in range(0, len(flat), 32)]
                emit_plain(f, f"gng_sprites{b}", "uint32_t", "[32]", 256, hex_rows(rows))

    write("gng_sprites.h", emit)
    return 128 * 256 * len(ARENA_SPRITE_BANKS)


def main():
    os.makedirs(OUT, exist_ok=True)
    arena = {
        "sound": convert_cpu(),
        "tiles": convert_tiles(),
        "sprites": convert_sprites(),
        "tune_ram": 0x1540,  # gng.h TUNE_RAM_SIZE, SID $3800-$4D3F
    }
    total = sum(arena.values())
    for name, size in arena.items():
        print(f"  arena {name:9s} {size:6d}")
    convert_chars()
    print(f"  arena total     {total:6d} of 201500")
    if total >= 201500:
        fatal("Ghosts'n Goblins assets exceed Arena::CAPACITY")


if __name__ == "__main__":
    main()
