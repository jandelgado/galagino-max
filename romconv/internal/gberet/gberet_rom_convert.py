#!/usr/bin/env python3
"""Convert the MAME gberet ROM set into galagino headers (MAME konami/gberet.cpp)."""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "pyconv"))
from gfxutil import load_file, mame_decode, rgb888_to_rgb565_le
from asset_emit import emit_compressed

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..", "..")
ZIP = os.path.join(ROOT, "romszip", "gberet.zip")
OUT_DIR = os.path.join(ROOT, "source", "src", "machines", "gberet")

# MAME ROM_START( gberet )
MAIN = [
    ("577l03.10c", "5c66de1403c5df5b6647bb37e26070ffd33590e8"),
    ("577l02.8c", "b76f3789f152198bf8a9a366378d664e683c6c9d"),
    ("577l01.7c", "90d1463e16b0f52c01078be044ce3672d4acebff"),
]
TILES = ("577l07.3f", "54adba9ae086852902d78ab36039498aae50d7a9")
SPRITES = [
    ("577l06.5e", "094004e70c05df8cd486d0854c258fa766e2925d"),
    ("577l05.4e", "5f2bcf2b702fe05f8a022b6284cb2d0a5b5f222f"),
    ("577l08.4f", "b565842edf09feeb2c4ac44ad58331757586b6aa"),
    ("577l04.3e", "cac053cab68cb420edd408ce032143db7abc29f5"),
]
PAL = ("577h09.2f", "c0e8a01e63ed8cf20b33456b68890313b387ad23")
TILE_CLUT = ("577h11.6f", "77cff7c9c8433f999a87776021935864cf9dccb4")
SPR_CLUT = ("577h10.5f", "406b8dfe54e6176082005cc5545e79c098672547")

ARENA_CAPACITY = 182000
ARENA_BLOCK = 91000


def load(entry):
    name, sha1 = entry
    return bytes(load_file(ZIP, [name], sha1))


def step(start, inc, n):
    return [start + i * inc for i in range(n)]


def pack_row(pens):
    v = 0
    for p in pens:
        v = (v << 4) | p
    return v


def decode_tiles(rom):
    # gfx_8x8x4_packed_msb
    tiles = mame_decode(rom, 8, 8, step(0, 1, 4), step(0, 4, 8), step(0, 32, 8), 256, 512)
    return [pack_row(row) for t in tiles for row in t]


def decode_sprites(rom):
    # gfx_8x8x4_row_2x2_group_packed_msb
    xoffs = step(0, 4, 8) + step(256, 4, 8)
    yoffs = step(0, 32, 8) + step(512, 32, 8)
    sprites = mame_decode(rom, 16, 16, step(0, 1, 4), xoffs, yoffs, 1024, 512)
    return [pack_row(row[h * 8:h * 8 + 8]) for s in sprites for row in s for h in range(2)]


def palette(prom):
    def bit(v, n):
        return (v >> n) & 1

    out = []
    for v in prom:
        r = 0x21 * bit(v, 0) + 0x47 * bit(v, 1) + 0x97 * bit(v, 2)
        g = 0x21 * bit(v, 3) + 0x47 * bit(v, 4) + 0x97 * bit(v, 5)
        b = 0x47 * bit(v, 6) + 0x97 * bit(v, 7)
        out.append(rgb888_to_rgb565_le(r, g, b))
    return out


def write_cmap(path, pal, tile_clut, spr_clut):
    def table(f, name, clut, base):
        f.write(f"const unsigned short {name}_cmap[16][16] PROGMEM = {{\n")
        transp = []
        for c in range(16):
            idx = [clut[c * 16 + p] & 0x0f for p in range(16)]
            transp.append(sum(1 << p for p in range(16) if idx[p] == 0))
            f.write("  { " + ", ".join(f"0x{pal[base | i]:04x}" for i in idx) + " },\n")
        f.write("};\n\n")
        f.write(f"// bit p set = pen p transparent (lookup nibble 0)\n")
        f.write(f"const unsigned short {name}_transp[16] PROGMEM = {{ "
                + ", ".join(f"0x{t:04x}" for t in transp) + " };\n\n")

    with open(path, "w", newline="\n") as f:
        f.write("// Generated by romconv/internal/gberet/gberet_rom_convert.py; do not edit.\n")
        f.write("// Green Beret color maps, RGB565 byte-swapped for the SPI display.\n\n")
        f.write("// Characters: 16 colors x 16 pens, lookup 577h11 -> palette 0x10 | nibble\n")
        table(f, "gberet_tile", tile_clut, 0x10)
        f.write("// Sprites: 16 colors x 16 pens, lookup 577h10 -> palette nibble\n")
        table(f, "gberet_spr", spr_clut, 0x00)
    print(f"  wrote {path}")


def emit(name, ctype, dims, count, flat, comment):
    path = os.path.join(OUT_DIR, f"{name}.h")
    with open(path, "w", newline="\n") as out:
        out.write("// Generated by romconv/internal/gberet/gberet_rom_convert.py; do not edit.\n")
        out.write(f"// {comment}\n")
        emit_compressed(out, name, ctype, dims, count, flat)
    print(f"  wrote {path}")


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    rom = b"".join(load(e) for e in MAIN)
    tiles = decode_tiles(load(TILES))
    sprites = decode_sprites(b"".join(load(e) for e in SPRITES))

    emit("gberet_rom", "unsigned char", "", len(rom), list(rom), "Z80 ROM 0x0000-0xbfff")
    emit("gberet_tilemap", "uint32_t", "[8]", 512, tiles,
         "512 chars 8x8 4 bpp, row = 8 pens, pixel 0 in bits 31-28")
    emit("gberet_spritemap", "uint32_t", "[16][2]", 512, sprites,
         "512 sprites 16x16 4 bpp, [row][0] pixels 0-7, [row][1] pixels 8-15, first in bits 31-28")
    write_cmap(os.path.join(OUT_DIR, "gberet_cmap.h"), palette(load(PAL)),
               load(TILE_CLUT), load(SPR_CLUT))

    sizes = {"rom": len(rom), "tilemap": len(tiles) * 4, "spritemap": len(sprites) * 4}
    total = sum(sizes.values())
    print("  Arena budget: " + ", ".join(f"{k} {v}" for k, v in sizes.items())
          + f" = {total} / {ARENA_CAPACITY} bytes")
    assert total < ARENA_CAPACITY
    assert sizes["rom"] + sizes["tilemap"] <= ARENA_BLOCK and sizes["spritemap"] <= ARENA_BLOCK


if __name__ == "__main__":
    main()
