#!/usr/bin/env python3
"""Convert the MAME tempest (Tempest rev 3, revised hardware) ROM set into galagino headers."""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "pyconv"))
from gfxutil import load_file
from asset_emit import emit_compressed

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..", "..")
ARCHIVE = os.path.join(ROOT, "romszip", "tempest.zip")
OUT_DIR = os.path.join(ROOT, "source", "src", "machines", "tempest")

# MAME tempest: name -> SHA1. The AVG state PROM 136002-125.d7 and the
# Mathbox PROMs 136002-126..132 are dropped: display list and Mathbox are
# emulated at a high level.
PROGRAM = [
    ("136002-133.d1", "7bef95db9b1102d6b1166bda0ccb276ef4cc3764"),
    ("136002-134.f1", "89144baf1efc703b2336774793ce345b37829ee7"),
    ("136002-235.j1", "a5f5fb630a48c5d25346f90d4c13aaa98f60b228"),
    ("136002-136.lm1", "73aa7d6f4e7093ccb2d97f6344f354872bcfd72a"),
    ("136002-237.p1", "04be074e45bf5cd95a852af97cd04e35b7f27fc4"),
]
VECTOR = [
    ("136002-138.np3", "2b725ee1a57d423c7d7377a1744f48412e0f2f69"),
]

# dvgMachine::MAX_LINES vec2d::Line (16 B) + StripRasterizer next/active
# (2 x uint16_t per line) + 36 strip heads, allocated in start()
MAX_LINES = 1024
LINE_BUFFER_BYTES = MAX_LINES * 16 + MAX_LINES * 2 * 2 + 36 * 2
# GO list: decode buffer (vec2d::Line per line) and published PackedLine
# (8 B) list (+ 2 B count + 4 B sequence)
GO_LIST_BYTES = MAX_LINES * 16 + MAX_LINES * 8 + 8


def load_all(files):
    return b"".join(bytes(load_file(ARCHIVE, [name], sha1)) for name, sha1 in files)


def write(filename, symbol, data, description):
    path = os.path.join(OUT_DIR, filename)
    with open(path, "w", newline="\n") as out:
        out.write("// Generated by romconv/internal/tempest/tempest_rom_convert.py; do not edit.\n")
        out.write(f"// {description}\n")
        emit_compressed(out, symbol, "unsigned char", "", len(data), list(data))
    print(f"  wrote {path}: {len(data)} bytes")
    return len(data)


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    total = write("tempest_rom.h", "tempest_rom", load_all(PROGRAM),
                  "Main M6502 ROM, 20 KiB mapped at 0x9000-0xdfff; 0xf000-0xffff mirrors 0xd000.")
    total += write("tempest_vrom.h", "tempest_vrom", load_all(VECTOR),
                   "AVG vector ROM, 4 KiB mapped at 0x3000-0x3fff.")
    total += LINE_BUFFER_BYTES + GO_LIST_BYTES
    print(f"  Arena budget: {total} / 182000 bytes")
    if total >= 182000:
        sys.exit("ERROR: Arena budget exceeded")


if __name__ == "__main__":
    main()
