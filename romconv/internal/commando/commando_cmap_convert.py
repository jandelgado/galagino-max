#!/usr/bin/env python3
"""Commando color maps: 256 direct RGB444 colors from vtb1/2/3 (no lookup
PROMs), split per layer as MAME's gfxdecode does:
tiles 0-127 (16 x 8), sprites 128-191 (4 x 16), chars 192-255 (16 x 4).
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "pyconv"))
from asset_emit import emit_compressed
from gfxutil import load_file

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..", "..")
ZIP = os.path.join(ROOT, "romszip", "commando.zip")
OUT = os.path.join(ROOT, "source", "src", "machines", "commando", "commando_cmap.h")

PROMS = [  # red, green, blue
    ("vtb1.1d", "8b057f6e26155dd9e48bde182e680fce4519f600"),
    ("vtb2.2d", "ca6dddca98baf00a65b2fb70b69cf4704ef8c831"),
    ("vtb3.3d", "644ac17c7413f094ec9a15cba87bbd421b26321f"),
]


def rgb565_swapped(r4, g4, b4):
    # same 4 -> 5/6 bit expansion as cmapconv.parse_palette
    rgb = ((r4 << 1) << 11) | ((g4 << 2) << 5) | (b4 << 1)
    return ((rgb & 0xff00) >> 8) | ((rgb & 0xff) << 8)


def main():
    r, g, b = (load_file(ZIP, [name], sha1) for name, sha1 in PROMS)
    pal = [rgb565_swapped(r[i] & 15, g[i] & 15, b[i] & 15) for i in range(256)]
    with open(OUT, "w", newline="\n") as f:
        f.write("// Generated by romconv/internal/commando/commando_cmap_convert.py; do not edit.\n")
        emit_compressed(f, "commando_cmap_tiles", "unsigned short", "[8]", 16, pal[0:128])
        emit_compressed(f, "commando_cmap_sprites", "unsigned short", "[16]", 4, pal[128:192])
        emit_compressed(f, "commando_cmap_chars", "unsigned short", "[4]", 16, pal[192:256])
    print(f"  wrote {OUT}")


if __name__ == "__main__":
    main()
