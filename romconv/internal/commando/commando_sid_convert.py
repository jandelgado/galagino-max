#!/usr/bin/env python3
"""Pack the C64 Commando SID tune (Rob Hubbard, HVSC) into a galagino header.

Test drive only: the dummy commando machine plays it. User supplied, like
ROMs: romszip/Commando.sid from HVSC MUSICIANS/H/Hubbard_Rob/Commando.sid.
"""
import hashlib
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "pyconv"))
from asset_emit import emit_compressed
from convutil import fatal

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..", "..")
SID_FILE = os.path.join(ROOT, "romszip", "Commando.sid")
SID_SHA1 = "8549166918b51bfde88f3f059588c4618dfbfc75"
OUT = os.path.join(ROOT, "source", "src", "machines", "commando", "commando_sid.h")


def main():
    if not os.path.exists(SID_FILE):
        fatal(f"missing {os.path.abspath(SID_FILE)} (HVSC Hubbard_Rob/Commando.sid)")
    with open(SID_FILE, "rb") as f:
        data = f.read()
    if hashlib.sha1(data).hexdigest() != SID_SHA1:
        fatal(f"{SID_FILE}: SHA1 mismatch, expected {SID_SHA1}")

    with open(OUT, "w", newline="\n") as out:
        out.write("// Generated by romconv/internal/commando/commando_sid_convert.py; do not edit.\n")
        out.write("// C64 Commando PSID (Rob Hubbard, 1985 Elite), whole file\n")
        emit_compressed(out, "commando_sid", "unsigned char", "", len(data), list(data))
    print(f"  wrote {OUT}: {len(data)} bytes")


if __name__ == "__main__":
    main()
